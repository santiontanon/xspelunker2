package xspelunker2;

import java.awt.image.BufferedImage;
import java.io.File;
import java.util.ArrayList;
import java.util.List;
import javax.imageio.ImageIO;
import util.Z80Assembler;
import util.ZX0Wrapper;

/**
 *
 * @author santi
 */
public class Story {
    public static void main(String args[]) throws Exception
    {
        // Extract the tiles:
        BufferedImage img = ImageIO.read(new File("data/story.png"));
        int[][] nametable = Map.extractUniqueTiles(img, "data/story.png", "data/story-tiles.png", 0, 24);
        GenerateTiles.extractAllTiles("data/story-tiles.png", "src/autogenerated/story-tiles");
        
        // Extract the name tables of all the frames:
        {
            int nametable2[] = new int[16*12];
            for(int i = 0;i<12;i++) {
                for(int j = 0;j<16;j++) {
                    nametable2[j + i*16] = nametable[j][i];
                }
            }
            // remove the talk bubble
            for(int i = 5;i<9;i++) {
                for(int j = 3;j<16;j++) {
                    nametable2[j + i*16] = 0;
                }
            }
            Z80Assembler.dataToBinary(nametable2, "src/autogenerated/story-nametable.bin");        
        }
        {
            int nametable2[] = new int[12*4];
            for(int i = 5;i<9;i++) {
                for(int j = 3;j<15;j++) {
                    nametable2[(j-3) + (i-5)*12] = nametable[j][i];
                }
            }
            // text tiles:
            for(int i = 0;i<10;i++) {
                nametable2[1 + 12 + i] = 128 + i;
                nametable2[1 + 24 + i] = 128 + 10 + i;
            }
            Z80Assembler.dataToBinary(nametable2, "src/autogenerated/story-bubble-nametable.bin");        
        }
        {
            int x[] = {0, 6, 0, 6, 0, 6};
            int y[] = {13, 13, 17, 17, 21, 21};
            for(int k = 0;k<6;k++) {
                int nametable2[] = new int[3*3];
                for(int i = y[k];i<y[k] + 3;i++) {
                    for(int j = x[k];j<x[k] + 3;j++) {
                        nametable2[(j-x[k]) + (i-y[k])*3] = nametable[j][i];
                    }
                }
                Z80Assembler.dataToBinary(nametable2, "src/autogenerated/story-nametable-frame"+(k+1)+".bin");
            }
        }
        {
            int nametable2[] = new int[3*10];
            for(int i = 0;i<10;i++) {
                for(int j = 16;j<19;j++) {
                    nametable2[j - 16 + i*3] = nametable[j][i];
                }
            }
            Z80Assembler.dataToBinary(nametable2, "src/autogenerated/story-nametable-artifact1.bin");        
        }
        {
            int nametable2[] = new int[3*5];
            for(int i = 0;i<5;i++) {
                for(int j = 19;j<22;j++) {
                    nametable2[j - 19 + i*3] = nametable[j][i];
                }
            }
            Z80Assembler.dataToBinary(nametable2, "src/autogenerated/story-nametable-artifact2a.bin");        
        }
        {
            int nametable2[] = new int[3*7];
            for(int i = 5;i<12;i++) {
                for(int j = 19;j<22;j++) {
                    nametable2[j - 19 + (i - 5)*3] = nametable[j][i];
                }
            }
            Z80Assembler.dataToBinary(nametable2, "src/autogenerated/story-nametable-artifact2b.bin");        
        }
        {
            int nametable2[] = new int[6*4];
            for(int i = 0;i<4;i++) {
                for(int j = 22;j<28;j++) {
                    nametable2[j - 22 + i*6] = nametable[j][i];
                }
            }
            Z80Assembler.dataToBinary(nametable2, "src/autogenerated/story-nametable-hand.bin");        
        }
        
        // sprites:
        List<Integer> data = new ArrayList<>();
        
        // common sprites to all areas:
        data.addAll(GenerateSprites.extractSprite(img, 64, 192, 10));  // Xavier walking
        data.addAll(GenerateSprites.extractSprite(img, 64, 192, 6));
        data.addAll(GenerateSprites.extractSprite(img, 64, 208, 10));
        data.addAll(GenerateSprites.extractSprite(img, 64, 208, 6));
        data.addAll(GenerateSprites.extractSprite(img, 48, 192, 10));  // Xavier standing
        data.addAll(GenerateSprites.extractSprite(img, 48, 192, 6));
        data.addAll(GenerateSprites.extractSprite(img, 48, 208, 10));
        data.addAll(GenerateSprites.extractSprite(img, 48, 208, 6));
        data.addAll(GenerateSprites.extractSprite(img, 32, 192, 10));  // Xavier holding item
        data.addAll(GenerateSprites.extractSprite(img, 32, 192, 6));

        data.addAll(GenerateSprites.extractSprite(img, 0, 192, 10));  // Elaine standing
        data.addAll(GenerateSprites.extractSprite(img, 0, 192, 9));
        data.addAll(GenerateSprites.extractSprite(img, 0, 208, 10));
        data.addAll(GenerateSprites.extractSprite(img, 0, 208, 9));
        data.addAll(GenerateSprites.extractSprite(img, 16, 192, 10));  // Elaine holding item
        data.addAll(GenerateSprites.extractSprite(img, 16, 192, 9));
        Z80Assembler.dataToBinary(data, "src/autogenerated/story-sprites.bin");
        ZX0Wrapper.main("src/autogenerated/story-sprites.bin",
                        "src/autogenerated/story-sprites.zx0", true, false);
    }
}
