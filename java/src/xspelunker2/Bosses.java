    public static void addNameTable(int nameTable[][], int x1, int y1, int x2, int y2, List<Integer> data)
    {
        for(int i = y1;i<y2;i++) {
            for(int j = x1; j<x2; j++) {
                data.add(nameTable[j][i]);
            }
        }
    }


