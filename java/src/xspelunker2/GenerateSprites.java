package xspelunker2;

import java.awt.image.BufferedImage;
import java.io.File;
import java.util.ArrayList;
import java.util.List;
import javax.imageio.ImageIO;
import util.ConvertPatternsToAssembler;
import util.Z80Assembler;

/**
 *
 * @author santi
 */
public class GenerateSprites {
    public static int TOLERANCE = 0;


    public static void main(String args[]) throws Exception
    {
        extractPlayerSprites("src/autogenerated/player-sprites");
    }

    
    private static void extractPlayerSprites(String outputPath) throws Exception
    {
        BufferedImage sourceImage = ImageIO.read(new File("data/player.png"));
        List<Integer> data = new ArrayList<>();
        List<Integer> dataLeft = new ArrayList<>();
        
        // Standing right:
        addPlayerFrame(sourceImage, 0, 0, data, dataLeft);
        addPlayerFrame(sourceImage, 0, 16, data, dataLeft);
        // Walk:
        addPlayerFrame(sourceImage, 16, 0, data, dataLeft);
        addPlayerFrame(sourceImage, 32, 0, data, dataLeft);
        // Crawl:
        addPlayerFrame(sourceImage, 16, 16, data, dataLeft);
        addPlayerFrame(sourceImage, 32, 16, data, dataLeft);
        
        System.out.println("data: " + data.size());
        System.out.println("dataLeft: " + dataLeft.size());
        Z80Assembler.dataToBinary(data, outputPath + ".bin");        
        Z80Assembler.dataToBinary(dataLeft, outputPath + "-left.bin");
    }
    
    
    private static void addPlayerFrame(BufferedImage sourceImage, int x, int y,
                                       List<Integer> data, List<Integer> dataLeft)
    {
        data.addAll(extractSprite(sourceImage, x, y, 10));  // dark yellow
        data.addAll(extractSprite(sourceImage, x, y, 6));  // dark red

        dataLeft.addAll(extractSpriteFlipped(sourceImage, x, y, 10));  // dark yellow
        dataLeft.addAll(extractSpriteFlipped(sourceImage, x, y, 6));  // dark red
    }

    
    public static List<Integer> extractSprite(BufferedImage img, int x, int y, int color)
    {
        List<Integer> data = new ArrayList<>();
        
        for(int j = 0;j<16;j+=8) {
            for(int i = 0;i<16;i++) {
                int value = 0;
                for(int k = 0;k<8;k++) {
                    value *= 2;
                    int pixel = ConvertPatternsToAssembler.findMSXColor(x + j + k, y + i, img, TOLERANCE);
                    if (pixel == color) {
                        value |= 1;
                    }
                }
                data.add(value);
            }
        }
        
        return data;
    }
    
    
    public static List<Integer> extractSpriteFlipped(BufferedImage img, int x, int y, int color)
    {
        List<Integer> data = new ArrayList<>();
        
        for(int j = 8;j>=0;j-=8) {
            for(int i = 0;i<16;i++) {
                int value = 0;
                for(int k = 7;k>=0;k--) {
                    value *= 2;
                    int pixel = ConvertPatternsToAssembler.findMSXColor(x + j + k, y + i, img, TOLERANCE);
                    if (pixel == color) {
                        value |= 1;
                    }
                }
                data.add(value);
            }
        }
        
        return data;
    }    
}
