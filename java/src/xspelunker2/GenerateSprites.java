    public static void addPlayerFrame(BufferedImage sourceImage, int x, int y,
                                       List<Integer> data, List<Integer> dataLeft)
    {
        data.addAll(extractSprite(sourceImage, x, y, 10));  // dark yellow
        data.addAll(extractSprite(sourceImage, x, y, 6));  // dark red

        dataLeft.addAll(extractSpriteFlipped(sourceImage, x, y, 10));  // dark yellow
        dataLeft.addAll(extractSpriteFlipped(sourceImage, x, y, 6));  // dark red
    }

    
    public static void addWeaponSprite(BufferedImage sourceImage, int x, int y,
                                       List<Integer> data, List<Integer> dataLeft)
    {
        data.addAll(extractSprite(sourceImage, x, y, 15));

        dataLeft.addAll(extractSpriteFlipped(sourceImage, x, y, 15));
    }

    
    public static List<Integer> extractSprite(BufferedImage img, int x, int y, int color)
    {
        List<Integer> data = new ArrayList<>();
        
        for(int j = 0;j<16;j+=8) {
            for(int i = 0;i<16;i++) {
                int value = 0;
                for(int k = 0;k<8;k++) {
                    value *= 2;
                    int pixel = ConvertPatternsToAssembler.findMSXColor(x + j + k, y + i, img, TOLERANCE);
                    if (pixel == color) {
                        value |= 1;
                    }
                }
                data.add(value);
            }
        }
        
        return data;
    }
    
    
    public static List<Integer> extractSpriteFlipped(BufferedImage img, int x, int y, int color)
    {
        List<Integer> data = new ArrayList<>();
        
        for(int j = 8;j>=0;j-=8) {
            for(int i = 0;i<16;i++) {
                int value = 0;
                for(int k = 7;k>=0;k--) {
                    value *= 2;
                    int pixel = ConvertPatternsToAssembler.findMSXColor(x + j + k, y + i, img, TOLERANCE);
                    if (pixel == color) {
                        value |= 1;
                    }
                }
                data.add(value);
            }
        }
        
        return data;
    }    
