    public static void extractTilesMarsRobotPuzzle(String pngPath, String outputPngPath, String outputPath) throws Exception
    {
        List<List<Integer>> tiles = new ArrayList<>();
        // start with the empty tile:
        List<Integer> tile = new ArrayList<>();
        for(int i = 0;i<8*8;i++) tile.add(0);
        tiles.add(tile);        
        int[][] nametable1 = extractUniqueTilesData(pngPath, tiles, 12, 0, 18, 5);
        int[][] nametable2 = extractUniqueTilesData(pngPath, tiles, 18, 0, 32, 18);

        // Generate an image with the different tiles:
        BufferedImage outputImage = new BufferedImage(128, 128, BufferedImage.TYPE_3BYTE_BGR);
        {
            int x = 0, y = 0;
            for(List<Integer> tile2:tiles) {
                for(int i = 0;i<8;i++) {
                    for(int j = 0;j<8;j++) {
                        outputImage.setRGB(x + j, y + i, ConvertPatternsToAssembler.MSXColorToRGB(tile2.get(j+i*8)));
                    }
                }
                x += 8;
                if (x >= 128) {
                    x = 0;
                    y += 8;
                }
            }
        }
        
        ImageIO.write(outputImage, "png", new File(outputPngPath));
        GenerateTiles.extractTiles(outputPngPath, outputPath + "-tiles", 0, 128);
        
        // name table data:
        List<Integer> data = new ArrayList<Integer>();
        for(int i = 0;i<5;i++) {
            for(int j = 1;j<6;j++) {
                data.add(nametable1[j][i]);
            }
        }
        for(int i = 0;i<3;i++) {
            for(int j = 0;j<2;j++) {
                for(int i2 = 0;i2<6;i2++) {
                    for(int j2 = 0;j2<7;j2++) {
                        data.add(nametable2[j*7+j2][i*6+i2]);
                    }
                }
            }
        }

        Z80Assembler.dataToBinary(data, outputPath + "-nametables.bin");
    }
    
    
