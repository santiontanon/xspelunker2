package xspelunker2;

import java.awt.image.BufferedImage;
import java.io.File;
import java.util.ArrayList;
import java.util.List;
import javax.imageio.ImageIO;
import util.ConvertPatternsToAssembler;
import util.Z80Assembler;
import util.ZX0Wrapper;

/**
 *
 * @author santi
 */
public class GenerateTiles {
    public static void main(String args[]) throws Exception
    {
        extractTiles("data/patterns/tiles.png", "src/autogenerated/tiles-hud", 0, 32);
        extractTiles("data/patterns/tiles.png", "src/autogenerated/tiles-pyramid", 32, 128);
        extractAllTiles("data/animations-pyramid.png", "src/autogenerated/animations-pyramid");
        extractHudWeaponTiles("data/weapons-hud.png", "src/autogenerated/weapons-hud");
        extractTilesObjects("data/objects.png", "src/autogenerated/tiles-objects");
    }
    
    
    public static void extractAllTiles(String pngPath, String outputPath) throws Exception
    {
        extractTiles(pngPath, outputPath, 0, 0);
    }

    
    public static void extractTiles(String pngPath, String outputPath, int y1, int y2) throws Exception
    {
        List<Integer> bitmap_data = new ArrayList<>();
        List<Integer> color_data = new ArrayList<>();
        BufferedImage sourceImage = ImageIO.read(new File(pngPath));
        if (y2 == 0) {
            y2 = sourceImage.getHeight();
        }
        y1 /= 8;
        y2 /= 8;
        for(int i = y1;i<y2;i++) {
            for(int j = 0;j<sourceImage.getWidth()/8;j++) {
                List<Integer> pattern = ConvertPatternsToAssembler.generateAssemblerPatternBitmap(j, i, sourceImage, 0);
                List<Integer> attributes = ConvertPatternsToAssembler.generateAssemblerPatternAttributes(j, i, sourceImage, 0);
                bitmap_data.addAll(pattern);
                color_data.addAll(attributes);
            }
        }
        
        List<Integer> data = new ArrayList<>();
        data.addAll(bitmap_data);
        data.addAll(color_data);
        Z80Assembler.dataToBinary(data, outputPath + ".bin");
        ZX0Wrapper.main(outputPath+".bin", outputPath+".zx0", true, false);
    }


    public static void extractHudWeaponTiles(String pngPath, String outputPath) throws Exception
    {
        List<Integer> data = new ArrayList<>();
        List<Integer> bitmap_data = new ArrayList<>();
        List<Integer> color_data = new ArrayList<>();
        BufferedImage sourceImage = ImageIO.read(new File(pngPath));
        for(int i = 0;i<sourceImage.getHeight()/8;i++) {
            for(int j = 0;j<sourceImage.getWidth()/8;j++) {
                List<Integer> pattern = ConvertPatternsToAssembler.generateAssemblerPatternBitmap(j, i, sourceImage, 0);
                List<Integer> attributes = ConvertPatternsToAssembler.generateAssemblerPatternAttributes(j, i, sourceImage, 0);
                bitmap_data.addAll(pattern);
                color_data.addAll(attributes);
            }
            // collate bitmap and color data, so we have all the data for one weapon togetner:
            if ((i % 2) == 1) {
                data.addAll(bitmap_data);
                data.addAll(color_data);
                bitmap_data.clear();
                color_data.clear();
            }
        }
        
        Z80Assembler.dataToBinary(data, outputPath + ".bin");
        ZX0Wrapper.main(outputPath+".bin", outputPath+".zx0", true, false);
    }
    
    
    public static void extractTilesObjects(String pngPath, String outputPath) throws Exception
    {
        BufferedImage sourceImage = ImageIO.read(new File(pngPath));
        List<Integer> data = new ArrayList<>();

        // boss keys (0, ... ,6)
        extratTilesOneObject(sourceImage, 16, 0, 16, 16, data);
        extratTilesOneObject(sourceImage, 32, 0, 16, 16, data);
        extratTilesOneObject(sourceImage, 48, 0, 16, 16, data);
        extratTilesOneObject(sourceImage, 64, 0, 16, 16, data);
        extratTilesOneObject(sourceImage, 80, 0, 16, 16, data);
        extratTilesOneObject(sourceImage, 96, 0, 16, 16, data);
        extratTilesOneObject(sourceImage, 112, 0, 16, 16, data);
        // boss lock (7)
        extratTilesOneObject(sourceImage, 192, 48, 16, 16, data);
        
        Z80Assembler.dataToBinary(data, outputPath + ".bin");
        ZX0Wrapper.main(outputPath+".bin", outputPath+".zx0", true, false);
    }    
    
    
    public static void extratTilesOneObject(BufferedImage sourceImage, int x1, int y1, int width, int height, List<Integer> data) throws Exception
    {
        List<Integer> bitmap_data = new ArrayList<>();
        List<Integer> color_data = new ArrayList<>();
        x1 /= 8;
        y1 /= 8;
        width /= 8;
        height /= 8;
        for(int i = y1;i<y1 + height;i++) {
            for(int j = x1;j<x1 + width;j++) {
                List<Integer> pattern = ConvertPatternsToAssembler.generateAssemblerPatternBitmap(j, i, sourceImage, 0);
                List<Integer> attributes = ConvertPatternsToAssembler.generateAssemblerPatternAttributes(j, i, sourceImage, 0);
                bitmap_data.addAll(pattern);
                color_data.addAll(attributes);
            }
        }
        data.addAll(bitmap_data);
        data.addAll(color_data);
    }    
}
