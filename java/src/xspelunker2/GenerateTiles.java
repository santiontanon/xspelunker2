    public static int[][] extractUniqueTilesData(String inputPath, List<List<Integer>> tiles, int x1, int y1, int x2, int y2) throws Exception
    {
        BufferedImage sourceImage = ImageIO.read(new File(inputPath));
        List<Integer> tile;
        int width = x2 - x1;
        int height = y2 - y1;
        int nameTable[][] = new int[width][height];
        
        for(int i = y1*8;i<y2*8;i+=8) {
            for(int j = x1*8;j<x2*8;j+=8) {
                tile = new ArrayList<>();
                // System.out.println(j + "," + i + "(" + sourceImage.getWidth() + ", " + sourceImage.getHeight() + ")");
                for(int ii = 0;ii<8;ii++) {
                    for(int jj = 0;jj<8;jj++) {
                        int color = ConvertPatternsToAssembler.findMSXColor(j+jj, i+ii, sourceImage, 0);
                        if (color == -1) throw new Exception("Unknown color at " + (j+jj) + ", " + (i+ii));
                        tile.add(color);
                    }
                }

                int found = -1;
                for(int tileIndex = 0;tileIndex<tiles.size();tileIndex++) {
                    List<Integer> tile2 = tiles.get(tileIndex);
                    boolean match = true;
                    for(int k = 0;k<8*8;k++) {
                        if (!tile.get(k).equals(tile2.get(k))) {
                            match = false;
                            break;
                        }
                    }
                    if (match) {
                        found = tileIndex;
                        break;
                    }
                }
                if (found == -1) {
                    nameTable[j/8 - x1][(i/8)-y1] = tiles.size();
                    tiles.add(tile);
                } else {
                    nameTable[j/8 - x1][(i/8)-y1] = found;
                }
            }
        }
        System.out.println("Different tiles after " + inputPath + ": " + tiles.size());
                
        return nameTable;
    }    

