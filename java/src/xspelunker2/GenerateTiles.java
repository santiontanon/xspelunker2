    public static void extratTilesOneObject(BufferedImage sourceImage, int x1, int y1, int width, int height, List<Integer> data) throws Exception
    {
        List<Integer> bitmap_data = new ArrayList<>();
        List<Integer> color_data = new ArrayList<>();
        x1 /= 8;
        y1 /= 8;
        width /= 8;
        height /= 8;
        for(int i = y1;i<y1 + height;i++) {
            for(int j = x1;j<x1 + width;j++) {
                List<Integer> pattern = ConvertPatternsToAssembler.generateAssemblerPatternBitmap(j, i, sourceImage, 0);
                List<Integer> attributes = ConvertPatternsToAssembler.generateAssemblerPatternAttributes(j, i, sourceImage, 0);
                bitmap_data.addAll(pattern);
                color_data.addAll(attributes);
            }
        }
        data.addAll(bitmap_data);
        data.addAll(color_data);
    }
    
    
    public static void extractPowerStoneTiles(String tilesFileName, String tmxfileName, String outputPrefix) throws Exception
    {
        extractAllTiles(tilesFileName, outputPrefix + "-tiles");
        
        int tiles[][] = Tiled.loadTMXtileData(tmxfileName);
        List<Integer> data = new ArrayList<>();
        for(int i = 0;i<tiles[0].length;i++) {
            for(int j = 0;j<tiles.length;j++) {
                data.add(tiles[j][i]);
            }
        }        
        String outputPath = outputPrefix + "-nametable";
        Z80Assembler.dataToBinary(data, outputPath + ".bin");
        ZX0Wrapper.main(outputPath+".bin", outputPath+".zx0", true, false);
    }


