package xspelunker2;

import java.awt.image.BufferedImage;
import java.io.File;
import java.util.ArrayList;
import java.util.List;
import javax.imageio.ImageIO;
import util.ConvertPatternsToAssembler;
import util.Tiled;
import util.Z80Assembler;
import util.ZX0Wrapper;
import static xspelunker2.GenerateSprites.TOLERANCE;

/**
 *
 * @author santi
 */
public class Title {
    public static void main(String args[]) throws Exception
    {
        BufferedImage titleImage = ImageIO.read(new File("data/title.png"));
        
        // Get sprites:
        {
            List<Integer> data = new ArrayList<>();

            data.addAll(GenerateSprites.extractSprite(titleImage, 8, 32, 15));
            data.addAll(GenerateSprites.extractSprite(titleImage, 32, 32, 15));
            data.addAll(GenerateSprites.extractSprite(titleImage, 80, 32, 15));
            data.addAll(GenerateSprites.extractSprite(titleImage, 112, 32, 15));

            data.addAll(GenerateSprites.extractSprite(titleImage, 8, 48, 15));
            data.addAll(GenerateSprites.extractSprite(titleImage, 32, 48, 15));
            data.addAll(GenerateSprites.extractSprite(titleImage, 112, 48, 15));
            data.addAll(GenerateSprites.extractSprite(titleImage, 144, 48, 15));
        
            System.out.println("title sprites: " + data.size());
            String path = "src/autogenerated/title-sprites";
            Z80Assembler.dataToBinary(data, path + ".bin");        
            ZX0Wrapper.main(path+".bin", path+".zx0", true, false);
        }
        
        // Replace the white pixels by dark blue oens:
        for(int i = 0;i<titleImage.getHeight();i++) {
            for(int j = 0;j<titleImage.getWidth();j++) {
                int pixel = ConvertPatternsToAssembler.findMSXColor(j, i, titleImage, TOLERANCE);
                if (pixel == 15) {
                    titleImage.setRGB(j, i, ConvertPatternsToAssembler.MSXColorToRGB(5));
                }
            }
        }
        
        // Extract tiles:
        {
            int[][] nametable = Map.extractUniqueTiles(titleImage, "data/title.png", "data/title-tiles.png", 0, 11);
            GenerateTiles.extractAllTiles("data/title-tiles.png", "src/autogenerated/title-tiles");
            List<Integer> data = new ArrayList<>();
            for(int i = 0;i<nametable[0].length;i++) {
                for(int j = 0;j<nametable.length;j++) {
                    data.add(nametable[j][i]);
                }
            }
            Z80Assembler.dataToBinary(data, "src/autogenerated/title-nametable.bin");        
        }
        
        // Game Start screen:
        {
            GenerateTiles.extractAllTiles("data/gamestart-tiles.png", "src/autogenerated/gamestart-tiles");
            
            String tmxPath = "data/gamestart.tmx";
            String outputPath = "src/autogenerated/gamestart-nametable";
            int nameTable[][] = Tiled.loadTMXtileData(tmxPath);
            List<Integer> data = new ArrayList<>();
            for(int i = 0;i<24;i++) {
                for(int j = 0;j<32;j++) {
                    data.add(nameTable[j][i]);
                }
            }

            Z80Assembler.dataToBinary(data, outputPath + ".bin");
            ZX0Wrapper.main(outputPath+".bin", outputPath+".zx0", true, false);
        }

        generateSpriteData("data/inventory-sprites.png", "src/autogenerated/gamestart-sprites");
    }
    
    
    public static void generateSpriteData(String path, String outputPath) throws Exception
    {
        BufferedImage sourceImage = ImageIO.read(new File(path));
        List<Integer> data = new ArrayList<>();
        
        data.addAll(GenerateSprites.extractSprite(sourceImage, 0, 0, 15));  // left bracket
        data.addAll(GenerateSprites.extractSprite(sourceImage, 16, 0, 15));  // right bracket
        data.addAll(GenerateSprites.extractSprite(sourceImage, 32, 0, 15));  // text pointer
        
        System.out.println("sprite data: " + data.size());
        Z80Assembler.dataToBinary(data, outputPath + ".bin");                
    }    
}
