package xspelunker2;

import java.awt.image.BufferedImage;
import java.io.File;
import java.io.FileWriter;
import java.util.ArrayList;
import java.util.List;
import javax.imageio.ImageIO;
import util.ConvertPatternsToAssembler;
import util.Tiled;
import util.Z80Assembler;
import util.ZX0Wrapper;

/**
 *
 * @author santi
 */
public class Inventory {
    public static void main(String args[]) throws Exception
    {
        String tilesPath = "data/inventory-tiles.png";
        String tmxPath = "data/inventory.tmx";
        String spritesPath = "data/inventory-sprites.png";
        
        extractTiles(tilesPath, 0, 8, "src/autogenerated/inventory-tiles-bank0");
        extractTiles(tilesPath, 8, 16, "src/autogenerated/inventory-tiles-bank1");
        extractTiles(tilesPath, 16, 24, "src/autogenerated/inventory-tiles-bank2");
        
        generateTileData(tmxPath, "src/autogenerated/inventory-nametable");
        generateSpriteData(spritesPath, "src/autogenerated/inventory-sprites");
    }
    
    
    public static void generateSpriteData(String path, String outputPath) throws Exception
    {
        BufferedImage sourceImage = ImageIO.read(new File(path));
        List<Integer> data = new ArrayList<>();
        
        data.addAll(GenerateSprites.extractSprite(sourceImage, 0, 0, 15));  // left bracket
        data.addAll(GenerateSprites.extractSprite(sourceImage, 16, 0, 15));  // right bracket

        data.addAll(GenerateSprites.extractSprite(sourceImage, 0, 16, 15));  // hammer
        data.addAll(GenerateSprites.extractSprite(sourceImage, 16, 16, 15));  // macuahuitl
        data.addAll(GenerateSprites.extractSprite(sourceImage, 32, 16, 15));  // blowgun

        data.addAll(GenerateSprites.extractSprite(sourceImage, 48, 16, 15));  // selected weapon up
        data.addAll(GenerateSprites.extractSprite(sourceImage, 64, 16, 15));  // selected weapon down
        
        System.out.println("sprite data: " + data.size());
        Z80Assembler.dataToBinary(data, outputPath + ".bin");        
        
    }
    
    
    public static void generateTileData(String tmxPath, String outputPath) throws Exception
    {
        int tiles[][] = Tiled.loadTMXtileData(tmxPath);
        List<Integer> data = new ArrayList<>();
        // Verify all tiles are correct:
        for(int i = 0;i<24;i++) {
            for(int j = 0;j<32;j++) {
                if (i<8) {
                    if (tiles[j][i] > 255) {
                        throw new Exception("Wrong tile at " + j + ", + i");
                    }
                    data.add(tiles[j][i]);
                } else if (i<16) {
                    if (tiles[j][i] < 256 || tiles[j][i] > 511) {
                        throw new Exception("Wrong tile at " + j + ", " + i);
                    }
                    data.add(tiles[j][i] - 256);
                } else {
                    if (tiles[j][i] < 512) {
                        throw new Exception("Wrong tile at " + j + ", + i");
                    }
                    data.add(tiles[j][i] - 512);
                }
            }
        }
        
        FileWriter fw = new FileWriter(outputPath + ".asm");
        Z80Assembler.dataBlockToAssembler(data, "inventory_name_table", fw, 32);
        fw.flush();
        fw.close();
        
        Z80Assembler.dataToBinary(data, outputPath + ".bin");
        ZX0Wrapper.main(outputPath+".bin", outputPath+".zx0", true, false);
    }


    public static void extractTiles(String pngPath, int firstRow, int lastRow, String outputPath) throws Exception
    {
        List<Integer> bitmap_data = new ArrayList<>();
        List<Integer> color_data = new ArrayList<>();
        BufferedImage sourceImage = ImageIO.read(new File(pngPath));
        for(int i = firstRow;i<lastRow;i++) {
            for(int j = 0;j<sourceImage.getWidth()/8;j++) {
                List<Integer> pattern = ConvertPatternsToAssembler.generateAssemblerPatternBitmap(j, i, sourceImage, 0);
                List<Integer> attributes = ConvertPatternsToAssembler.generateAssemblerPatternAttributes(j, i, sourceImage, 0);
                bitmap_data.addAll(pattern);
                color_data.addAll(attributes);
            }
        }
        
        List<Integer> data = new ArrayList<>();
        data.addAll(bitmap_data);
        data.addAll(color_data);
        Z80Assembler.dataToBinary(data, outputPath + ".bin");
        ZX0Wrapper.main(outputPath+".bin", outputPath+".zx0", true, false);
    }
    
}
