    public static void generateTileData(String tmxPath, String outputPath) throws Exception
    {
        int tiles[][] = Tiled.loadTMXtileData(tmxPath);
        List<Integer> data = new ArrayList<>();
        // Verify all tiles are correct:
        for(int i = 0;i<tiles[0].length;i++) {
            for(int j = 0;j<tiles.length;j++) {
                data.add(tiles[j][i]);
            }
        }
        
        FileWriter fw = new FileWriter(outputPath + ".asm");
        Z80Assembler.dataBlockToAssembler(data, "name_table", fw, tiles.length);
        fw.flush();
        fw.close();
        
        Z80Assembler.dataToBinary(data, outputPath + ".bin");
        ZX0Wrapper.main(outputPath+".bin", outputPath+".zx0", true, false);
    }
    
    
    public static BufferedImage extractUniqueTiles(String inputPaths[], String outputPath) throws Exception
    {
        List<List<Integer>> tiles = new ArrayList<>();
        
        List<Integer> tile = new ArrayList<>();
        
        // start with the empty tile:
        for(int i = 0;i<8*8;i++) tile.add(0);
        tiles.add(tile);

        for(String inputPath:inputPaths) {
            BufferedImage sourceImage = ImageIO.read(new File(inputPath));
            for(int i = 0;i<sourceImage.getHeight();i+=8) {
                for(int j = 0;j<sourceImage.getWidth();j+=8) {
                    tile = new ArrayList<>();
                    for(int ii = 0;ii<8;ii++) {
                        for(int jj = 0;jj<8;jj++) {
                            int color = ConvertPatternsToAssembler.findMSXColor(j+jj, i+ii, sourceImage, 0);
                            if (color == -1) throw new Exception("Unknown color at " + (j+jj) + ", " + (i+ii));
                            tile.add(color);
                        }
                    }

                    boolean found = false;
                    for(List<Integer> tile2:tiles) {
                        boolean match = true;
                        for(int k = 0;k<8*8;k++) {
                            if (!tile.get(k).equals(tile2.get(k))) {
                                match = false;
                                break;
                            }
                        }
                        if (match) {
                            found = true;
                            break;
                        }
                    }
                    if (!found) {
                        tiles.add(tile);
                    }
                }
            }
            System.out.println("Different tiles after " + inputPath + ": " + tiles.size());
        }
        
        // Generate an image with the different tiles:
        BufferedImage outputImage = new BufferedImage(128, 128, BufferedImage.TYPE_3BYTE_BGR);
        {
            int x = 0, y = 0;
            for(List<Integer> tile2:tiles) {
                for(int i = 0;i<8;i++) {
                    for(int j = 0;j<8;j++) {
                        outputImage.setRGB(x + j, y + i, ConvertPatternsToAssembler.MSXColorToRGB(tile2.get(j+i*8)));
                    }
                }
                x += 8;
                if (x >= 128) {
                    x = 0;
                    y += 8;
                }
            }
        }
        
        
        ImageIO.write(outputImage, "png", new File(outputPath));
        
        return outputImage;
    }
    
