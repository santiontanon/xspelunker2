    public static Pair<BufferedImage, int[][]> extractUniqueTiles(String inputPath, String outputPath, int firstRow, int lastRow) throws Exception
    {
        BufferedImage img = ImageIO.read(new File(inputPath));
        return new Pair<>(img, extractUniqueTiles(img, inputPath, outputPath, firstRow, lastRow));
    }
 
    
    public static int[][] extractUniqueTiles(BufferedImage sourceImage, String inputPath, String outputPath, int firstRow, int lastRow) throws Exception
    {
        List<List<Integer>> tiles = new ArrayList<>();
        List<Integer> tile = new ArrayList<>();
        int nameTable[][] = new int[sourceImage.getWidth()/8][lastRow-firstRow];
        
        // start with the empty tile:
        for(int i = 0;i<8*8;i++) tile.add(0);
        tiles.add(tile);

        for(int i = firstRow*8;i<lastRow*8;i+=8) {
            for(int j = 0;j<sourceImage.getWidth();j+=8) {
                tile = new ArrayList<>();
                for(int ii = 0;ii<8;ii++) {
                    for(int jj = 0;jj<8;jj++) {
                        int color = ConvertPatternsToAssembler.findMSXColor(j+jj, i+ii, sourceImage, 0);
                        if (color == -1) throw new Exception("Unknown color at " + (j+jj) + ", " + (i+ii));
                        tile.add(color);
                    }
                }

                int found = -1;
                for(int tileIndex = 0;tileIndex<tiles.size();tileIndex++) {
                    List<Integer> tile2 = tiles.get(tileIndex);
                    boolean match = true;
                    for(int k = 0;k<8*8;k++) {
                        if (!tile.get(k).equals(tile2.get(k))) {
                            match = false;
                            break;
                        }
                    }
                    if (match) {
                        found = tileIndex;
                        break;
                    }
                }
                if (found == -1) {
                    nameTable[j/8][(i/8)-firstRow] = tiles.size();
                    tiles.add(tile);
                } else {
                    nameTable[j/8][(i/8)-firstRow] = found;
                }
            }
        }
        System.out.println("Different tiles after " + inputPath + ": " + tiles.size());
        
        // Generate an image with the different tiles:
        BufferedImage outputImage = new BufferedImage(128, 128, BufferedImage.TYPE_3BYTE_BGR);
        {
            int x = 0, y = 0;
            for(List<Integer> tile2:tiles) {
                for(int i = 0;i<8;i++) {
                    for(int j = 0;j<8;j++) {
                        outputImage.setRGB(x + j, y + i, ConvertPatternsToAssembler.MSXColorToRGB(tile2.get(j+i*8)));
                    }
                }
                x += 8;
                if (x >= 128) {
                    x = 0;
                    y += 8;
                }
            }
        }
        
        ImageIO.write(outputImage, "png", new File(outputPath));
        
        return nameTable;
    }
