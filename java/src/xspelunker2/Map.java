    public static int[][] newMapNameTable(int w, int h)
    {
        int nt[][] = new int[w][h];
        for(int i = 0;i<h;i++) {
            for(int j = 0;j<w;j++) {
                nt[j][i] = 0;
            }
        }
        return nt;
    }
    
    
    public static void addMapTablePiece(int nt[][], int source[][], int x, int y, int sx1, int sy1, int sx2, int sy2)
    {
        for(int i = sy1;i<sy2;i++) {
            for(int j = sx1;j<sx2;j++) {
                nt[x + (j-sx1)][y + (i-sy1)] = source[j][i];
            }
        }
    }
    
    
    public static void saveNameTable(int tiles[][], String outputPath) throws Exception
    {
        List<Integer> data = new ArrayList<>();
        // Verify all tiles are correct:
        for(int i = 0;i<tiles[0].length;i++) {
            for(int j = 0;j<tiles.length;j++) {
                data.add(tiles[j][i]);
            }
        }
        
        FileWriter fw = new FileWriter(outputPath + ".asm");
        Z80Assembler.dataBlockToAssembler(data, "name_table", fw, tiles.length);
        fw.flush();
        fw.close();
        
        Z80Assembler.dataToBinary(data, outputPath + ".bin");
        ZX0Wrapper.main(outputPath+".bin", outputPath+".zx0", true, false);        
    }
    
    
