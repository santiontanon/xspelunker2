    public static void encodeChunksInBanks(List<RoomChunk> chunks, int bankSize, String path) throws Exception
    {
        int size = 0;
        for(int i = 0;i<chunks.size();i+=bankSize) {
            List<Integer> data = new ArrayList<>();
            for(int j = 0;j<bankSize;j++) {
                if (chunks.size() > i + j) {
                    RoomChunk c = chunks.get(i + j);
                    encodeChunk(c, data);
                    System.out.println("    " + (i+j) + ": " + c.path);
                }
            }
            
            String bankPath = path + "-" + (i/bankSize);
            Z80Assembler.dataToBinary(data, bankPath + ".bin");
            size += ZX0Wrapper.main(bankPath+".bin", bankPath+".zx0", true, false);
        }
        System.out.println("total compressed size: " + size);
    }
    
    
