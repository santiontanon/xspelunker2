    private static void generateChunkTagsTable(
            List<RoomChunk> chunks, int first_boss, int first_block, int first_combination,
            String path, String prefix) throws Exception
    {
        FileWriter fw = new FileWriter(path);
        fw.write("; Each chunk is 5 bytes: type, chunkFlags, left/up/right/down tags, locationTypeFlags (word)\n");
        fw.write(prefix + "_chunk_flags:\n");
        fw.write(prefix + "_standard_chunk_pool:\n");
        for(int i = 0;i<chunks.size();i++) {
            if (i == first_boss) {
                fw.write(prefix + "_boss_chunk_pool:\n");
            }
            if (i == first_block) {
                fw.write(prefix + "_block_chunk_pool:\n");
            }
            if (i == first_combination) {
                fw.write(prefix + "_combination_chunk_pool:\n");
            }
            RoomChunk c = chunks.get(i);
            int chunkFlags = 0;  // 0, 0, 0, 0, 0, 0, 0,boss
            int edgeFlags = 0;  // left, left, up, up, right, right, down, down
            if (c.tags.containsKey("boss")) {
                chunkFlags |= 1;
            }
            if (c.tags.containsKey("up")) {
                if (c.tags.get("up").equals("hole")) edgeFlags |= 0x10;
                if (c.tags.get("up").equals("stairs")) edgeFlags |= 0x20;
            }
            if (c.tags.containsKey("down")) {
                if (c.tags.get("down").equals("hole")) edgeFlags |= 0x01;
                if (c.tags.get("down").equals("stairs")) edgeFlags |= 0x02;
            }
            // location type flags:
            int locationTypeFlags = 0;
            for(TMXObject o:c.locations) {
                int bit = locationTypeToInt(o.type);
                int mask = 1;
                while(bit > 1) {
                    mask *= 2;
                    bit-- ;
                }
                locationTypeFlags |= mask;
            }
            
            fw.write("  db " + c.type + ", " + 
                    Z80Assembler.toHex8bit(chunkFlags) + ", " + 
                    Z80Assembler.toHex8bit(edgeFlags) + "  ; " + c.path + " ("+chunks.indexOf(c)+")\n");
            fw.write("  dw " + Z80Assembler.toHex16bit(locationTypeFlags, true) + "\n");
        }
        fw.flush();
        fw.close();
    }
    
    
    private static void generateChunkEdgeCollisionsTable(List<RoomChunk> chunks, String path) throws Exception
    {
        FileWriter fw = new FileWriter(path);
        for(RoomChunk c:chunks) {
            int leftFlags = 0;
            int upFlags = 0;
            int rightFlags = 0;
            int downFlags = 0;
            for(int i = 14;i>=0;i-=2) {
                // up:
                int tile1 = c.tiles[i][0];
                int tile2 = c.tiles[i + 1][0];
                upFlags *= 2;
                if (pyramid_tile_collision_types[tile1] == 2 ||
                    pyramid_tile_collision_types[tile2] == 2) {
                    upFlags |= 1;
                }
                // down:
                tile1 = c.tiles[i][11];
                tile2 = c.tiles[i + 1][11];
                downFlags *= 2;
                if (pyramid_tile_collision_types[tile1] == 2 ||
                    pyramid_tile_collision_types[tile2] == 2) {
                    downFlags |= 1;
                }
            }
            for(int i = 10;i>=0;i-=2) {
                // left:
                int tile1 = c.tiles[0][i];
                int tile2 = c.tiles[0][i+1];
                leftFlags *= 2;
                if (pyramid_tile_collision_types[tile1] == 2 ||
                    pyramid_tile_collision_types[tile2] == 2) {
                    leftFlags |= 1;
                }
                // right:
                tile1 = c.tiles[15][i];
                tile2 = c.tiles[15][i + 1];
                rightFlags *= 2;
                if (pyramid_tile_collision_types[tile1] == 2 ||
                    pyramid_tile_collision_types[tile2] == 2) {
                    rightFlags |= 1;
                }
            }            
            
            fw.write("  db " + Z80Assembler.toHex8bit(leftFlags) + ", " +
                               Z80Assembler.toHex8bit(upFlags) + ", " +
                               Z80Assembler.toHex8bit(rightFlags) + ", " +
                               Z80Assembler.toHex8bit(downFlags) + "  ; "+c.path+"\n");
        }
        fw.flush();
        fw.close();
    }
