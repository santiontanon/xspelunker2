    public static int locationTypeToInt(String type) throws Exception
    {
        switch(type) {
            case "item":
                return 1;
            case "big-item":
                return 2;
            case "4x4-item":
                return 3;
            case "breakable-left":
                return 4;
            case "breakable-up":
                return 5;
            case "breakable-right":
                return 6;
            case "breakable-down":
                return 7;
            case "door-left":
                return 8;
            case "door-up":
                return 9;
            case "door-right":
                return 10;
            case "door-down":
                return 11;
            default:
                throw new Exception("unsuported chunk location type: " + type);
        }
    }
    
    
