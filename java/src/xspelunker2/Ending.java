    public static void generateEnemyTypeData(String impage_path, int x0, int y0, String names1, String names2, String output_path) throws Exception
    {
        BufferedImage img = ImageIO.read(new File(impage_path));
        Pair<List<Integer>, int[][]> tmp = extractUniqueTilesAndNameTable(img, impage_path, x0, y0, x0 + 10, y0 + 6);
        
        List<Integer> data = new ArrayList<>();
        for(int i = 0;i<6;i++) {
            for(int j = 0;j<10;j++) {
                int v = tmp.right[j][i];
                int v2 = 0;
                while(v >= 12) {
                    v2 += 32;
                    v -= 12;
                }
                v2 += v;
                data.add(v2);
            }
        }
        data.addAll(font.convertStringToAssembler(names1));
        if (names2 == null) {
            data.add(0);
        } else {
            data.addAll(font.convertStringToAssembler(names2));
        }
        
        int n_tiles = tmp.left.size() / 16;
        int VDP_ptr = 0x0000  + 256*8;
        for(int i = 0;i<n_tiles;i+=12) {
            int n = 12;
            if (n_tiles - i < 12) n = n_tiles - i;
            data.add(n * 8);
            data.add(VDP_ptr & 0x00ff);
            data.add((VDP_ptr >> 8)  & 0x00ff);
            for(int j = 0;j<n*8;j++) {
                data.add(tmp.left.get(i*8 + j));  // patterns
            }
            for(int j = 0;j<n*8;j++) {
                data.add(tmp.left.get(i*8 + j + n_tiles*8));  // attributes
            }
            VDP_ptr += 32*8;
        }
        data.add(0);
        data.add(0);
        
        Z80Assembler.dataToBinary(data, output_path + ".bin");
        ZX0Wrapper.main(output_path + ".bin", output_path + ".zx0", true, false);
    }    

    
    public static Pair<List<Integer>, int[][]> extractUniqueTilesAndNameTable(BufferedImage sourceImage, String inputPath, int x0, int y0, int x1, int y1) throws Exception
    {
        List<List<Integer>> tiles = new ArrayList<>();
        List<Integer> tile = new ArrayList<>();
        int nameTable[][] = new int[x1-x0][y1-y0];
        List<Integer> bitmap_data = new ArrayList<>();
        List<Integer> color_data = new ArrayList<>();
        
        // start with the empty tile:
        for(int i = 0;i<8*8;i++) tile.add(0);
        for(int i = 0;i<8;i++) {
            bitmap_data.add(0);
            color_data.add(0);
        }
        tiles.add(tile);
        

        for(int i = y0*8;i<y1*8;i+=8) {
            for(int j = x0*8;j<x1*8;j+=8) {
                tile = new ArrayList<>();
                for(int ii = 0;ii<8;ii++) {
                    for(int jj = 0;jj<8;jj++) {
                        int color = ConvertPatternsToAssembler.findMSXColor(j+jj, i+ii, sourceImage, 0);
                        if (color == -1) throw new Exception("Unknown color at " + (j+jj) + ", " + (i+ii));
                        tile.add(color);
                    }
                }

                int found = -1;
                for(int tileIndex = 0;tileIndex<tiles.size();tileIndex++) {
                    List<Integer> tile2 = tiles.get(tileIndex);
                    boolean match = true;
                    for(int k = 0;k<8*8;k++) {
                        if (!tile.get(k).equals(tile2.get(k))) {
                            match = false;
                            break;
                        }
                    }
                    if (match) {
                        found = tileIndex;
                        break;
                    }
                }
                if (found == -1) {
                    nameTable[j/8 - x0][(i/8)-y0] = tiles.size();
                    tiles.add(tile);
                    List<Integer> pattern = ConvertPatternsToAssembler.generateAssemblerPatternBitmap(j/8, i/8, sourceImage, 0);
                    List<Integer> attributes = ConvertPatternsToAssembler.generateAssemblerPatternAttributes(j/8, i/8, sourceImage, 0);
                    bitmap_data.addAll(pattern);
                    color_data.addAll(attributes);
                } else {
                    nameTable[j/8 - x0][(i/8)-y0] = found;
                }
            }
        }
        System.out.println("Different tiles after " + inputPath + ": " + tiles.size());

        List<Integer> data = new ArrayList<>();
        data.addAll(bitmap_data);
        data.addAll(color_data);

        return new Pair<>(data, nameTable);
    }
    
