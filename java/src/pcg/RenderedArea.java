            for(int i = 0;i<fg_chunks[0].length;i++) {
                for(int j = 0;j<fg_chunks.length;j++) {
                    if (fg_chunks[j][i] != null) {
                        fg_chunks2[j][i] = fg_chunks[j][i].clone();
                    }
                }
            }
            
