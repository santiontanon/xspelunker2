public class Boss1 {
    int start_x = 32, start_y = 64;
    int width = 256, height = 192;
    int pixel_size = 2;

    BufferedImage tileSet;
    int nameTables[];
    int room[][];
    
    int state = 0;
    int timer = 0;
    int bossx = 26, bossy = 13;
    int prev_x = 26, prev_y = 13;
    int prev_w = 6, prev_h = 9;
    boolean firstDraw = true;

    
    public static void main(String args[]) throws Exception
    {
        /*
        ***- draw boss bullets:
            ***- small bullets fired from the eyes
            ***- whirlwinds
            ***- lightnings (like those in MoG boss 9, but telegraphed)
        - design attack patterns:
            - turn the current states into some variables (e.g., "boolean staff_broken = false")
              to program the behavior more easily
            - design several sequences, and randomly pick one or the other
            - have in mind where can the player damage the boss
        - adjust to have sequences that require a choreography to dodge (can I write a script to ensure the effect I want?)
        - patterns for the different difficulty levels
        
        */
        
        Boss1 b = new Boss1();
        
        JFrame w = new JFrame() {
            @Override
            public void paint(Graphics g) {
                Graphics2D g2d = (Graphics2D)g;
                try {
                    b.draw(g2d);
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        };
        w.setSize(new Dimension(640, 480));
        w.setVisible(true);
        w.setDefaultCloseOperation(JFrame.EXIT_ON_CLOSE);
        
        long start_time = System.currentTimeMillis();
        long target_frame_interval = 20;
        while(true) {
            Thread.yield();
            long current_time = System.currentTimeMillis();
            while((current_time - start_time) > target_frame_interval) {
                b.update();
                w.repaint();
                start_time += target_frame_interval;
            }
        }
    }
    
    
    public Boss1() throws Exception
    {
        tileSet = ImageIO.read(new File("data/boss1-tiles.png"));
        FileInputStream fstream = new FileInputStream("src/autogenerated/boss1-nametables.bin");
        byte tmp[] = fstream.readAllBytes();
        nameTables = new int[tmp.length];
        for(int i = 0;i<tmp.length;i++) {
            nameTables[i] = (int)tmp[i];
            if (nameTables[i] < 0) nameTables[i] += 256;
        }
        room = Tiled.loadTMXtileData("data/boss1-room.tmx");
    }
    
        
    public void draw(Graphics2D g2d) throws Exception
    {
        if (firstDraw) {
            g2d.setColor(Color.BLACK);
            g2d.fillRect(start_x, start_y, width * pixel_size, height * pixel_size);
            drawRoom(g2d);
            firstDraw = false;
        }
        
        switch(state) {
            case 0:  // rock
                drawBossFrame(g2d, 0, bossx, bossy);
                break;
            case 1:  // still
//                drawBossFrame(g2d, 1, bossx, bossy);
                drawBossFrame(g2d, 9, bossx, bossy);  // no staff
                break;
            case 2:  // walk left
            {
                int frame = (timer / 32) % 4;
                drawBossFrame(g2d, 2 + frame, bossx, bossy);
                break;
            }
            case 3:  // crouch
            case 5:  // crouch
                drawBossFrame(g2d, 6, bossx, bossy);
                break;
            case 4:  // jumping
                drawBossFrame(g2d, 1, bossx, bossy);
                break;
            case 6:  // scepter attack
                drawBossFrame(g2d, 7, bossx, bossy);
                break;
            case 7:  // left-hand attack
                drawBossFrame(g2d, 8, bossx, bossy);
                break;
                
            case 8:  // walk left without staff
            {
                int frame = (timer / 32) % 4;
                drawBossFrame(g2d, 10 + frame, bossx, bossy);
                break;
            }
            case 9:  // crouch (no staff)
            case 11:  // crouch (no staff)
                drawBossFrame(g2d, 14, bossx, bossy);
                break;
            case 10:  // jumping (no staff)
                drawBossFrame(g2d, 9, bossx, bossy);
                break;
            case 12:  // left-hand attack
                drawBossFrame(g2d, 15, bossx, bossy);
                break;
            case 13:  // punch
                drawBossFrame(g2d, 16, bossx, bossy);
                break;
                
        }
    }
    
    
    public void update() throws Exception
    {
        switch(state) {
            case 0:
                timer ++;
                if (timer >= 64) {
                    state = 1;
                    timer = 0;
                }
                break;
            case 1:
                timer ++;
                if (timer >= 64) {
//                    state = 2;  // walk
//                    state = 3;  // jump
//                    state = 6;  // scenpter attack
//                    state = 7;  // left-hand attack
//                    state = 8;  // walk without staff
//                    state = 9;  // jump without staff
//                    state = 12;  // left-hand attack without staff
                    state = 13;  // punch
                    timer = 0;
                }
                break;
            case 2:
                // walk left:
                timer ++;
                timer = timer % 128;
                if ((timer % 128) == 0) bossx--;
                if ((timer % 128) == 64) bossx--;
                if ((timer % 128) == 96) bossx--;
                break;
            case 3:
                // crouch before jumping
                timer ++;
                if (timer > 32) {
                    timer = 0;
                    state = 4;
                    bossy--;
                }
                break;
            case 4:
                // jumping
                timer ++;
                if (timer < 64) {
                    if ((timer%8) == 0) bossy--;
                } else if (timer < 128) {
                    if ((timer%8) == 0) bossy++;
                } else {
                    timer = 0;
                    state = 5;
//                    bossy++;
                }
                break;
            case 5:
                // landing from a jump
                timer ++;
                if (timer > 32) {
                    timer = 0;
                    state = 1;
                }
                break;
            case 6:
                // staff attack
                timer ++;
                if (timer > 64) {
                    timer = 0;
                    state = 1;
                }
                break;
            case 7:
                // left-hand attack
                timer ++;
                if (timer > 64) {
                    timer = 0;
                    state = 1;
                }
                break;
                
            case 8:
                // walk left without staff:
                timer ++;
                timer = timer % 128;
                if ((timer % 128) == 0) bossx--;
                if ((timer % 128) == 64) bossx--;
                if ((timer % 128) == 96) bossx--;
                break;
            case 9:
                // crouch before jumping
                timer ++;
                if (timer > 32) {
                    timer = 0;
                    state = 10;
                    bossy--;
                }
                break;
            case 10:
                // jumping
                timer ++;
                if (timer < 64) {
                    if ((timer%8) == 0) bossy--;
                } else if (timer < 128) {
                    if ((timer%8) == 0) bossy++;
                } else {
                    timer = 0;
                    state = 11;
//                    bossy++;
                }
                break;
            case 11:
                // landing from a jump
                timer ++;
                if (timer > 32) {
                    timer = 0;
                    state = 1;
                }
                break;                
            case 12:
                // left-hand attack
                timer ++;
                if (timer > 64) {
                    timer = 0;
                    state = 1;
                }
                break;
            case 13:
                // punch
                timer ++;
                if (timer > 64) {
                    timer = 0;
                    state = 1;
                }
                break;
                
        }
    }
    
    
    public void drawRoom(Graphics2D g2d)
    {
        for(int i = 0;i<24;i++) {
            for(int j = 0;j<32;j++) {
                drawTile(g2d, room[j][i], j, i);
            }
        }
    }
    
    
    public void drawBossFrame(Graphics2D g2d, int ID, int x, int y) throws Exception
    {
        g2d.setColor(Color.black);
        if (prev_w == 8) prev_x -= 2;
        g2d.fillRect(start_x + prev_x*8*pixel_size, start_y + prev_y*8*pixel_size,
                     prev_w * 8 * pixel_size, prev_h * 8 * pixel_size);
        prev_x = x;
        prev_y = y;
        switch(ID) {
            // stone version:
            case 0: drawNameTable(g2d, 0, 6, 9, x, y);
                break;
            // base frame:
            case 1: drawNameTable(g2d, 54, 6, 9, x, y);
                    drawNameTable(g2d, 154, 4, 4, x+1, y + 5);
                    break;
            // walk 1 (back leg up):
            case 2: drawNameTable(g2d, 54, 6, 9, x, y);
                    drawNameTable(g2d, 170, 5, 4, x, y + 5);
                    break;
            // walk 2 (legs wide):
            case 3: drawNameTable(g2d, 54, 6, 9, x, y);
                    drawNameTable(g2d, 206, 5, 4, x, y + 5);
                    break;
            // walk 3 (front leg up):
            case 4: drawNameTable(g2d, 54, 6, 9, x, y);
                    drawNameTable(g2d, 190, 4, 4, x + 1, y + 5);
                    break;
            // walk 4 (legs crossed):
            case 5: drawNameTable(g2d, 54, 6, 9, x, y);
                    drawNameTable(g2d, 226, 3, 4, x + 2, y + 5);
                    break;

            // crouch:
            case 6: drawNameTable(g2d, 108, 6, 7, x, y + 1);
                    drawNameTable(g2d, 238, 4, 3, x + 1, y + 6);
                    break;
            // staff attack:
            case 7: drawNameTable(g2d, 108, 6, 7, x, y);
                    drawNameTable(g2d, 154, 4, 4, x+1, y + 5);
                    break;
            // left-hand attack:
            case 8: drawNameTable(g2d, 250, 6, 9, x, y);
                    drawNameTable(g2d, 154, 4, 4, x+1, y + 5);
                    break;

            // base frame (no staff):
            case 9: drawNameTable(g2d, 304, 5, 7, x+1, y);
                    drawNameTable(g2d, 154, 4, 4, x+1, y + 5);
                    break;
            // walk-no-staff 1 (back leg up):
            case 10: drawNameTable(g2d, 304, 5, 7, x + 1, y);
                    drawNameTable(g2d, 170, 5, 4, x, y + 5);
                    break;
            // walk-no-staff 2 (legs wide):
            case 11: drawNameTable(g2d, 304, 5, 7, x + 1, y);
                     drawNameTable(g2d, 206, 5, 4, x, y + 5);
                     break;
            // walk-no-staff 3 (front leg up):
            case 12: drawNameTable(g2d, 304, 5, 7, x + 1, y);
                     drawNameTable(g2d, 190, 4, 4, x + 1, y + 5);
                     break;
            // walk-no-staff 4 (legs crossed):
            case 13: drawNameTable(g2d, 304, 5, 7, x + 1, y);
                     drawNameTable(g2d, 226, 3, 4, x + 2, y + 5);
                     break;
            // crouching (no staff):
            case 14: drawNameTable(g2d, 304, 5, 7, x + 1, y + 1);
                     drawNameTable(g2d, 238, 4, 3, x + 1, y + 6);
                     break;
            // left-hand-attack (no staff):
            case 15: drawNameTable(g2d, 339, 5, 6, x+1, y);
                     drawNameTable(g2d, 154, 4, 4, x+1, y + 5);
                     break;
            // punch (no staff):
            case 16: drawNameTable(g2d, 369, 8, 7, x-2, y);
                     drawNameTable(g2d, 154, 4, 4, x+1, y + 5);
                     break;
                    
            default:
                throw new Exception("Unknown boss nametable " + ID);
        }
        
        if (ID == 16) {
            prev_w = 8;
        } else {
            prev_w = 6;
        }
        
    }
    
    
    public void drawNameTable(Graphics2D g2d, int start_offset, int width, int height, int x, int y)
    {
        for(int i = 0;i<height;i++) {
            for(int j = 0;j<width;j++) {
                if (nameTables[start_offset + j + (i*width)] > 0) {
                    drawTile(g2d, nameTables[start_offset + j + (i*width)], x + j, y + i);
                }
            }
        }
    }


    public void drawTile(Graphics2D g2d, int tileID, int x, int y)
    {
        int tx = tileID % 16;
        int ty = tileID / 16;
        g2d.drawImage(tileSet,
                      start_x + x*8*pixel_size, start_y + y*8*pixel_size,
                      start_x + (x+1)*8*pixel_size, start_y + (y+1)*8*pixel_size,
                      tx*8, ty*8, (tx+1)*8, (ty+1)*8, null);
    }
}
