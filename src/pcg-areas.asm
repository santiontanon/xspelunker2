;-----------------------------------------------
room_offset_to_chunk_offset:
	ld d, a
	; the offset is in rooms, we need to convert it to chunks:
	; - a = x + y * width
	; - we want: x*2 + y*2*width*2
	; we isolate x:
	push af
		ld a, (current_area__width)
		ld e, a
	pop af
room_offset_to_chunk_offset_loop:
	cp e
	jr c, room_offset_to_chunk_offset_loop_loop_done
	sub e
	jr room_offset_to_chunk_offset_loop
room_offset_to_chunk_offset_loop_loop_done:
	; - a = x
	; - e: area width (in rooms)
	; - d: room offset
	ld c, a
	ld a, d
	sub c  ; a = y * width
	add a, a
	add a, a  ; a = y * 2 * width * 2
	add a, c
	add a, c  ; a = offset in chunks
	ret


;-----------------------------------------------
; input:
; - e: chunk offset
; output:
; - e: room offset
covert_chunk_offset_to_room_offset:
	; - chunk offset = x + y * width*2
	; - room offset = x/2 + y/2 * width
	ld a, e
	ld hl, current_area__width
	ld c, (hl)  ; width in rooms
	sla c  ; c = width * 2
	ld b, 0
covert_chunk_offset_to_room_offset_loop_1:
	cp c
	jr c, covert_chunk_offset_to_room_offset_loop_1_done
	sub c
	inc b
	jr covert_chunk_offset_to_room_offset_loop_1
covert_chunk_offset_to_room_offset_loop_1_done:
	; b = y
	; a = x
	srl a  ; a = x/2
	srl b  ; b = y/2
	ld c, (hl)  ; c = width
	jr z, covert_chunk_offset_to_room_offset_loop_2_done
covert_chunk_offset_to_room_offset_loop_2:
	add a, c
	djnz covert_chunk_offset_to_room_offset_loop_2
covert_chunk_offset_to_room_offset_loop_2_done:
	ld e, a  ; e = x/2 + y/2 * width
	ret


;-----------------------------------------------
; input:
; - hl: tag list ptr
; - ixl: tag
; output:
; - z: if the tag is in the list
; - nz: if it is not
pcg_generate_area__tag_in_list:
	ld a, (hl)
	or a
	jr z, pcg_generate_area__tag_in_list_negative
	cp ixl
	ret z
	inc hl
	jp pcg_generate_area__tag_in_list
pcg_generate_area__tag_in_list_negative:
	or 1
	ret

