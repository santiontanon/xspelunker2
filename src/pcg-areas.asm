tmp_pcg_area__ptr_to_world_area: equ buffer_4096  ; 2 bytes
tmp_pcg_area__division_ids_tmp: equ buffer_4096 + 2  ; MAX_AREA_SIZE*2*2 bytes
													 ; this array is used at "room" resolution (size MAX_AREA_SIZE) or
													 ; at chunk resolution (size MAX_AREA_SIZE * 2 * 2).
tmp_pcg_area__piece_types: equ tmp_pcg_area__division_ids_tmp + MAX_AREA_SIZE*2*2  ; MAX_AREA_SIZE*2*2 bytes
tmp_pcg_area__placed_tags: equ tmp_pcg_area__piece_types + MAX_AREA_SIZE*2*2  ; MAX_AREA_SIZE*2*2 bytes
tmp_pcg_area__spanning_tree_open: equ tmp_pcg_area__placed_tags + MAX_AREA_SIZE*2*2  ; 64 bytes  ; assuming no division has area >= 64


;-----------------------------------------------
; Pseudocode for this method:
; 0.- mergeAreaRooms
;     - for each position in the map, random change to merge with up/down/left/right as long
;       as it's within division, and as long as room area is <= 4.
; 1.- Generate a spanning tree for each division:
;   - The result is that "pieceTypes" has all the connections necessary for this spanning tree
; 2.- Complement "pieceTypes" with the "a.connections" generated by PCGWorld,
;     inter-area connections and with random paths.
; 3.- Place tags (assign room tags to a single chunk position, only one tag per chunk)
; 4.- Choose chunks. For each position in the map (chunk-level):
;   - Determine the constraints on the chunks (pool, tags, locations it must have)
;   - Choose a chunk
;   - Add necessary objects according to the tag (if any)
; 
; input:
; - e: area ID
pcg_generate_area:
	; get ptr of the area to generate:
	ld hl, current_world__area_data
	ld bc, WORLD_AREA__SIZE
	ld a, e
	or a
	jr z, pcg_generate_area__world_area_ptr_set
pcg_generate_area__world_area_ptr_loop:
	add hl, bc
	dec a
	jr nz, pcg_generate_area__world_area_ptr_loop
pcg_generate_area__world_area_ptr_set:
	ld (tmp_pcg_area__ptr_to_world_area), hl

	; copy seed, ID, width, height
	ld de, current_area__seed
	ld bc, 4 + 1 + 1 + 1
	ldir

	; reset rng:
	ld hl, current_area__seed
	ld de, rng_seed1
	ldi
	ldi
	ldi
	ldi

	call pcg_generate_area__initialize_room_ids  ; initializes 'current_area__room_ids'
	call pcg_generate_area__merge_rooms  ; merges rooms in 'current_area__room_ids'
	call pcg_generate_area__division_spanning_trees  ; fills 'tmp_pcg_area__piece_types'
	call pcg_generate_area__additional_connections  ; updates 'tmp_pcg_area__piece_types'
	call pcg_generate_area__random_connections  ; updates 'tmp_pcg_area__piece_types'
	call pcg_generate_area__inter_area_connections  ; updates 'tmp_pcg_area__piece_types'
	call pcg_generate_area__place_tags  ; fills 'tmp_pcg_area__placed_tags'
	call pcg_generate_area__choose_chunks  ; fills 'current_area__chunks_ids'

; 	ld hl, hardcoded_area_data
; 	ld de, current_area__seed
; 	ld bc, hardcoded_area_data_end - hardcoded_area_data
; 	ldir

	; for now just copy over the hardcoded data:
	ld hl, hardcoded_area_data__chunk_ids
	ld de, current_area__chunks_ids
	ld bc, MAX_AREA_SIZE * 2 * 2
	ldir
	ret


;-----------------------------------------------
; This method sets the 'current_area__room_ids' to:
; - #ff for positions in which there is no room
; - to a room ID (>=0) if there should be a room, and it makes all the rooms 1x1 in size.
pcg_generate_area__initialize_room_ids:
	ld hl, (tmp_pcg_area__ptr_to_world_area)
	ld bc, WORLD_AREA__DIVISION_IDS_OFFSET
	add hl, bc
	ex de, hl
	ld ix, current_area__room_ids
	ld bc, (current_area__width)
	xor a  ; next room ID
	ex af, af'
pcg_generate_area__initialize_room_ids_loop_y:
	push bc
		ld b, c
pcg_generate_area__initialize_room_ids_loop_x:
		ld a, (de)  ; division ID
		or a
		jr z, pcg_generate_area__initialize_room_ids_loop_x_no_room
		ex af, af'
			ld (ix), a  ; room ID
			inc a
		ex af, af'
		jp pcg_generate_area__initialize_room_ids_loop_x_continue
pcg_generate_area__initialize_room_ids_loop_x_no_room:
		ld (ix), #ff
pcg_generate_area__initialize_room_ids_loop_x_continue:
		inc de
		inc ix
		djnz pcg_generate_area__initialize_room_ids_loop_x
	pop bc
	djnz pcg_generate_area__initialize_room_ids_loop_y
	ret


;-----------------------------------------------
; This method attempts to merge neighboring rooms that belong to the same division.
; It will try to make rooms that are 2x1, 3x1, 4x1, 2x2, 1x2, 1x3, or 1x4 in size.
pcg_generate_area__merge_rooms:
	; make a copy of the division IDs (we will use to mark which rooms have already been processed)
	ld hl, (tmp_pcg_area__ptr_to_world_area)
	ld bc, WORLD_AREA__DIVISION_IDS_OFFSET
	add hl, bc  ; hl = division IDs ptr
	ld de, tmp_pcg_area__division_ids_tmp
	ld bc, MAX_AREA_SIZE
	ldir
	ld hl, tmp_pcg_area__division_ids_tmp

	ld bc, (current_area__width)
	ld ixl, c
	ld ixh, b  ; ixl: width, ixh: height
	ld d, 0  ; e: x, d: y
pcg_generate_area__merge_rooms_loop_y:
	push bc
		ld b, c
		ld e, 0
pcg_generate_area__merge_rooms_loop_x:
		push bc
			ld a, (hl)
			or a
			jp z, pcg_generate_area__merge_rooms_loop_x_skip
			ld (hl), 0  ; mark as "processed"
			ld iyl, a  ; iyl will hold the division ID we are merging

			; check if we can make a 2x1 room:
			ld a, e
			inc a
			cp ixl
			jp nc, pcg_generate_area__merge_rooms_loop_x_2x1_failed
			inc hl
			ld a, iyl
			cp (hl)
			dec hl  ; preserves z flag
			jp nz, pcg_generate_area__merge_rooms_loop_x_2x1_failed
			; we can make a 2x1!
			push bc
				ld bc, current_area__room_ids - tmp_pcg_area__division_ids_tmp
				add hl, bc
				ld a, (hl)  ; room ID
				inc hl
				ld (hl), a  ; set the room ID of the room to the right
				or a
				sbc hl, bc
				ld (hl), 0  ; mark the room to the right as "processed"
				dec hl  ; recover hl to point again to the division ID of the original room
			pop bc

			; if so, check if we can make a 2x2:
			ld a, d
			inc a
			cp ixh
			jr nc, pcg_generate_area__merge_rooms_loop_x_2x2_failed
			push bc
				ld c, ixl
				ld b, 0
				add hl, bc
				ld a, iyl  ; division ID
				cp (hl)  ; comparing with room (0, +1)
				jr nz, pcg_generate_area__merge_rooms_loop_x_2x2_failed_sub_bc
				inc hl
				cp (hl)  ; comparing with room (+1, +1)
				jr nz, pcg_generate_area__merge_rooms_loop_x_2x2_failed_sub_bc_1
				sbc hl, bc  ; we are back pointing to division id (+1, 0)
				; we can make a 2x2!
				push de
					ld de, current_area__room_ids - tmp_pcg_area__division_ids_tmp
					add hl, de
					ld a, (hl)  ; room ID
					add hl, bc
					ld (hl), a  ; set the room ID of the room (+1, +1)
					dec hl
					ld (hl), a  ; set the room ID of the room (0, +1)
					or a
					sbc hl, de
					ld (hl), 0  ; mark room (0, +1) as "processed"
					inc hl
					ld (hl), 0  ; mark room (+1, +1) as "processed"
				pop de
				sbc hl, bc
				dec hl  ; recover hl to point again to the division ID of the original room
			pop bc
			jp pcg_generate_area__merge_rooms_loop_x_skip

pcg_generate_area__merge_rooms_loop_x_2x2_failed_sub_bc_1:
				dec hl
pcg_generate_area__merge_rooms_loop_x_2x2_failed_sub_bc:
				or a
				sbc hl, bc
			pop bc
pcg_generate_area__merge_rooms_loop_x_2x2_failed:

			; 2x2 failed, check if we can make a 3x1:
			ld a, e
			add a, 2
			cp ixl
			jp nc, pcg_generate_area__merge_rooms_loop_x_skip
			inc hl
			inc hl
			ld a, iyl
			cp (hl)
			dec hl  ; preserves z flag
			dec hl  ; preserves z flag
			jp nz, pcg_generate_area__merge_rooms_loop_x_skip
			; we can make a 3x1!
			push bc
				ld bc, current_area__room_ids - tmp_pcg_area__division_ids_tmp
				add hl, bc
				ld a, (hl)  ; room ID
				inc hl
				inc hl
				ld (hl), a  ; set the room ID of the room to the right
				or a
				sbc hl, bc
				ld (hl), 0  ; mark the room to the right as "processed"
				dec hl
				dec hl  ; recover hl to point again to the division ID of the original room
			pop bc

			; We could do a 3x1, check if we can make a 4x1:
			ld a, e
			add a, 3
			cp ixl
			jp nc, pcg_generate_area__merge_rooms_loop_x_skip
			inc hl
			inc hl
			inc hl
			ld a, iyl
			cp (hl)
			dec hl  ; preserves z flag
			dec hl
			dec hl
			jp nz, pcg_generate_area__merge_rooms_loop_x_skip
			; we can make a 3x1!
			push bc
				ld bc, current_area__room_ids - tmp_pcg_area__division_ids_tmp
				add hl, bc
				ld a, (hl)  ; room ID
				inc hl
				inc hl
				inc hl
				ld (hl), a  ; set the room ID of the room to the right
				or a
				sbc hl, bc
				ld (hl), 0  ; mark the room to the right as "processed"
				dec hl
				dec hl
				dec hl  ; recover hl to point again to the division ID of the original room
			pop bc

			jp pcg_generate_area__merge_rooms_loop_x_skip

pcg_generate_area__merge_rooms_loop_x_2x1_failed:
			; otherwise (if we cannot make a 2x1), check if we can make a 1x2:
			ld a, d
			inc a
			cp ixh
			jp nc, pcg_generate_area__merge_rooms_loop_x_skip
			push bc
				ld c, ixl
				ld b, 0
				add hl, bc
				ld a, iyl
				cp (hl)
				jr nz, pcg_generate_area__merge_rooms_loop_x_skip_sub_bc
				sbc hl, bc
				; we can make a 2x1!
				push de
					ld de, current_area__room_ids - tmp_pcg_area__division_ids_tmp
					add hl, de
					ld a, (hl)  ; room ID
					add hl, bc
					ld (hl), a  ; set the room ID of the room below
					or a
					sbc hl, de
					ld (hl), 0  ; mark the room to the right as "processed"
				pop de
				sbc hl, bc  ; recover hl to point again to the division ID of the original room
			pop bc

			; We can make a 1x2, check if we can make a 1x3:
			ld a, d
			add a, 2
			cp ixh
			jr nc, pcg_generate_area__merge_rooms_loop_x_skip
			push bc
				ld c, ixl
				ld b, 0
				add hl, bc
				add hl, bc
				ld a, iyl
				cp (hl)
				jr nz, pcg_generate_area__merge_rooms_loop_x_skip_sub_2bc
				sbc hl, bc
				sbc hl, bc
				; we can make a 2x1!
				push de
					ld de, current_area__room_ids - tmp_pcg_area__division_ids_tmp
					add hl, de
					ld a, (hl)  ; room ID
					add hl, bc
					add hl, bc
					ld (hl), a  ; set the room ID of the room below
					or a
					sbc hl, de
					ld (hl), 0  ; mark the room to the right as "processed"
				pop de
				sbc hl, bc
				sbc hl, bc  ; recover hl to point again to the division ID of the original room
			pop bc

			; we can make a 1x3, check if we can make a 1x4:
			ld a, d
			add a, 3
			cp ixh
			jr nc, pcg_generate_area__merge_rooms_loop_x_skip
			push bc
				ld c, ixl
				ld b, 0
				add hl, bc
				add hl, bc
				add hl, bc
				ld a, iyl
				cp (hl)
				jr nz, pcg_generate_area__merge_rooms_loop_x_skip_sub_3bc
				sbc hl, bc
				sbc hl, bc
				sbc hl, bc
				; we can make a 2x1!
				push de
					ld de, current_area__room_ids - tmp_pcg_area__division_ids_tmp
					add hl, de
					ld a, (hl)  ; room ID
					add hl, bc
					add hl, bc
					add hl, bc
					ld (hl), a  ; set the room ID of the room below
					or a
					sbc hl, de
					ld (hl), 0  ; mark the room to the right as "processed"
				pop de
				sbc hl, bc
				sbc hl, bc
				sbc hl, bc  ; recover hl to point again to the division ID of the original room
			pop bc

			jp pcg_generate_area__merge_rooms_loop_x_skip

pcg_generate_area__merge_rooms_loop_x_skip_sub_3bc:
				or a
				sbc hl, bc
pcg_generate_area__merge_rooms_loop_x_skip_sub_2bc:
				or a
				sbc hl, bc
pcg_generate_area__merge_rooms_loop_x_skip_sub_bc:
				or a
				sbc hl, bc
			pop bc

pcg_generate_area__merge_rooms_loop_x_skip:
			inc hl
			inc e
		pop bc
		dec b
		jp nz, pcg_generate_area__merge_rooms_loop_x
	pop bc
	inc d
	dec b
	jp nz, pcg_generate_area__merge_rooms_loop_y
	ret


;-----------------------------------------------
pcg_generate_area__division_spanning_trees:
	; initialize the piece types:
	ld hl, tmp_pcg_area__piece_types
	ld bc, MAX_AREA_SIZE * 2 * 2 - 1
	ld a, #ff
	call clear_memory_a

	; make a copy of the division IDs, but at chunk resolution
	; (we will use to mark which rooms have already been processed)
	call pcg_generate_area__chunk_resolution_division_ids
	ld hl, tmp_pcg_area__division_ids_tmp

	ld bc, (current_area__width)
	sla b
	sla c	
	ld ixl, c  ; ixl: width (in chunks)
	ld d, 0  ; e: x, d: y
pcg_generate_area__division_spanning_trees_loop_y:
	push bc
		ld b, c
		ld e, 0
pcg_generate_area__division_spanning_trees_loop_x:
		push bc
			ld a, (hl)
			or a
			jp z, pcg_generate_area__division_spanning_trees_loop_x_skip

			; generate spanning tree:
			push hl
				call pcg_generate_area__division_spanning_trees_generate
			pop hl
pcg_generate_area__division_spanning_trees_loop_x_skip:
			inc hl
		pop bc
		djnz pcg_generate_area__division_spanning_trees_loop_x
	pop bc
	djnz pcg_generate_area__division_spanning_trees_loop_y
	ret


;-----------------------------------------------
; input:
; - hl: ptr to 'tmp_pcg_area__division_ids_tmp' where to start the spanning tree
pcg_generate_area__division_spanning_trees_generate:
	ld a, (hl)
	ld (hl), 0  ; mark the position as "closed"
	ld iyl, a  ; division ID we are filling
	ld bc, tmp_pcg_area__division_ids_tmp
	or a
	sbc hl, bc
	ld a, l
	ld de, tmp_pcg_area__spanning_tree_open
	ld (de), a  ; first open
	ld iyh, 1  ; size of open list
pcg_generate_area__division_spanning_trees_generate_loop:
	ld a, iyh
	or a
	ret z  ; we are done!
	call pcg_generate_area__division_spanning_trees_generate_pop
	ld ixh, a
	; here:
	; - iyl: division ID we are filling
	; - iyh: open list size
	; - ixl: area width/height
	; - ixh, a: current position
	ld hl, tmp_pcg_area__piece_types
	ADD_HL_A
	ld a, (hl)
	inc a
	jr nz, pcg_generate_area__division_spanning_trees_generate_loop_continue
	ld (hl), 0  ; initialize the piece type
pcg_generate_area__division_spanning_trees_generate_loop_continue:

	; left:
	ld hl, tmp_pcg_area__division_ids_tmp
	ld a, ixh
	ADD_HL_A
	dec hl  ; left
	ld a, (hl)
	cp iyl
	jr nz, pcg_generate_area__division_spanning_trees_generate_loop_left_done
	ld a, ixh
	dec a  ; left
	jr c, pcg_generate_area__division_spanning_trees_generate_loop_left_done  ; we are out of the map
	call pcg_generate_area__division_spanning_trees_generate_open_push_a
	jr c, pcg_generate_area__division_spanning_trees_generate_loop_left_done
	ld (hl), 0  ; mark as processed
	ld bc, tmp_pcg_area__piece_types - tmp_pcg_area__division_ids_tmp
	add hl, bc  ; hl now points to the piece type to the left
	ld a, (hl)
	cp #ff
	jr nz, pcg_generate_area__division_spanning_trees_generate_loop_left_continue
	xor a
	ld (hl), a  ; initialize the piece type
pcg_generate_area__division_spanning_trees_generate_loop_left_continue:
	or PCG_DIRECTION_RIGHT
	ld (hl), a
	inc hl
	ld a, (hl)
	or PCG_DIRECTION_LEFT
	ld (hl), a
pcg_generate_area__division_spanning_trees_generate_loop_left_done:

	; up:
	ld hl, tmp_pcg_area__division_ids_tmp
	ld a, ixh
	ADD_HL_A
	ld b, 0
	ld c, ixl
	or a
	sbc hl, bc  ; up
	ld a, (hl)
	cp iyl
	jr nz, pcg_generate_area__division_spanning_trees_generate_loop_up_done
	ld a, ixh
	sub ixl  ; up
	jr c, pcg_generate_area__division_spanning_trees_generate_loop_up_done  ; we are out of the map
	call pcg_generate_area__division_spanning_trees_generate_open_push_a
	jr c, pcg_generate_area__division_spanning_trees_generate_loop_up_done
	ld (hl), 0  ; mark as processed
	ld bc, tmp_pcg_area__piece_types - tmp_pcg_area__division_ids_tmp
	add hl, bc  ; hl now points to the piece type above
	ld a, (hl)
	cp #ff
	jr nz, pcg_generate_area__division_spanning_trees_generate_loop_up_continue
	xor a
	ld (hl), a  ; initialize the piece type
pcg_generate_area__division_spanning_trees_generate_loop_up_continue:
	or PCG_DIRECTION_DOWN
	ld (hl), a
	ld b, 0
	ld c, ixl
	add hl, bc	
	ld a, (hl)
	or PCG_DIRECTION_UP
	ld (hl), a
pcg_generate_area__division_spanning_trees_generate_loop_up_done:

	; right:
	ld hl, tmp_pcg_area__division_ids_tmp
	ld a, ixh
	ADD_HL_A
	inc hl  ; right
	ld a, (hl)
	cp iyl
	jr nz, pcg_generate_area__division_spanning_trees_generate_loop_right_done
	ld a, ixh
	inc a  ; right
	call pcg_generate_area__division_spanning_trees_generate_open_push_a
	jr c, pcg_generate_area__division_spanning_trees_generate_loop_right_done
	ld (hl), 0  ; mark as processed
	ld bc, tmp_pcg_area__piece_types - tmp_pcg_area__division_ids_tmp
	add hl, bc  ; hl now points to the piece type to the right
	ld a, (hl)
	cp #ff
	jr nz, pcg_generate_area__division_spanning_trees_generate_loop_right_continue
	xor a
	ld (hl), a  ; initialize the piece type
pcg_generate_area__division_spanning_trees_generate_loop_right_continue:
	or PCG_DIRECTION_LEFT
	ld (hl), a
	dec hl
	ld a, (hl)
	or PCG_DIRECTION_RIGHT
	ld (hl), a
pcg_generate_area__division_spanning_trees_generate_loop_right_done:

	; down:
	ld hl, tmp_pcg_area__division_ids_tmp
	ld a, ixh
	ADD_HL_A
	ld b, 0
	ld c, ixl
	add hl, bc
	ld a, (hl)
	cp iyl
	jr nz, pcg_generate_area__division_spanning_trees_generate_loop_down_done
	ld a, ixh
	add a, ixl  ; down
	; cp MAX_AREA_SIZE * 2 * 2
	; jr nc, pcg_generate_area__division_spanning_trees_generate_loop_down_done  ; we are out of the map
	jr c, pcg_generate_area__division_spanning_trees_generate_loop_down_done  ; we are out of the map (since MAX_AREA_SIZE * 2 * 2 is 256)
	call pcg_generate_area__division_spanning_trees_generate_open_push_a
	jr c, pcg_generate_area__division_spanning_trees_generate_loop_down_done
	ld (hl), 0  ; mark as processed
	ld bc, tmp_pcg_area__piece_types - tmp_pcg_area__division_ids_tmp
	add hl, bc  ; hl now points to the piece type above
	ld a, (hl)
	cp #ff
	jr nz, pcg_generate_area__division_spanning_trees_generate_loop_down_continue
	xor a
	ld (hl), a  ; initialize the piece type
pcg_generate_area__division_spanning_trees_generate_loop_down_continue:
	or PCG_DIRECTION_UP
	ld (hl), a
	ld b, 0
	ld c, ixl
	or a
	sbc hl, bc	
	ld a, (hl)
	or PCG_DIRECTION_DOWN
	ld (hl), a
pcg_generate_area__division_spanning_trees_generate_loop_down_done:
	jp pcg_generate_area__division_spanning_trees_generate_loop


pcg_generate_area__division_spanning_trees_generate_pop:
	; get a random element from the open list (size in iyh):
	call random_a
	and #3f  ; open list is at most 64 positions in size
	cp iyh
	jr c, pcg_generate_area__division_spanning_trees_generate_pop_done
pcg_generate_area__division_spanning_trees_generate_pop_loop:
	sub iyh
	jr nc, pcg_generate_area__division_spanning_trees_generate_pop_loop
	add a, iyh
pcg_generate_area__division_spanning_trees_generate_pop_done:
	ld hl, tmp_pcg_area__spanning_tree_open
	ld c, a
	ADD_HL_A
	ld a, (hl)  ; element to pop
	push af
		; copy (iyh - c) - 1 elements left:
		ld e, l
		ld d, h
		inc hl
		ld a, iyh
		sub c
		dec a  ; a = (iyh - c) - 1
		jr z, pcg_generate_area__division_spanning_trees_generate_pop_last
		ld b, 0
		ld c, a
		ldir
pcg_generate_area__division_spanning_trees_generate_pop_last:
	pop af
	dec iyh
	ret


; - carry: open already contains a
; - no carry: open did not contain a (and "a" was just pushed)
pcg_generate_area__division_spanning_trees_generate_open_push_a:
	push hl
		ld hl, tmp_pcg_area__spanning_tree_open
		ld b, iyh
		inc b
		dec b
		jr z, pcg_generate_area__division_spanning_trees_generate_open_push_a_not_there
pcg_generate_area__division_spanning_trees_generate_open_push_a_loop:
		cp (hl)
		jr z, pcg_generate_area__division_spanning_trees_generate_open_push_a_already_there
		inc hl
		djnz pcg_generate_area__division_spanning_trees_generate_open_push_a_loop
pcg_generate_area__division_spanning_trees_generate_open_push_a_not_there:
		; add 'a' to open:
		ld (hl), a
		inc iyh
	pop hl
	or a
	ret
pcg_generate_area__division_spanning_trees_generate_open_push_a_already_there:
	pop hl
	scf
	ret


;-----------------------------------------------
; make a copy of the division IDs, but at chunk resolution
pcg_generate_area__chunk_resolution_division_ids:
	ld hl, (tmp_pcg_area__ptr_to_world_area)
	ld bc, WORLD_AREA__DIVISION_IDS_OFFSET
	add hl, bc  ; hl = division IDs ptr
	ld de, tmp_pcg_area__division_ids_tmp
	ld bc, (current_area__width)
	sla b  ; height * 2
pcg_generate_area__division_spanning_trees_expant_division_ids_loop_y:
	push bc
		ld b, c
pcg_generate_area__division_spanning_trees_expant_division_ids_loop_x:
		ld a, (hl)
		inc hl
		ld (de), a
		inc de
		ld (de), a
		inc de
		djnz pcg_generate_area__division_spanning_trees_expant_division_ids_loop_x
	pop bc
	ld a, b
	and #01
	jr nz, pcg_generate_area__division_spanning_trees_expant_division_ids_loop_y_continue
	push bc
		ld b, 0
		or a
		sbc hl, bc  ; copy this row one more time
	pop bc
pcg_generate_area__division_spanning_trees_expant_division_ids_loop_y_continue:
	djnz pcg_generate_area__division_spanning_trees_expant_division_ids_loop_y
	ret


;-----------------------------------------------
pcg_generate_area__additional_connections:
	ld hl, (tmp_pcg_area__ptr_to_world_area)
	ld bc, WORLD_AREA__CONNECTIONS_OFFSET
	add hl, bc  ; hl = connections ptr

	ld bc, (current_area__width)
	ld ixl, c  ; ixl: width (in rooms)
	ld ixh, b  ; ixh: height (in rooms)
	ld de, tmp_pcg_area__piece_types
pcg_generate_area__additional_connections_loop_y:
	push bc
pcg_generate_area__additional_connections_loop_x:
		ld a, (hl)
		or a
		jp z, pcg_generate_area__additional_connections_loop_x_skip

		bit PCG_DIRECTION_LEFT_BIT, a  ; left bit
		jr z, pcg_generate_area__additional_connections_loop_x_continue
		push de
			; add horizontal connection:
			call random_a
			and #01
			jr z, pcg_generate_area__additional_connections_loop_x_horizontal_continue
			push hl
			ex de, hl
				ld e, ixl
				ld d, 0
				add hl, de
				add hl, de
			ex de, hl
			pop hl
pcg_generate_area__additional_connections_loop_x_horizontal_continue:
			ld a, (de)
			or a, PCG_DIRECTION_LEFT
			ld (de), a
			; if we are not on the left-edge, modify the room to the left:
			ld a, c
			cp ixl
			jr z, pcg_generate_area__additional_connections_loop_x_horizontal_continue2
			dec de
			ld a, (de)
			or a, PCG_DIRECTION_RIGHT
			ld (de), a
pcg_generate_area__additional_connections_loop_x_horizontal_continue2:
		pop de

pcg_generate_area__additional_connections_loop_x_continue:
		ld a, (hl)
		bit PCG_DIRECTION_UP_BIT, a  ; up bit
		jr z, pcg_generate_area__additional_connections_loop_x_continue2
		push de
			; add vertical connection:
			call random_a
			and #01
			jr z, pcg_generate_area__additional_connections_loop_x_vertical_continue
			inc de
pcg_generate_area__additional_connections_loop_x_vertical_continue:
			ld a, (de)
			or a, PCG_DIRECTION_UP
			ld (de), a
			; if we are not on the top-edge, modify the room to the left:
			ld a, b
			cp ixh
			jr z, pcg_generate_area__additional_connections_loop_x_vertical_continue2
			push hl
			ex de, hl
				ld e, ixl
				ld d, 0
				or a
				sbc hl, de
				sbc hl, de
			ex de, hl
			pop hl
			ld a, (de)
			or a, PCG_DIRECTION_DOWN
			ld (de), a
pcg_generate_area__additional_connections_loop_x_vertical_continue2:
		pop de
pcg_generate_area__additional_connections_loop_x_continue2:

pcg_generate_area__additional_connections_loop_x_skip:
		inc hl
		; each room is 2 chunks, so, we skip one column:
		inc de
		inc de
		dec c
		jr nz, pcg_generate_area__additional_connections_loop_x
	pop bc
	; each room is 2 chunks, so, we skip one row:
	push hl
	ex de, hl
		ld e, ixl
		ld d, 0
		add hl, de
		add hl, de
	ex de, hl
	pop hl
	djnz pcg_generate_area__additional_connections_loop_y
	ret


;-----------------------------------------------
; Add random connections:
pcg_generate_area__random_connections
	; make a copy of the division ids, but at chunk resolution, it'll be useful to simplify pointer logic
	call pcg_generate_area__chunk_resolution_division_ids
	ld hl, tmp_pcg_area__piece_types
	ld bc, (current_area__width)
	sla b
	sla c	
	ld ixl, c  ; ixl: width (in chunks)
	ld ixh, b  ; ixh: height (in chunks)
pcg_generate_area__random_connections_loop_y:
	; - hl: piece types ptr
	push bc
pcg_generate_area__random_connections_loop_x:
		ld a, (hl)
		or a
		jp m, pcg_generate_area__random_connections_loop_x_skip

		ld a, c
		cp ixl
		jr z, pcg_generate_area__random_connections_loop_x_horizontal_done  ; we are in the left-most edge of the map
		push bc
			ld de, tmp_pcg_area__division_ids_tmp - tmp_pcg_area__piece_types
			add hl, de
			ld c, (hl)
			dec hl
			ld a, (hl)
			inc hl
			or a
			sbc hl, de
			cp c
		pop bc
		jr nz, pcg_generate_area__random_connections_loop_x_horizontal_done
		call random_a
		and #07
		jr nz, pcg_generate_area__random_connections_loop_x_horizontal_done
		ld a, (hl)
		or a, PCG_DIRECTION_LEFT
		ld (hl), a
		dec hl
		ld a, (hl)
		or a, PCG_DIRECTION_RIGHT
		ld (hl), a
		inc hl
pcg_generate_area__random_connections_loop_x_horizontal_done:

		ld a, b
		cp ixh
		jr z, pcg_generate_area__random_connections_loop_x_vertical_done  ; we are in the top-most edge of the map
		push bc
			ld de, tmp_pcg_area__division_ids_tmp - tmp_pcg_area__piece_types
			add hl, de
			ld c, (hl)
			ld e, ixl
			ld d, 0
			or a
			sbc hl, de
			ld a, (hl)
			add hl, de
			ld de, tmp_pcg_area__piece_types - tmp_pcg_area__division_ids_tmp
			add hl, de
			cp c
		pop bc
		jr nz, pcg_generate_area__random_connections_loop_x_vertical_done
		call random_a
		and #07
		jr nz, pcg_generate_area__random_connections_loop_x_vertical_done
		ld a, (hl)
		or a, PCG_DIRECTION_UP
		ld (hl), a
		ld e, ixl
		ld d, 0
		or a
		sbc hl, de
		ld a, (hl)
		or a, PCG_DIRECTION_DOWN
		ld (hl), a
		add hl, de
pcg_generate_area__random_connections_loop_x_vertical_done:

pcg_generate_area__random_connections_loop_x_skip:
		inc hl
		dec c
		jr nz, pcg_generate_area__random_connections_loop_x
	pop bc
	djnz pcg_generate_area__random_connections_loop_y
	ret


