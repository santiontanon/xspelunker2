tmp_pcg_area__processed: equ buffer_4096

tmp_pcg_area__ptr_to_world_area: equ tmp_pcg_area__processed + MAX_AREA_WIDTH*MAX_AREA_WIDTH


;-----------------------------------------------
; input:
; - e: area ID
pcg_generate_area:
	; get ptr of the area to generate:
	ld hl, current_world__area_data
	ld bc, WORLD_AREA__SIZE
	ld a, e
	or a
	jr z, pcg_generate_area__world_area_ptr_set
pcg_generate_area__world_area_ptr_loop:
	add hl, bc
	dec a
	jr nz, pcg_generate_area__world_area_ptr_loop
pcg_generate_area__world_area_ptr_set:
	ld (tmp_pcg_area__ptr_to_world_area), hl

	; copy seed, ID, width, height
	ld de, current_area__seed
	ld bc, 4 + 1 + 1 + 1
	ldir

	call pcg_generate_area__initialize_room_ids
	call pcg_generate_area__merge_rooms

	; ...

	; 1.- Generate a spanning tree for each division:
	;   - The result is that "pieceTypes" has all the connections necessary for this spanning tree
	; 2.- Complement "pieceTypes" with the "a.connections" generated by PCGWorld
	; 3.- Add random paths (note: 2 & 3 can be done in the same loop)
	; 4.- Place tags (assign room tags to a single chunk position, only one tag per chunk)
	; 5.- Choose chunks. For each position in the map (chunk-level):
	;   - Determine the constraints on the chunks (pool, tags, locations it must have)
	;   - Choose a chunk: write in "current_area__chunks_ids"
	;   - Add necessary objects according to the tag (if any)


; 	ld hl, hardcoded_area_data
; 	ld de, current_area__seed
; 	ld bc, hardcoded_area_data_end - hardcoded_area_data
; 	ldir

	; for now just copy over the hardcoded data:
	ld hl, hardcoded_area_data__chunk_ids
	ld de, current_area__chunks_ids
	ld bc, MAX_AREA_WIDTH * 2 * MAX_AREA_HEIGHT * 2
	ldir
	ret


;-----------------------------------------------
pcg_generate_area__initialize_room_ids:
	ld hl, (tmp_pcg_area__ptr_to_world_area)
	ld bc, WORLD_AREA__DIVISION_IDS_OFFSET
	add hl, bc
	ex de, hl
	ld ix, current_area__room_ids
	ld hl, tmp_pcg_area__processed
	ld bc, (current_area__width)
	ld a, 1  ; next room ID
	ex af, af'
pcg_generate_area__initialize_room_ids_loop_y:
	push bc
		ld b, c
pcg_generate_area__initialize_room_ids_loop_x:
		ld a, (de)  ; division ID
		or a
		jr z, pcg_generate_area__initialize_room_ids_loop_x_no_room
		ex af, af'
			ld (ix), a  ; room ID
			inc a
		ex af, af'
		jp pcg_generate_area__initialize_room_ids_loop_x_continue
pcg_generate_area__initialize_room_ids_loop_x_no_room:
		ld (ix), #ff
pcg_generate_area__initialize_room_ids_loop_x_continue:
		ld (hl), 0  ; processed (used in pcg_generate_area__merge_rooms)
		inc hl
		inc de
		inc ix
		djnz pcg_generate_area__initialize_room_ids_loop_x
	pop bc
	djnz pcg_generate_area__initialize_room_ids_loop_y
	ret


