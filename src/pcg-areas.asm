;-----------------------------------------------
; Pseudocode for this method:
; 0.- mergeAreaRooms
;     - for each position in the map, random change to merge with up/down/left/right as long
;       as it's within division, and as long as room area is <= 4.
; 1.- Generate a spanning tree for each division:
;   - The result is that "pieceTypes" has all the connections necessary for this spanning tree
; 2.- Complement "pieceTypes" with the "a.connections" generated by PCGWorld,
;     inter-area connections and with random paths.
; 3.- Place tags (assign room tags to a single chunk position, only one tag per chunk)
; 4.- Choose chunks. For each position in the map (chunk-level):
;   - Determine the constraints on the chunks (pool, tags, locations it must have)
;   - Choose a chunk
;   - Add necessary objects according to the tag (if any)
; 
; input:
; - e: area ID
pcg_generate_area:
	; get ptr of the area to generate:
	ld hl, current_world__area_data
	ld bc, WORLD_AREA__SIZE
	ld a, e
	or a
	jr z, pcg_generate_area__world_area_ptr_set
pcg_generate_area__world_area_ptr_loop:
	add hl, bc
	dec a
	jr nz, pcg_generate_area__world_area_ptr_loop
pcg_generate_area__world_area_ptr_set:
	ld (tmp_pcg_area__ptr_to_world_area), hl

	; copy seed, ID, width, height
	ld de, current_area__seed
	ld bc, 4 + 1 + 1 + 1
	ldir

	; reset rng:
	ld hl, current_area__seed
	ld de, rng_seed1
	ldi
	ldi
	ldi
	ldi

	call pcg_generate_area__initialize_ptrs
	call pcg_generate_area__initialize_room_ids  ; initializes 'current_area__room_ids'
	call pcg_generate_area__merge_rooms  ; merges rooms in 'current_area__room_ids'
	call pcg_generate_area__division_spanning_trees  ; fills 'tmp_pcg_area__piece_types'
	call pcg_generate_area__additional_connections  ; updates 'tmp_pcg_area__piece_types'
	call pcg_generate_area__random_connections  ; updates 'tmp_pcg_area__piece_types'
	call pcg_generate_area__inter_area_connections  ; updates 'tmp_pcg_area__piece_types'
	call pcg_generate_area__place_tags  ; fills 'tmp_pcg_area__placed_tags'
	jp  pcg_generate_area__choose_chunks  ; fills 'current_area__chunks_ids' and 'current_area__objects'

