;-----------------------------------------------
state_gamestart_sprites:
	incbin "autogenerated/gamestart-sprites.bin"
state_gamestart_sprites_end:


;-----------------------------------------------
state_gamestart:
    ld sp, stack
	call clear_screen_left_to_right

	call disable_VDP_output
		; sprites:
		ld hl, state_gamestart_sprites
		ld de, SPRTBL2
		ld bc, state_gamestart_sprites_end - state_gamestart_sprites
		call fast_LDIRVM

		ld hl, gamestart_tiles_zx0
		ld c, GAMESTART_PAGE
		call decompress_tiles_to_all_banks

		ld hl, gamestart_nametable_zx0
		ld de, buffer_4096
		ld c, GAMESTART_PAGE
		call dzx0_from_page_c

		ld hl, buffer_4096
		ld de, NAMTBL2
		ld bc, 768
		call fast_LDIRVM

		ld de, TEXT_GAMESTART1
		ld hl, copy_text_from_another_page
		ld c, TEXT_PAGE3
		call call_hl_in_page_c_8000
		DRAW_SENTENCE_TO_VDP_REMOTE_MACRO buffer_4096, CHRTBL2 + (256*0 + 128)*8, COLOR_BLUE*16, 10

		ld de, TEXT_GAMESTART2
		ld hl, copy_text_from_another_page
		ld c, TEXT_PAGE3
		call call_hl_in_page_c_8000
		DRAW_SENTENCE_TO_VDP_REMOTE_MACRO buffer_4096, CHRTBL2 + (256*1 + 128)*8, COLOR_BLUE*16, 6

		ld de, TEXT_GAMESTART3
		ld hl, copy_text_from_another_page
		ld c, TEXT_PAGE3
		call call_hl_in_page_c_8000
		DRAW_SENTENCE_TO_VDP_REMOTE_MACRO buffer_4096, CHRTBL2 + (256*2 + 134)*8, COLOR_BLUE*16, 6

		ld a, 1  ; start
		ld (tmp_gamestart_cursor_position1), a
		; look for the end of the current word:
		ld hl, current_world__name + 15
		ld c, 16
state_gamestart_init_loop:
		ld a, (hl)
		cp 26
		jr nz, state_gamestart_init_loop_done
		dec hl
		dec c
		jr nz, state_gamestart_init_loop
state_gamestart_init_loop_done:
		ld a, c
		cp 16
		jr nz, state_gamestart_init_loop_done_continue
		dec a
state_gamestart_init_loop_done_continue:
		ld (tmp_gamestart_cursor_position2), a

		call draw_gamestart_world_name

		ld iy, TEXT_GAMESTART_CONSOLE_MSG1
		ld b, 146
		ld de, NAMTBL2 + 3 + 16*32
		ld ix, CHRTBL2 + 256*2*8
		call state_gamestart_console_paragraph

	call enable_VDP_output

state_gamestart_loop:
	halt
	call draw_gamestart_cursor
	call state_gamestart_update_cursor
	jr state_gamestart_loop
	; jp state_play


;-----------------------------------------------
draw_gamestart_world_name_table:
	db 40, 41, 42, 43, 44, 45, 46, 47
	db 72, 73, 74, 75, 76, 77, 78, 79
	db 96, 97, 98, 99, 100, 101, 102, 103
	db 104, 105, 106, 107, 108, 109, 110, 111

draw_gamestart_world_name:
	ld hl, current_world__name
	ld de, NAMTBL2 + 8 + 6*32
	ld b, 16
draw_gamestart_world_name_loop:
	push bc
	push hl
		ld a, (hl)
		ld hl, draw_gamestart_world_name_table
		ADD_HL_A
		ld a, (hl)
		push de
			push de
				push af
					ex de, hl
					ld b, 1
					call fast_small_FILVRM
				pop af
				add a, 16
			pop hl
			ld bc, 32
			add hl, bc
			ld b, 1
			call fast_small_FILVRM
		pop de
	pop hl
	pop bc
	inc hl
	inc de
	djnz draw_gamestart_world_name_loop

	call gamestart_compute_random_seed
	call gamestart_compute_difficulty
	call gamestart_draw_difficulty
	call gamestart_generate_random_seed_string
	DRAW_SENTENCE_TO_VDP_REMOTE_MACRO buffer_4096, CHRTBL2 + (256*2 + 128)*8, COLOR_WHITE*16, 4
	ret


;-----------------------------------------------
gamestart_generate_random_seed_string:
	ld de, buffer_4096
	ld a, 4
	ld (de), a
	inc de

	ld hl, (current_world__seed)
	ld a, h
	rrca
	rrca
	rrca
	rrca
	and #0f
	call gamestart_draw_random_seed_add_digit
	ld a, h
	and #0f
	call gamestart_draw_random_seed_add_digit
	ld a, l
	rrca
	rrca
	rrca
	rrca
	and #0f
	call gamestart_draw_random_seed_add_digit
	ld a, l
	and #0f
	jp gamestart_draw_random_seed_add_digit


;-----------------------------------------------
; input:
; - a: digit
; - de: ptr where to add
gamestart_draw_random_seed_hex_digits:
	db 22, 24, 26, 28, 30, 32, 35, 37, 39, 41, 108, 110, 112, 114, 116, 118

gamestart_draw_random_seed_add_digit:
	push hl
		ld hl, gamestart_draw_random_seed_hex_digits
		ADD_HL_A
		ld a, (hl)
		ld (de), a
		inc de
	pop hl
	ret


;-----------------------------------------------
gamestart_compute_random_seed:
	ld hl, current_world__name
	ld de, #0000  ; initial seed
	ld b, 8
gamestart_compute_random_seed_loop:
	ld a, (hl)
	xor d
	ld d, a
	inc hl
	ld a, (hl)
	xor e
	ld e, a
	inc hl

	; rotate the seed:
 	ld  a, e
   	rla
   	rl  d
   	rl  e
	djnz gamestart_compute_random_seed_loop

; 	ld de, 5  ; DEBUG
	ld (current_world__seed), de
	ld hl, #5555
	ld (current_world__seed + 2), hl
	ret


;-----------------------------------------------
gamestart_difficulty_settings_easy:
	db 40  ; current_world__difficulty_attack_warn_time
	db 2  ; current_world__difficulty_bullet_speed
	db 2  ; current_world__difficulty_n_cluster_bullets
gamestart_difficulty_settings_easy_end:

gamestart_difficulty_settings_normal:
	db 32  ; current_world__difficulty_attack_warn_time
	db 3  ; current_world__difficulty_bullet_speed
	db 4  ; current_world__difficulty_n_cluster_bullets

gamestart_difficulty_settings_hard:
	db 26  ; current_world__difficulty_attack_warn_time
	db 4  ; current_world__difficulty_bullet_speed
	db 5  ; current_world__difficulty_n_cluster_bullets

gamestart_difficulty_settings_hardest:
	db 20  ; current_world__difficulty_attack_warn_time
	db 5  ; current_world__difficulty_bullet_speed
	db 6  ; current_world__difficulty_n_cluster_bullets


gamestart_compute_difficulty:
	; infer difficulty:
	ld a, (current_world__name)
	ld c, 0
	rrca
	rrca
	rl c
	rrca
	rrca
	rl c
	ld a, c
	ld (current_world__difficulty), a
	ld de, TEXT_DIFFICULTY_EASY
	ld hl, gamestart_difficulty_settings_easy
	or a
	jr z, gamestart_draw_difficulty_set
	ld de, TEXT_DIFFICULTY_NORMAL
	ld hl, gamestart_difficulty_settings_normal
	dec a
	jr z, gamestart_draw_difficulty_set
	ld de, TEXT_DIFFICULTY_HARD
	ld hl, gamestart_difficulty_settings_hard
	dec a
	jr z, gamestart_draw_difficulty_set
	ld de, TEXT_DIFFICULTY_HARDEST
	ld hl, gamestart_difficulty_settings_hardest
gamestart_draw_difficulty_set:
	push de
		ld de, current_world__difficulty_attack_warn_time
		ld bc, gamestart_difficulty_settings_easy_end - gamestart_difficulty_settings_easy
		ldir
	pop de
	ret


;-----------------------------------------------
gamestart_draw_difficulty:
	ld hl, copy_text_from_another_page
	ld c, TEXT_PAGE3
	call call_hl_in_page_c_8000
	DRAW_SENTENCE_TO_VDP_REMOTE_MACRO buffer_4096, CHRTBL2 + (256*2 + 140)*8, COLOR_WHITE*16, 6
	ret


;-----------------------------------------------
draw_gamestart_cursor_offsets:
	db 0, 0, 0, 1, 2, 2, 2, 1
draw_gamestart_cursor:
	; base position: x: c, e, y: b
	ld a, (tmp_gamestart_cursor_position1)
	or a
	jr z, draw_gamestart_cursor_world_name
	dec a
	jr z, draw_gamestart_cursor_start
	dec a
	jr z, draw_gamestart_cursor_back
	; help:
	ld c, 164
	ld e, 200
	ld b, 83
	jr draw_gamestart_cursor_coordinates_set
draw_gamestart_cursor_start:
	ld c, 52
	ld e, 88
	ld b, 83
	jr draw_gamestart_cursor_coordinates_set
draw_gamestart_cursor_back:
	ld c, 108
	ld e, 144
	ld b, 83
draw_gamestart_cursor_coordinates_set:
	ld a, (interrupt_cycle)
	rrca
	and #07
	ld hl, draw_gamestart_cursor_offsets
	ADD_HL_A
	ld a, c
	sub (hl)
	ld c, a  ; x1
	ld a, e
	add a, (hl)
	ld e, a  ; x2

	ld hl, buffer_4096
	ld (hl), b
	inc hl
	ld (hl), c
	inc hl
	ld (hl), 0  ; sprite number
	inc hl
	ld (hl), COLOR_WHITE
	inc hl
	ld (hl), b
	inc hl
	ld (hl), e
	inc hl
	ld (hl), 4  ; sprite number
	inc hl
	ld (hl), COLOR_WHITE
	inc hl
	ld hl, buffer_4096
	ld de, SPRATR2
	ld b, 8
	jp fast_small_LDIRVM

draw_gamestart_cursor_world_name:
	ld a, (tmp_gamestart_cursor_position2)
	add a, a
	add a, a
	add a, a
	add a, 64
	ld hl, buffer_4096
	ld (hl), 47
	inc hl
	ld (hl), a
	inc hl
	ld (hl), 8  ; sprite number
	inc hl
	ld a, (interrupt_cycle)
	bit 3, a
	jr z, draw_gamestart_cursor_world_name_color_transparent
	ld a, COLOR_WHITE
	jr draw_gamestart_cursor_world_name_color_set
draw_gamestart_cursor_world_name_color_transparent:
	xor a
draw_gamestart_cursor_world_name_color_set:
	ld (hl), a
	inc hl
	ld (hl), 200
	inc hl
	ld (hl), 0
	inc hl
	ld (hl), 4  ; sprite number
	inc hl
	ld (hl), COLOR_WHITE
	inc hl
	ld hl, buffer_4096
	ld de, SPRATR2
	ld b, 8
	jp fast_small_LDIRVM


;-----------------------------------------------
state_gamestart_update_cursor:
	ld a, (tmp_gamestart_cursor_position1)
	or a
	jr z, state_gamestart_update_cursor_world_name
	call update_keyboard_buffers
	ld a, (keyboard_clicks)
	bit KEY_RIGHT_BIT, a  ; right
	push af
		call nz, state_gamestart_update_cursor_right
	pop af
	bit KEY_UP_BIT, a  ; up
	push af
		call nz, state_gamestart_update_cursor_up
	pop af
	bit KEY_LEFT_BIT, a  ; left
	push af
		call nz, state_gamestart_update_cursor_left
	pop af
	bit KEY_WEAPON_BIT, a
	push af
		call nz, state_gamestart_update_cursor_button
	pop af	
	ret
state_gamestart_update_cursor_right:
	ld a, (tmp_gamestart_cursor_position1)
	inc a
	cp 4
	ret z
state_gamestart_update_cursor_move_set:
	ld (tmp_gamestart_cursor_position1), a
	ld hl, SFX_ui_move
	jp play_SFX_with_high_priority

state_gamestart_update_cursor_up:
	call getcharacter_nonwaiting_reset  ; get ready to move into the world name
	xor a
	jr state_gamestart_update_cursor_move_set

state_gamestart_update_cursor_left:
	ld a, (tmp_gamestart_cursor_position1)
	dec a
	ret z
	jr state_gamestart_update_cursor_move_set

state_gamestart_update_cursor_world_name:
	; cursor is over the wolrd name:
	call getcharacter_nonwaiting
	or a
	ret z
	cp #1f
	jr z, state_gamestart_update_cursor_world_name_down
	cp #0d
	jr z, state_gamestart_update_cursor_world_name_down
	cp #1d
	jr z, state_gamestart_update_cursor_left_name
	cp #1c
	jr z, state_gamestart_update_cursor_right_name
	cp #08
	jr z, state_gamestart_update_cursor_name_delete
	cp ' '
	jr z, state_gamestart_update_cursor_enter_character_space
	cp '0'
	ret c
	cp '4' + 1
	jr c, state_gamestart_update_cursor_enter_character_number
	cp 'a'
	ret c
	cp 'z' + 1
	jr c, state_gamestart_update_cursor_enter_character_letter
	ret

state_gamestart_update_cursor_world_name_down:
	ld a, 1
	jr state_gamestart_update_cursor_move_set

state_gamestart_update_cursor_enter_character_space:
	ld c, 26
	jr state_gamestart_update_cursor_enter_character
state_gamestart_update_cursor_enter_character_number:
	add a, 27 - '0'
	ld c, a
	jr state_gamestart_update_cursor_enter_character
state_gamestart_update_cursor_enter_character_letter:
	sub 'a'
	ld c, a	
state_gamestart_update_cursor_enter_character:
	ld a, (tmp_gamestart_cursor_position2)
	cp 15
	jr z, state_gamestart_update_cursor_enter_character_error
	ld hl, current_world__name
	ADD_HL_A
	ld (hl), c
	ld hl, SFX_ui_move
	call play_SFX_with_high_priority
	call draw_gamestart_world_name
	ld a, (tmp_gamestart_cursor_position2)
	cp 15
	ret z
	inc a
	ld (tmp_gamestart_cursor_position2), a
	ret

state_gamestart_update_cursor_name_delete:
	ld a, (tmp_gamestart_cursor_position2)
	or a
	jr z, state_gamestart_update_cursor_name_delete_continue
	dec a
	ld (tmp_gamestart_cursor_position2), a
state_gamestart_update_cursor_name_delete_continue:
	ld hl, current_world__name
	ADD_HL_A
	ld (hl), 26  ; space
	ld hl, SFX_ui_move
	call play_SFX_with_high_priority
	jp draw_gamestart_world_name

state_gamestart_update_cursor_right_name:
	ld a, (tmp_gamestart_cursor_position2)
	cp 15
	ret z
	inc a
state_gamestart_update_cursor_name_position_set:
	ld (tmp_gamestart_cursor_position2), a
	ld hl, SFX_ui_move
	jp play_SFX_with_high_priority

state_gamestart_update_cursor_left_name:
	ld a, (tmp_gamestart_cursor_position2)
	or a
	ret z
	dec a
	jr state_gamestart_update_cursor_name_position_set

state_gamestart_update_cursor_enter_character_error:
	ld hl, SFX_ui_wrong
	jp play_SFX_with_high_priority

state_gamestart_update_cursor_button:
	ld a, (tmp_gamestart_cursor_position1)
	or a
	ret z
	dec a
	jr z, state_gamestart_update_cursor_start
	dec a
	jr z, state_gamestart_update_cursor_back
	dec a
	jr z, state_gamestart_update_cursor_help
	ret

state_gamestart_update_cursor_start:
	call clear_all_the_sprites
	call gamestart_clear_console
	ld hl, SFX_ui_select
	call play_SFX_with_high_priority
	ld iy, TEXT_GAMESTART_CONSOLE_MSG4
	ld b, 146
	ld de, NAMTBL2 + 3 + 16*32
	ld ix, CHRTBL2 + 256*2*8
	call state_gamestart_console_paragraph

	ld hl, pcg_generate_world
	ld c, PCG_PAGE_WORLD
	call call_hl_in_page_c_8000
	jp z, state_play

	; Generation failed:
	call gamestart_clear_console
	ld hl, SFX_ui_wrong
	call play_SFX_with_high_priority
	ld iy, TEXT_GAMESTART_CONSOLE_MSG5
	ld b, 146
	ld de, NAMTBL2 + 3 + 16*32
	ld ix, CHRTBL2 + 256*2*8
	jp state_gamestart_console_paragraph


state_gamestart_update_cursor_back:
	ld hl, SFX_ui_select
	call play_SFX_with_high_priority
    ld hl, state_braingames
    ld a, BRAINGAMES_PAGE
    jp jp_to_hl_in_page_a_8000

state_gamestart_update_cursor_help:
	call clear_all_the_sprites
	ld hl, SFX_ui_select
	call play_SFX_with_high_priority
	ld iy, TEXT_GAMESTART_CONSOLE_MSG2
	ld b, 146
	ld de, NAMTBL2 + 3 + 16*32
	ld ix, CHRTBL2 + 256*2*8
	call state_gamestart_console_paragraph
state_gamestart_update_cursor_help_loop:
	halt
	call update_keyboard_buffers
	ld a, (keyboard_clicks)
	bit KEY_WEAPON_BIT, a
	jr z, state_gamestart_update_cursor_help_loop
	ld iy, TEXT_GAMESTART_CONSOLE_MSG3
	ld b, 146
	ld de, NAMTBL2 + 3 + 16*32
	ld ix, CHRTBL2 + 256*2*8
	jp state_gamestart_console_paragraph


;-----------------------------------------------
gamestart_clear_console:
	ld hl, NAMTBL2 + 3 + 16*32
	ld b, 6
gamestart_clear_console_loop:
	push bc
		push hl
			ld b, 16
			xor a
			call fast_small_FILVRM
		pop hl
		ld bc, 32
		add hl, bc
	pop bc
	djnz gamestart_clear_console_loop
	ret


;-----------------------------------------------
; input:
; - iy: text
; - b: first tile to use
; - de: NAMTBL2 ptr
; - ix: base CHRTBL2 address (1st, 2nd or 3rd bank?)
state_gamestart_console_paragraph:
	ld hl, (tmp_gamestart_cursor_position1)
	push hl
		ld a, 16
		ld (tmp_letter_line_width), a
		ld a, #f0
		ld (tmp_letter_line_color), a	
		ld hl, display_paragraph_text_page3
		ld c, TABLET_LETTER_PAGE
		call call_hl_in_page_c_8000
	pop hl
	ld (tmp_gamestart_cursor_position1), hl
	ret


