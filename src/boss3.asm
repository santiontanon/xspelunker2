; input:
; - a: tile number that was hit
; - iyh: damage to deal
player_weapon_hitbox_check_boss__boss3_hit:
	; hit the main body:
	; ...

	; hit the head:
	ld hl, (boss__hp)
	ld a, h
	or l
	ret z  ; boss HP are already 0
	ld a, iyh
	or a
	jr z, player_weapon_hitbox_check_boss__boss3_hit_continue2
player_weapon_hitbox_check_boss__boss3_hit_loop:
	dec hl
	jr z, player_weapon_hitbox_check_boss__boss3_hit_continue2
	dec a
	jr nz, player_weapon_hitbox_check_boss__boss3_hit_loop
player_weapon_hitbox_check_boss__boss3_hit_continue2:
	ld (boss__hp), hl
	ld a, 4
	ld (boss__hit_timer), a

	ld hl, SFX_enemy_hit
	call play_SFX_with_high_priority
	xor a
	ld (player_weapon_hitbox_check_result), a  ; mark a hit
	ld a, iyl
	ld (boss__last_collision_id), a
	ret


;-----------------------------------------------
boss3_move_left:
	ld hl, boss__x
	ld a, (hl)
	cp 2
	ret z
	dec (hl)
	ret


;-----------------------------------------------
boss3_move_right:
	ld hl, boss__x
	ld a, (hl)
	cp 21
	ret z
	inc (hl)
	ret

