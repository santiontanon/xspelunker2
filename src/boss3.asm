	jp z, update_boss3_behavior_2  ; dashing
	dec a
	jp z, update_boss3_behavior_3  ; stomping
	jp update_boss3_behavior_4  ; death


;-----------------------------------------------
update_boss3_behavior_0:
	ld a, (boss__state)
	or a
	jr nz, update_boss3_behavior_0_wait_for_player
update_boss3_behavior_init:
	ld a, (current_world__difficulty)
	ld hl, boss3_difficulty_setting__easy
	or a
	jr z, update_boss3_behavior_init_continue
	ld hl, boss3_difficulty_setting__normal
	dec a
	jr z, update_boss3_behavior_init_continue
	dec a
	ld hl, boss3_difficulty_setting__hard
	jr z, update_boss3_behavior_init_continue
	ld hl, boss3_difficulty_setting__hardest
update_boss3_behavior_init_continue:
	ld de, boss__3_settings
	ld bc, 12
	ldir

	ld a, 23
	ld (boss__x), a
	ld a, 13
	ld (boss__y), a
	ld hl, (boss__3_settings + BOSS_2_HP_OFFSET)
	ld (boss__hp), hl
	ld hl, player_weapon_hitbox_check_boss__boss3_hit
	ld (boss__hit_fn), hl
	inc a
	ld (boss__state), a

