player_weapon_hitbox_check_boss__boss3_hit:
	; hit the main body:
	ld a, e
	cp 4 * 16 + 12  ; first non head tile
	jp c, player_weapon_hitbox_check_boss__lose_hp  ; hit the head
	ld hl, SFX_shield
	call play_SFX_with_high_priority
	xor a
	ld (player_weapon_hitbox_check_result), a  ; mark a hit
	ld hl, boss__last_collision_id_3
	ld de, boss__last_collision_id_4
	ldd
	ldd
	ldd
	ld a, iyl
	ld (boss__last_collision_id_1), a
	ret


