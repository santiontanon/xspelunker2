update_boss3_behavior:
	ld hl, boss__hit_timer
	ld a, (hl)
	or a
	jr z, update_boss3_behavior_continue
	dec (hl)
update_boss3_behavior_continue:
	ld a, (boss__active)
	or a
	ret z

	ld a, (boss__3_head_attached)
	or a
	call nz, update_boss3_head_behavior  ; head dettached

	ld a, (boss__behavior)
	or a
	jp z, update_boss3_behavior_0  ; before boss is spawned
	dec a
	jp z, update_boss3_behavior_1  ; walking
	dec a
	jp z, update_boss3_behavior_2  ; stomping
	jp update_boss3_behavior_3  ; death


;-----------------------------------------------
update_boss3_behavior_0:
	ld a, (boss__state)
	or a
	jr nz, update_boss3_behavior_0_wait_for_player
update_boss3_behavior_init:
	ld a, (current_world__difficulty)
	ld hl, boss3_difficulty_setting__easy
	or a
	jr z, update_boss3_behavior_init_continue
	ld hl, boss3_difficulty_setting__normal
	dec a
	jr z, update_boss3_behavior_init_continue
	dec a
	ld hl, boss3_difficulty_setting__hard
	jr z, update_boss3_behavior_init_continue
	ld hl, boss3_difficulty_setting__hardest
update_boss3_behavior_init_continue:
	ld de, boss__settings
	ld bc, 12
	ldir

	ld a, 21
	ld (boss__x), a
	add a, 3
	ld (boss__x2), a
	ld a, 13
	ld (boss__y), a
	ld a, -4
	ld (boss__y2), a
	ld hl, (boss__settings + BOSS_3_HP_OFFSET)
	ld (boss__hp), hl
	ld hl, player_weapon_hitbox_check_boss__boss3_hit
	ld (boss__hit_fn), hl
	ld a, BOSS_PAGE
	ld (boss__hit_fn_page), a
	ld a, 1
	ld (boss__3_head_attached), a
	ld (boss__state), a

	; spawn object for sprite decorations
	call ptr_to_new_sprite_object
	ret nz
	ld (hl), 0  ; ID
	inc hl
	ld (hl), SPRITE_OBJECT_TYPE_BOSS_EXTRAS
	ret

update_boss3_behavior_0_wait_for_player:
	xor a
	call update_boss3_draw_boss_frame

	ld a, (player_x + 1)  ; tile x
	cp 16
	ret c

	; appear!
	ld a, 1
	ld (boss__behavior), a

	; head comes crashing down:
	ld b, 17
update_boss3_behavior_0_head_drop_loop:
	push bc
		ld a, 14
		sub b
		ld (boss__y2), a
		xor a
		call update_boss3_draw_boss_frame
		ld hl, draw_room_with_hud
		ld c, TILES_PAGE
		call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at		
		halt
		halt
	pop bc
	djnz update_boss3_behavior_0_head_drop_loop
	ld hl, SFX_explosion_low_pitch
	call play_SFX_with_high_priority

	xor a
	ld (boss__3_head_attached), a	
	call update_boss3_draw_boss_frame
	ld hl, draw_room_with_hud
	ld c, TILES_PAGE
	call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at		

	ld hl, boss3_name_initial_sprite_attributes
	ld de, boss3_name_y_table
	call update_boss_behavior_bring_name_down	

	ld b, 200
	call wait_b_halts_skippable
	ld hl, boss3_name_initial_sprite_attributes
	ld de, boss3_name_y_table + 23
	jp update_boss_behavior_bring_name_up


