update_boss3_behavior_1:
	ld a, (boss__state)
	or a
	jr z, update_boss3_behavior_1_state_0  ; idle
	dec a
	jp z, update_boss3_behavior_1_state_1  ; walk left
	dec a
	jp z, update_boss3_behavior_1_state_2  ; walk right
	dec a
	jp z, update_boss3_behavior_1_state_3  ; dash left
	ret

update_boss3_behavior_1_state_0:
	; idle:
	xor a
	call update_boss3_draw_boss_frame

	ld hl, boss__state_timer
	inc (hl)
	ld a, (boss__settings + BOSS_3_WAIT_TIME_OFFSET)
	cp (hl)
	ret nz

	; chance of dashing (only if boss is towards the right, and player is towards the left and down):
	ld a, (boss__x)
	cp 16
	jr c, update_boss3_behavior_1_state_1_done
	ld a, (player_x + 1)
	cp 20
	jr nc, update_boss3_behavior_1_state_1_done
	ld a, (player_y + 1)
	cp 12
	jr c, update_boss3_behavior_1_state_1_done
	call random_a
	and #01
	jr z, update_boss3_behavior_1_state_1_done
	; dash!
	ld a, 3
	ld (boss__state), a
	xor a
	ld (boss__state_timer), a
	ret

update_boss3_behavior_1_state_1_done:
update_boss3_behavior_1_state_2_done:
	ld hl, (boss__hp)
	ld a, h
	or l
	jr z, update_boss3_behavior_1_state_1_to_death
	; chance of:
	; - idle: 0
	; - walk: 1, 2
	; - stomp: 3
	; - dettach head (if attached, otherwise, walk): 4
	ld c, 5
	call random_modulo
; 	ld a, 4  ; DEBUG
	or a
	jr z, update_boss3_behavior_1_state_1_to_idle
	cp 3
	jr z, update_boss3_behavior_1_state_1_to_stomp
	cp 4
	jr z, update_boss3_behavior_1_state_1_to_dettach_head
update_boss3_behavior_1_state_1_to_walk:
	call random_a
	and #03
	jr z, update_boss3_behavior_1_state_1_walk_away
	; walk to player
	ld a, (boss__x)
	add a, 4
	ld c, a
	ld a, (player_x + 1)
	cp c
	jr c, update_boss3_behavior_1_state_1_walk_left
	jr update_boss3_behavior_1_state_1_walk_right

update_boss3_behavior_1_state_1_walk_away:
	; walk to player
	ld a, (boss__x)
	add a, 4
	ld c, a
	ld a, (player_x + 1)
	cp c
	jr nc, update_boss3_behavior_1_state_1_walk_left
update_boss3_behavior_1_state_1_walk_right:
	ld a, 2
	ld (boss__state), a
	xor a
	ld (boss__state_timer), a
	ret

update_boss3_behavior_1_state_1_walk_left:
	ld a, 1
	ld (boss__state), a
	xor a
	ld (boss__state_timer), a
	ret

update_boss3_behavior_1_state_1_to_idle:
	xor a
	ld (boss__state), a
	ld (boss__state_timer), a
	ret

update_boss3_behavior_1_state_1_to_stomp:
	ld a, 2
	ld (boss__behavior), a
	xor a
	ld (boss__state), a
	ld (boss__state_timer), a
	ret

update_boss3_behavior_1_state_1_to_death:
	call stop_music
	xor a
	ld (boss__state), a
	ld (boss__state_timer), a
	ld a, 3
	ld (boss__behavior), a
	ret

update_boss3_behavior_1_state_1_to_dettach_head:
	ld a, (boss__3_head_attached)
	or a
	jr nz, update_boss3_behavior_1_state_1_to_walk  ; head is already dettached, keep walking
	; dettach head:
	ld a, (boss__x)
	add a, 3
	ld (boss__x2), a
	ld a, (boss__y)
	ld (boss__y2), a
	xor a
	ld (boss__3_head_state), a
	ld (boss__3_head_state_timer), a
	inc a
	ld (boss__3_head_attached), a
	jr update_boss3_behavior_1_state_1_to_idle


update_boss3_behavior_1_state_1:
	; walk forward:
	; walk frames loop: 1, 2, 3, 4
	ld c, 1  ; frame
	ld a, (boss__settings + BOSS_3_WALK_TIME_MASK_OFFSET)
	ld e, a
	ld a, (boss__settings + BOSS_3_WALK_TIME_OFFSET)
	ld b, a
	ld hl, boss__state_timer
	ld a, (hl)
	and e
	call z, boss3_move_left
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
update_boss3_behavior_1_state_1_loop:
	sub b
	jr c, update_boss3_behavior_1_state_1_frame_set
	inc c
	jr update_boss3_behavior_1_state_1_loop
update_boss3_behavior_1_state_1_frame_set:
	ld a, c
	cp 5
	jp c, update_boss3_draw_boss_frame
	call boss3_move_right
	jp update_boss3_behavior_1_state_1_done

update_boss3_behavior_1_state_2:
	; walk backwards:
	; walk frames loop: 4, 3, 3, 1
	ld c, 4  ; frame
	ld a, (boss__settings + BOSS_3_WALK_TIME_MASK_OFFSET)
	ld e, a
	ld a, (boss__settings + BOSS_3_WALK_TIME_OFFSET)
	ld b, a
	ld hl, boss__state_timer
	ld a, (hl)
	and e
	call z, boss3_move_right
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
update_boss3_behavior_1_state_2_loop:
	sub b
	jr c, update_boss3_behavior_1_state_2_frame_set
	dec c
	jr update_boss3_behavior_1_state_2_loop
update_boss3_behavior_1_state_2_frame_set:
	ld a, c
	or a
	jp nz, update_boss3_draw_boss_frame
	call boss3_move_left
	jp update_boss3_behavior_1_state_2_done

update_boss3_behavior_1_state_3:
	; dash:
	; walk frames loop: 1, 2, 3, 4
	ld c, 1  ; frame
	ld a, (boss__settings + BOSS_3_DASH_TIME_MASK_OFFSET)
	ld e, a
	ld a, (boss__settings + BOSS_3_DASH_TIME_OFFSET)
	ld b, a
	ld hl, boss__state_timer
	ld a, (hl)
	and e
	call z, boss3_move_left
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
update_boss3_behavior_1_state_3_loop:
	sub b
	jr c, update_boss3_behavior_1_state_3_frame_set
	inc c
	jr update_boss3_behavior_1_state_3_loop
update_boss3_behavior_1_state_3_frame_set:
	ld a, c
	cp 5
	jp c, update_boss3_draw_boss_frame
	ld a, (boss__x)
	cp BOSS_3_MIN_X
	jp z, update_boss3_behavior_1_state_1_to_idle
	call boss3_move_right
	ld a, 1
	ld (boss__state_timer), a
	ret


