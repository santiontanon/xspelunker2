			inc hl
			inc de
			djnz draw_boss7_snake_part_loop_x
draw_boss7_snake_part_loop_y_skip2:
		pop de
		ex de, hl
		ld a, (current_room__width)
		; ld b, 0
		ld c, a
		add hl, bc
		ex de, hl
	pop bc
	djnz draw_boss7_snake_part_loop_y
	ret
draw_boss7_snake_part_loop_y_skip:
			; advance 'hl':
			ld b, 0
			add hl, bc
			jr draw_boss7_snake_part_loop_y_skip2


