	ld de, TEXT_MOON_BOSS_1
	ld hl, display_in_game_message_textpage4
	ld c, TEXT_PAGE
	call call_hl_in_page_c_8000

	; appear!
	xor a
	ld (boss__state), a
	inc a
	ld (boss__behavior), a

	; snake face appears:
	ld b, 6  ; 6 frames animation of appearing
update_boss7_behavior_0_wait_for_player_appearing_loop:
