	; - e: direction of player in x axis
	; - d: direction of player in y axis
	; which difference is larger?
	ld a, c
	cp b
	jr nc, update_boss7_update_snake_state_2_add_new_piece_following_player_x_diff_larger
	; swap e,db:
	ld a, e
	ld e, d
	ld d, a
