	or a
	ret z
	dec a
	add a, a
	ld hl, boss7_phase1_frame_ptrs
	ADD_HL_A
	ld a, (hl)
	inc hl
	ld h, (hl)
	ld l, a
	push hl
		ld bc, (boss__x2)
		call get_room_tile_ptr
		ex de, hl  ; hl = ptr where the boss is to be drawn
	pop ix
