update_boss7_behavior_0:
	ld a, (boss__state)
	or a
	jr nz, update_boss7_behavior_0_wait_for_player

update_boss7_behavior_init:
	ld a, (current_world__difficulty)
	ld hl, boss7_difficulty_setting__easy
	or a
	jr z, update_boss7_behavior_init_continue
	ld hl, boss7_difficulty_setting__normal
	dec a
	jr z, update_boss7_behavior_init_continue
	dec a
	ld hl, boss7_difficulty_setting__hard
	jr z, update_boss7_behavior_init_continue
	ld hl, boss7_difficulty_setting__hardest
update_boss7_behavior_init_continue:
	ld de, boss__settings
	ld bc, 12
	ldir

	ld a, 55
	ld (boss__x), a
	ld a, 4
	ld (boss__y), a
	ld a, 51
	ld (boss__x2), a
	ld a, 6
	ld (boss__y2), a
	ld hl, (boss__settings + BOSS_7_HP_OFFSET)
	ld (boss__hp), hl
	ld hl, player_weapon_hitbox_check_boss__boss7_hit
	ld (boss__hit_fn), hl
	ld a, BOSS_7_PAGE
	ld (boss__hit_fn_page), a
	ld a, 1
	ld (boss__state), a
	xor a
	ld (boss__7_snake1_head_x), a
	ld (boss__7_snake1_head_y), a
	ld (boss__7_snake1_head_eye_sprite), a
	ld (boss__7_snake1_mouth_open), a
	ld (boss__7_snake1_movement_counter), a
	ld (boss__7_snake1_snake_length), a
	ld (boss__7_snake1_head_direction), a
	ld (boss__7_snake1_head_offset), a
	ld (boss__7_snake1_tail_offset), a
	ld a, PCG_DIRECTION_UP
	ld (boss__7_snake1_tail_direction), a

