update_boss7_to_behavior_2:
	ld a, 2
	ld (boss__behavior), a
	xor a
	ld (boss__state), a
	ld (boss__state_timer), a
	ret
update_boss7_behavior_2:
	; states:
	; 0: statue breaking (then go to 1)
	; 1: decide which position to go to next
	; 2: moving to the target posision (then go to 3)
	; 3: waiting (then go to 1, or 4)
	; 4: spit attack (then go to 1)
	ld a, (boss__state)
	or a
	jr z, update_boss7_behavior_2_state_0
	dec a
	jp z, update_boss7_behavior_2_state_1
	dec a
	jp z, update_boss7_behavior_2_state_2
	dec a
	jp z, update_boss7_behavior_2_state_3
	dec a
	jp z, update_boss7_behavior_2_state_4
	ret

update_boss7_behavior_2_state_0:
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
	cp 24
	jr nz, update_boss7_behavior_2_state_0_continue
	push af
		ld bc, #113a  ; 58, 17  ; position of the tail (which will not be drawn in phase 2)
		ld (boss__x), bc

		; no snake for the transition to the new tileset:
		ld a, #ff
		ld (tile_enemy_work_memory), a  ; initialize the snake clear array too
		ld (tile_enemy_work_memory + 32), a  ; initialize the snake clear array too

		; draw broken statue + snake:
		call update_boss7_draw_phase2_boss_frame
		ld hl, draw_room_with_hud
		ld c, TILES_PAGE
		call call_hl_in_page_c_8000

		; switch to the new tileset & collision tables:
		ld hl, boss_7_phase2_tiles_zx0
		ld c, BOSS_7_PAGE
		ld (current_room__tileset_ptr), hl
		call setup_game_tiles_only_biome

		; initial position of the snake:
		ld a, 1
		ld (boss__7_target_phase2_position), a
		ld hl, update_boss7_behavior_2_snake_position_out_up
		ld de, tile_enemy_work_memory
		ld bc, 4
		ldir
		ld de, current_room__tile_map + 58 + 17*64
		ld (boss__7_snake1_undraw_ptr), de

		call update_boss7_draw_phase2_boss_frame  ; draw snake now that we have the tileset
		ld hl, draw_room_with_hud
		ld c, TILES_PAGE
		call call_hl_in_page_c_8000

		ld hl, tile_collision_types_boss7_phase2
		ld (current_room__collision_ptr), hl
		ld de, current_room__collision_table
		ld bc, 256
		ldir
	pop af
update_boss7_behavior_2_state_0_continue:
	cp 32
	jr z, update_boss7_behavior_2_to_state_1
	and #01
	ret nz
	; spawn an explosion:
	ld bc, #0636  ; 54, 6
	call random_a
	and #07
	add a, c
	ld c, a
	call random_a
	and #07
	add a, b
	ld b, a
	jp spawn_explosion

update_boss7_behavior_2_to_state_1:
	ld a, 1
	ld (boss__state), a
	ret

update_boss7_behavior_2_state_1:
	; phase 3?
	ld bc, (boss__settings + BOSS_7_HP_PHASE3_OFFSET)
	ld hl, (boss__hp)
	or a
	sbc hl, bc
	ld c, 0  ; hide
	jp c, update_boss7_behavior_2_state_1_target_set  ; if we are moving to phase 3, to go hiding!

	; decide where to go next:
	; if player x < 34: 0
	; if player_x > 57: 1
	; if player_x > 50: 2
	; if player_y < 6: 3
	; if player_y < 11: 4
	; if player_y < 16: 5
	; else: 6
	ld c, 0
	ld a, (player_x + 1)
	cp 34
	jr c, update_boss7_behavior_2_state_1_target_set
	inc c  ; c = 1
	cp 58
	jr nc, update_boss7_behavior_2_state_1_target_set
	inc c  ; c = 2
	cp 51
	jr nc, update_boss7_behavior_2_state_1_target_set
	ld a, (player_y + 1)
	inc c  ; c = 3
	cp 6
	jr c, update_boss7_behavior_2_state_1_target_set
	inc c  ; c = 4
	cp 11
	jr c, update_boss7_behavior_2_state_1_target_set
	inc c  ; c = 5
	cp 16
	jr c, update_boss7_behavior_2_state_1_target_set
	inc c  ; c = 6
update_boss7_behavior_2_state_1_target_set:
	ld a, c
	ld (boss__7_target_phase2_position), a
	xor a
	ld (boss__state_timer), a
	ld a, 2
	ld (boss__state), a
	ret


update_boss7_behavior_2_state_2:
	; move to the target position:
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
	and #03
	ret nz

	; See what do we need to do:
	; - if current_snake_pieces match target and boss__7_snake1_head_offset == 0: done!
	; - if current_snake_pieces match target and boss__7_snake1_head_offset > 0: boss__7_snake1_head_offset--
	; - if current_snake_pieces does not match target: (mismatch in "i")
	;   - if current_snake_pieces[i] == 2 (we need extra pieces):
	;     - if boss__7_snake1_head_offset > 0: boss__7_snake1_head_offset--
	;     - if boss__7_snake1_head_offset == 0: add new piece, and set boss__7_snake1_head_offset = 2
	;   - if current_snake_pieces[i] != 2 (we need to backtrack):
	;     - if boss__7_snake1_head_offset < 2: boss__7_snake1_head_offset++
