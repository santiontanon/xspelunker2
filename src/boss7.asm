update_boss7_draw_snake:
	; make a copy of the snake as it is right now, so we can erase it later:
	ld l, (iy + BOSS_7_SNAKE_STRUCT_PIECES_PTR)
	ld h, (iy + BOSS_7_SNAKE_STRUCT_PIECES_PTR + 1)	
	ld e, l
	ld d, h
	ld bc, 16
	add hl, bc
	ex de, hl
	ld bc, 16
	ldir

	xor a
	ld (iy + BOSS_7_SNAKE_STRUCT_LENGTH), a
	ld (tmp_boss__7_snake_tail_draw_ptr), a
	ld (tmp_boss__7_snake_tail_draw_ptr + 1), a
	ld a, (iy + BOSS_7_SNAKE_STRUCT_TAIL_DIRECTION)
	ld (iy + BOSS_7_SNAKE_STRUCT_TAIL_DIRECTION_UNDRAW), a

	ld a, iyl
	cp boss__7_snake1_struct % 256
	jr nz, update_boss7_draw_snake2
