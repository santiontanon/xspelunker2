; input:
update_boss7_draw_phase2_boss_frame:
	; in phase 2:
	; - frame 1 is the statue
	; - snake is handled in a special way
	call update_boss7_undraw_snake
	ld hl, draw_boss_frame_clear_previous_frame_1
	ld c, BOSS_PAGE
	call call_hl_in_page_c_8000

	call update_boss7_draw_snake

	; draw statue:
	ld de, current_room__tile_map + 56 + 13*64
	ld ix, boss7_statue_frame_2
	ld c, BOSS_PAGE
	ld hl, draw_boss_frame_1_without_clearing_ix
	call call_hl_in_page_c_8000

	ld hl, redraw_flags
	set ROOM_REDRAW_FLAG_BIT, (hl)	
	ret


;-----------------------------------------------
update_boss7_draw_snake:
	; make a copy of the snake as it is right now, so we can erase it later:
	ld hl, tile_enemy_work_memory
	ld de, tile_enemy_work_memory + 32
	ld bc, 32
	ldir

	ld bc, (boss__x)
	call get_room_tile_ptr
	ex de, hl  ; de = ptr where the snake is to be drawn

	; draw the snake:
	ld hl, tile_enemy_work_memory
update_boss7_draw_snake_loop:
	ld a, (hl)
	cp #ff
	ret z

	; draw piece:
	; here:
	; - hl: ptr to the current piece
