draw_boss7_snake_part:
	ld bc, #0504
draw_boss7_snake_part_loop_y:
	push bc
		push de
			; if "de" < current_room__tile_map, skip row  ->  draw_boss7_snake_part_loop_y_skip
			ex de, hl
			push bc
			push hl
				ld bc, current_room__tile_map
				or a  ; clear carry flag
				sbc hl, bc
			pop hl
			pop bc
			ex de, hl
			jr c, draw_boss7_snake_part_loop_y_skip

			ld b, c
draw_boss7_snake_part_loop_x:
			ld a, (hl)
			or a
			jr z, draw_boss7_snake_part_loop_x_skip
			ld (de), a
