update_boss7_to_behavior_2:
	ld a, 2
	ld (boss__behavior), a
	xor a
	ld (boss__state), a
	ld (boss__state_timer), a
	ret
update_boss7_behavior_2:
	; states:
	; 0: statue breaking (then go to 1)
	; 1: decide which position to go to next
	; 2: moving to the target posision (then go to 3)
	; 3: waiting (then go to 1, or 4)
	; 4: spit attack (then go to 1)
	ld a, (boss__state)
	or a
	jr z, update_boss7_behavior_2_state_0
	dec a
	jp z, update_boss7_behavior_2_state_1
	; ...
	ret

update_boss7_behavior_2_state_0:
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
	or a
	jr nz, update_boss7_behavior_2_state_0_continue
	push af
		ld bc, #1039  ; 57, 16  ; position of the tail (which will not be drawn in phase 2)
		ld (boss__x), bc

		ld hl, tile_enemy_work_memory
		ld (hl), #ff  ; end of snake (basically, draw nothing)

		; draw broken statue + snake:
		call update_boss7_draw_phase2_boss_frame

		ld hl, draw_room_with_hud
		ld c, TILES_PAGE
		call call_hl_in_page_c_8000

		; switch to the new tileset & collision tables:
		ld hl, boss_7_phase2_tiles_zx0
		ld c, BOSS_7_PAGE
		ld (current_room__tileset_ptr), hl
		call setup_game_tiles_only_biome

		ld hl, tile_collision_types_boss7_phase2
		ld (current_room__collision_ptr), hl
		ld de, current_room__collision_table
		ld bc, 256
		ldir
	pop af
update_boss7_behavior_2_state_0_continue:
	cp 32
	jr z, update_boss7_behavior_2_to_state_1
	and #01
	ret nz
	; spawn an explosion:
	ld bc, #0636  ; 54, 6
	call random_a
	and #07
	add a, c
	ld c, a
	call random_a
	and #07
	add a, b
	ld b, a
	jp spawn_explosion

update_boss7_behavior_2_to_state_1:
	xor a
	ld (boss__state_timer), a
	inc a
	ld (boss__state), a

	; snake inside of the statue:
	ld hl, tile_enemy_work_memory
	ld (hl), 0
	inc hl
	ld (hl), #ff
	xor a
	ld (boss__7_head_offset), a
	jp update_boss7_draw_phase2_boss_frame

update_boss7_behavior_2_state_1:
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
	or a
	jr nz, update_boss7_behavior_2_state_1_continue
	ld c, 7
	call random_modulo
	add a, a
	ld hl, update_boss7_behavior_2_snake_position_table
	ADD_HL_A
	ld a, (hl)
	inc hl
	ld h, (hl)
	ld l, a
	ld de, tile_enemy_work_memory
	ld bc, 16  ; just enough to copy the whole thing
	ldir
	xor a
	ld (boss__7_head_offset), a	
	call update_boss7_draw_phase2_boss_frame
update_boss7_behavior_2_state_1_continue:
	ld a, (boss__state_timer)
	and #1f
	ld (boss__state_timer), a
	ret


