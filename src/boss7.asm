	ld de, boss7_name_y_table + 23
	ld hl, update_boss_behavior_bring_name_up_ix
	ld c, BOSS_PAGE
	call call_hl_in_page_c_8000

	; start tile animations:
; 	ld hl, update_animations_in_vdp_boss7
; 	ld (current_room__animation_fn_ptr), hl
	ret



