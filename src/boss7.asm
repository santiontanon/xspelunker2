	; here:
	; - hl: ptr to the current piece
	; - de: pointer where to draw it
	push hl
		ld hl, update_boss7_snake_piece_drawing_methods
		add a, a
		ADD_HL_A
		ld a, (hl)
		inc hl
		ld h, (hl)
		ld l, a
		jp (hl)
update_boss7_draw_snake_loop_continue:
	pop hl
	inc hl
	jp update_boss7_draw_snake_loop
update_boss7_draw_snake_loop_end:
