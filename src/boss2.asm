update_boss2_behavior:
	; DEBUG:
; 	ld a, 40
; 	ld (boss__x), a
; 	ld a, 17
; 	ld (boss__y), a
; ; 	ld a, 1
; ; 	ld (boss__2_direction), a
; 	ld a, 0
; 	call update_boss2_draw_boss_frame
; 	ret

	ld a, (boss__active)
	or a
	ret z
	ld a, (boss__y)
	cp 17
	jr nz, update_boss2_behavior_continue
	; boss is in the floor, check if it is dead
	ld hl, (boss__hp)
	ld a, h
	or l
	jr nz, update_boss2_behavior_continue
	; boss is dead!
	ld a, 4
	ld (boss__behavior), a
update_boss2_behavior_continue:

	ld a, (boss__behavior)
	or a
	jp z, update_boss2_behavior_0  ; before boss is spawned
	dec a
	jp z, update_boss2_behavior_1  ; walking on floor (right)
	dec a
	jp z, update_boss2_behavior_2  ; walking on floor (left)
	dec a
	jp z, update_boss2_behavior_3  ; flying
	jp update_boss2_behavior_4  ; death


;-----------------------------------------------
update_boss2_behavior_0:
	ld a, (boss__state)
	or a
	jr nz, update_boss2_behavior_0_wait_for_player
update_boss2_behavior_init:
	ld a, (current_world__difficulty)
	ld hl, boss2_difficulty_setting__easy
	or a
	jr z, update_boss2_behavior_init_continue
	ld hl, boss2_difficulty_setting__normal
	dec a
	jr z, update_boss2_behavior_init_continue
	dec a
	ld hl, boss2_difficulty_setting__hard
	jr z, update_boss2_behavior_init_continue
	ld hl, boss2_difficulty_setting__hardest
update_boss2_behavior_init_continue:
	ld de, boss__2_settings
	ld bc, 7
	ldir

	ld a, 49
	ld (boss__x), a
	ld a, 17
	ld (boss__y), a
	ld hl, (boss__2_settings + BOSS_2_HP_OFFSET)
	ld (boss__hp), hl
	ld hl, player_weapon_hitbox_check_boss__boss2_hit
	ld (boss__hit_fn), hl
	xor a
	ld (boss__2_direction), a  ; facing left
	inc a
	ld (boss__state), a
	ret

update_boss2_behavior_0_wait_for_player:
	xor a
	call update_boss2_draw_boss_frame

	ld a, (player_x + 1)  ; tile x
	cp 47
	ret c

	; appear!
	ld a, 1
	ld (boss__behavior), a

	ld a, 1
	call update_boss2_draw_boss_frame
	ld hl, SFX_explosion_low_pitch
	call play_SFX_with_high_priority
	ld hl, draw_room_with_hud
	ld c, TILES_PAGE
	call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at	

	ld hl, boss2_name_initial_sprite_attributes
	ld de, boss2_name_y_table
	call update_boss_behavior_bring_name_down	

	ld a, 2
	call update_boss2_draw_boss_frame
	ld hl, SFX_explosion_low_pitch
	call play_SFX_with_high_priority
	ld hl, draw_room_with_hud
	ld c, TILES_PAGE
	call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at	
	ld b, 50
	call wait_b_halts

	ld a, 3
	call update_boss2_draw_boss_frame
	ld hl, SFX_explosion_low_pitch
	call play_SFX_with_high_priority
	ld hl, draw_room_with_hud
	ld c, TILES_PAGE
	call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at	

	ld b, 200
	call wait_b_halts_skippable
	ld hl, boss2_name_initial_sprite_attributes
	ld de, boss2_name_y_table + 23
	jp update_boss_behavior_bring_name_up


