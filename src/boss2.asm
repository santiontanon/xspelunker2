update_boss2_behavior:
	; DEBUG:
; 	ld a, 40
; 	ld (boss__x), a
; 	ld a, 17
; 	ld (boss__y), a
; ; 	ld a, 1
; ; 	ld (boss__2_direction), a
; 	ld a, 0
; 	call update_boss2_draw_boss_frame
; 	ret

	ld a, (boss__active)
	or a
	ret z
	ld a, (boss__y)
	cp 17
	jr nz, update_boss2_behavior_continue
	; boss is in the floor, check if it is dead
	ld hl, (boss__hp)
	ld a, h
	or l
	jr nz, update_boss2_behavior_continue
	; boss is dead!
	ld a, 4
	ld (boss__behavior), a
update_boss2_behavior_continue:

	ld a, (boss__behavior)
	or a
	jp z, update_boss2_behavior_0  ; before boss is spawned
	dec a
	jp z, update_boss2_behavior_1  ; walking on floor
	dec a
	jp z, update_boss2_behavior_2  ; flying
	dec a
	jp z, update_boss2_behavior_3  ; ???
	jp update_boss2_behavior_4  ; death


;-----------------------------------------------
update_boss2_behavior_0:
	ld a, (boss__state)
	or a
	jr nz, update_boss2_behavior_0_wait_for_player
update_boss2_behavior_init:
	ld a, (current_world__difficulty)
	ld hl, boss2_difficulty_setting__easy
	or a
	jr z, update_boss2_behavior_init_continue
	ld hl, boss2_difficulty_setting__normal
	dec a
	jr z, update_boss2_behavior_init_continue
	dec a
	ld hl, boss2_difficulty_setting__hard
	jr z, update_boss2_behavior_init_continue
	ld hl, boss2_difficulty_setting__hardest
update_boss2_behavior_init_continue:
	ld de, boss__2_settings
	ld bc, 12
	ldir

	ld a, 49
	ld (boss__x), a
	ld a, 17
	ld (boss__y), a
	ld hl, (boss__2_settings + BOSS_2_HP_OFFSET)
	ld (boss__hp), hl
	ld hl, player_weapon_hitbox_check_boss__boss2_hit
	ld (boss__hit_fn), hl
	xor a
	ld (boss__2_direction), a  ; facing left
	inc a
	ld (boss__state), a

	; spawn object for sprite decorations
	call ptr_to_new_sprite_object
	ret nz
	ld (hl), 0  ; ID
	inc hl
	ld (hl), SPRITE_OBJECT_TYPE_BOSS_EXTRAS
	ret

update_boss2_behavior_0_wait_for_player:
	xor a
	call update_boss2_draw_boss_frame

	ld a, (player_x + 1)  ; tile x
	cp 47
	ret c

	; appear!
	ld a, 1
	ld (boss__behavior), a

	ld a, 1
	call update_boss2_draw_boss_frame
	ld hl, SFX_explosion_low_pitch
	call play_SFX_with_high_priority
	ld hl, draw_room_with_hud
	ld c, TILES_PAGE
	call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at	

	ld hl, boss2_name_initial_sprite_attributes
	ld de, boss2_name_y_table
	call update_boss_behavior_bring_name_down	

	ld a, 2
	call update_boss2_draw_boss_frame
	ld hl, SFX_explosion_low_pitch
	call play_SFX_with_high_priority
	ld hl, draw_room_with_hud
	ld c, TILES_PAGE
	call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at	
	ld b, 50
	call wait_b_halts

	ld a, 3
	call update_boss2_draw_boss_frame
	ld hl, SFX_explosion_low_pitch
	call play_SFX_with_high_priority
	ld hl, draw_room_with_hud
	ld c, TILES_PAGE
	call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at	

	ld b, 200
	call wait_b_halts_skippable
	ld hl, boss2_name_initial_sprite_attributes
	ld de, boss2_name_y_table + 23
	jp update_boss_behavior_bring_name_up


;-----------------------------------------------
; walking, facing left
; states:
; - 0: waiting facing left
; - 1: walking forward (left or right)
; - 2: walking backwards
; - 3: dash
; - 4: bullet attack through eyes
; - 5: claw attack
; - 6: sonic boom through mouth
update_boss2_behavior_1:
	ld a, (boss__state)
	or a
	jr z, update_boss2_behavior_1_state_0
	dec a
	jr z, update_boss2_behavior_1_state_1
	dec a
	jp z, update_boss2_behavior_1_state_2
	dec a
	jp z, update_boss2_behavior_1_state_3
	dec a
	jp z, update_boss2_behavior_1_state_4
	dec a
	jp z, update_boss2_behavior_1_state_5
	jp update_boss2_behavior_1_state_6

update_boss2_behavior_1_state_0:
	ld a, 3
	call update_boss2_draw_boss_frame

	ld hl, boss__state_timer
	inc (hl)
	ld a, (boss__2_settings + BOSS_2_WAIT_TIME_OFFSET)
	cp (hl)
	ret nz
	xor a
	ld (boss__state_timer), a
	; DEBUG:
; 	ld a, 6
; 	ld (boss__state), a
; 	ret
	; chance of going to:
	; - 1: walk forward: 3
	; - 2: walk backward: 1
	; - 3: dash: 1
	; - 4, 5, 6: attacks: 1, 1, 1
	call random_a
	and #07
	cp 3
	jr c, update_boss2_behavior_1_state_0_go_walk
; 	; DEBUG:
; 	ld a, 6
; 	ld (boss__state), a
; 	ret
	dec a
	ld (boss__state), a
	ret
update_boss2_behavior_1_state_0_go_walk:
	ld a, 1
	ld (boss__state), a
	ret

update_boss2_behavior_1_state_1:
	; Walk forward:
	; walk frames loop: 4, 5, 6, 7
	ld c, 4  ; frame
	ld a, (boss__2_settings + BOSS_2_WALK_TIME_MASK_OFFSET)
	ld e, a
	ld a, (boss__2_settings + BOSS_2_WALK_TIME_OFFSET)
	ld b, a
	ld hl, boss__state_timer
	ld a, (hl)
	and e
	call z, boss2_move_forward
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
update_boss2_behavior_1_state_1_loop:
	sub b
	jr c, update_boss2_behavior_1_state_1_frame_set
	inc c
	jr update_boss2_behavior_1_state_1_loop
update_boss2_behavior_1_state_1_frame_set:
	ld a, c
	cp 8
	jr nc, update_boss2_behavior_1_state_1_done
	jp update_boss2_draw_boss_frame
update_boss2_behavior_1_state_1_done:
	; chance to keep walking:
	call random_a
	and #03
	jr z, update_boss2_behavior_1_state_1_done_keep_walking
update_boss2_behavior_1_state_2_done:
update_boss2_behavior_1_state_3_done:
	; switch to idle:
	xor a
	ld (boss__state_timer), a
	ld (boss__state), a
	; check if player is left or right, to switch sides:
	ld a, (boss__x)
	add a, 6
	ld c, a
	ld a, (player_x + 1)
	cp c
	jr c, update_boss2_behavior_1_state_1_done_player_left
update_boss2_behavior_1_state_1_done_player_right:
	ld a, (boss__2_direction)
	or a
	jr nz, update_boss2_behavior_1_state_1_done_player_right_done
	ld a, 1
	ld (boss__2_direction), a
	; load 'right' tiles:
	ld hl, boss_2_tiles_right_zx0
	ld c, BOSS_PAGE
	ld (current_room__tileset_ptr), hl
	call setup_game_tiles
update_boss2_behavior_1_state_1_done_player_right_done:
	ld a, 3
	jp update_boss2_draw_boss_frame
update_boss2_behavior_1_state_1_done_player_left:
	ld a, (boss__2_direction)
	or a
	jr z, update_boss2_behavior_1_state_1_done_player_left_done
	xor a
	ld (boss__2_direction), a
	; load 'left' tiles:
	ld hl, boss_2_tiles_zx0
	ld c, BOSS_PAGE
	ld (current_room__tileset_ptr), hl
	call setup_game_tiles
update_boss2_behavior_1_state_1_done_player_left_done:
	ld a, 3
	jp update_boss2_draw_boss_frame
update_boss2_behavior_1_state_1_done_keep_walking:
	xor a
	ld (boss__state_timer), a
	ret

update_boss2_behavior_1_state_2:
	; Walk backward:
	; walk frames loop: 7, 6, 5, 4
	ld c, 7  ; frame
	ld a, (boss__2_settings + BOSS_2_WALK_TIME_MASK_OFFSET)
	ld e, a
	ld a, (boss__2_settings + BOSS_2_WALK_TIME_OFFSET)
	ld b, a
	ld hl, boss__state_timer
	ld a, (hl)
	and e
	call z, boss2_move_backward
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
update_boss2_behavior_1_state_2_loop:
	sub b
	jr c, update_boss2_behavior_1_state_2_frame_set
	dec c
	jr update_boss2_behavior_1_state_2_loop
update_boss2_behavior_1_state_2_frame_set:
	ld a, c
	cp 3
	jp z, update_boss2_behavior_1_state_2_done
	jp update_boss2_draw_boss_frame

update_boss2_behavior_1_state_3:
	; Dash forward:
	; walk frames loop: 4, 5, 6, 7
	ld c, 4  ; frame
	ld a, (boss__2_settings + BOSS_2_DASH_TIME_MASK_OFFSET)
	ld e, a
	ld a, (boss__2_settings + BOSS_2_DASH_TIME_OFFSET)
	ld b, a
	ld hl, boss__state_timer
	ld a, (hl)
	and e
	call z, boss2_move_forward
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
update_boss2_behavior_1_state_3_loop:
	sub b
	jr c, update_boss2_behavior_1_state_3_frame_set
	inc c
	jr update_boss2_behavior_1_state_3_loop
update_boss2_behavior_1_state_3_frame_set:
	ld a, c
	cp 8
	jr nc, update_boss2_behavior_1_state_3_next_step
	jp update_boss2_draw_boss_frame
update_boss2_behavior_1_state_3_next_step:
	; check if the boss reached the wall
	ld a, (boss__x)
	cp 1
	jp z, update_boss2_behavior_1_state_3_done
	cp 50
	jp z, update_boss2_behavior_1_state_3_done
	xor a
	ld (boss__state_timer), a
	ret


update_boss2_behavior_1_state_4:
	; eye attack, fire bullets:
	ld a, 3
	call update_boss2_draw_boss_frame
	ld hl, boss__state_timer
	inc (hl)
	ld a, (hl)
	ld hl, boss__2_settings + BOSS_2_BULLET_FREQUENCY_OFFSET
	and (hl)
	jr nz, update_boss2_behavior_1_state_4_skip_bullet
	ld a, (boss__x)
	add a, 3
	ld c, a
	ld a, (boss__2_direction)
	or a
	jr z, update_boss2_behavior_1_state_4_continue
	; facing right
	ld a, 6
	add a, c
	ld c, a
update_boss2_behavior_1_state_4_continue:
	ld a, (boss__y)
	add a, 2
	ld b, a
	ld ix, #0000	
	call boss_fire_directional_bullet_towards_player_with_random_offset
update_boss2_behavior_1_state_4_skip_bullet:
	ld a, (boss__state_timer)
	ld hl, boss__2_settings + BOSS_2_BULLET_TIME_OFFSET
	cp (hl)
	ret c
	xor a
	ld (boss__state_timer), a
	ld (boss__state), a
	ret	


update_boss2_behavior_1_state_5:
	; claw attack:
	ld a, (boss__2_settings + BOSS_2_ATTACK_TIME_OFFSET)
	ld c, a
	add a, a
	ld d, a
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
	cp c
	jr z, update_boss2_behavior_1_state_5_frame2_start
	jr c, update_boss2_behavior_1_state_5_frame1
	cp d
	jr c, update_boss2_behavior_1_state_5_frame2
	; done
	xor a
	ld (boss__state_timer), a
	ld (boss__state), a
	ret	
update_boss2_behavior_1_state_5_frame1:
	ld a, 8
	jp update_boss2_draw_boss_frame
update_boss2_behavior_1_state_5_frame2_start:
	push af
	push bc
		ld hl, SFX_weapon_swing_slow
		call play_SFX_with_high_priority
	pop bc
	pop af
update_boss2_behavior_1_state_5_frame2:
	sub c
	cp 8
	jr nc, update_boss2_behavior_1_state_5_frame2_continue
	and #02
	call z, boss2_move_forward
update_boss2_behavior_1_state_5_frame2_continue:
	ld a, 9
	jp update_boss2_draw_boss_frame


update_boss2_behavior_1_state_6:
	ld a, (boss__2_settings + BOSS_2_ATTACK_TIME_OFFSET)
	ld c, a
	add a, a
	ld d, a
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
	or a
	jr z, update_boss2_behavior_1_state_6_start
	cp d
	jr z, update_boss2_behavior_1_state_6_done
	cp c 
	jr nz, update_boss2_behavior_1_state_6_continue

	; fire sonic boom:
	call ptr_to_new_sprite_enemy
	jr nz, update_boss2_behavior_1_state_6_continue2
	ld (hl), 0  ; ID
	inc hl
	ld (hl), ENEMY_BULLET_SONIC_BOOM
	inc hl
	ld (hl), 0  ; pixel x
	inc hl
	ld a, (boss__2_direction)
	or a
	jr z, update_boss2_behavior_1_state_6_fire_left
	; fire right:
	ld a, (boss__x)
	add a, 9
	jr update_boss2_behavior_1_state_6_fire_right_continue
update_boss2_behavior_1_state_6_fire_left:
	ld a, (boss__x)
	add a, 2
update_boss2_behavior_1_state_6_fire_right_continue:
	ld (hl), a
	inc hl
	ld (hl), 0  ; pixel y
	inc hl
	ld a, (boss__y)
	add a, 2
	ld (hl), a
	inc hl
	ld a, (boss__2_direction)
	xor #01
	ld (hl), a  ; direction

	ld hl, SFX_sonic_attack
	call play_SFX_with_high_priority
update_boss2_behavior_1_state_6_continue2:
	call update_boss2_spawn_bat
	jr update_boss2_behavior_1_state_6_done
update_boss2_behavior_1_state_6_start:
	call boss2_move_forward
update_boss2_behavior_1_state_6_continue:
	ld a, 10
	jp update_boss2_draw_boss_frame
update_boss2_behavior_1_state_6_done:
	call boss2_move_backward
	xor a
	ld (boss__state_timer), a
	ld (boss__state), a
	ret	


