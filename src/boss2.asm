	call update_boss2_draw_boss_frame
	ld hl, SFX_explosion_low_pitch
	call play_SFX_with_high_priority
	ld hl, draw_room_with_hud
	ld c, TILES_PAGE
	call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at	
	ld b, 50
	call wait_b_halts

	call draw_boss_frame_clear_previous_frame

	ld a, (boss__x)
	add a, 4
	ld e, a
	ld d, 20  ; e, d: x, y coordinates
	ld a, 1  ; boss number (boss 2)
	call boss_spawn_power_stone

	ld hl, draw_room_with_hud
	ld c, TILES_PAGE
	call call_hl_in_page_c_8000

	xor a
	ld (boss__active), a
	ret


