; input:
; - a: frame to draw
update_boss2_draw_boss_frame:
	; ld iyl, a  ; save the frame we are drawing for later
	ld hl, boss2_frame_ptrs
	add a, a
	ADD_HL_A
	ld a, (boss__2_direction)
	or a
	jr z, update_boss2_draw_boss_frame_continue
	ld bc, boss2_frame_ptrs_flipped - boss2_frame_ptrs
	add hl, bc
update_boss2_draw_boss_frame_continue:
	ld a, (hl)
	inc hl
	ld h, (hl)
	ld l, a
	push hl
		ld hl, redraw_flags
		set ROOM_REDRAW_FLAG_BIT, (hl)

		; compute draw pointer:
		ld bc, (boss__x)
		call get_room_tile_ptr
		ex de, hl  ; hl = ptr where the boss is to be drawn
	pop hl
	ld a, (boss__2_direction)
	or a
; 	push de
		push af
			call z, draw_boss_frame
		pop af
		call nz, draw_boss_frame_flipped
; 	pop de  ; preserve the ptr of where to draw for the damage face

	; check if we need to draw an overlay of the "damage face" when the boss is hit:
	ld a, (boss__hit_timer)
	or a
	ret z
	dec a
	ld (boss__hit_timer), a

	; we need to show the boss as being hit:
	; ...
	ret


;-----------------------------------------------
; input:
; - a: tile number that was hit
; - iyh: damage to deal
player_weapon_hitbox_check_boss__boss2_hit:
	; hit the main body:
	ld hl, (boss__hp)
	ld a, h
	or l
	ret z  ; boss HP are already 0
	ld a, iyh
	or a
	jr z, player_weapon_hitbox_check_boss__boss2_hit_continue2
player_weapon_hitbox_check_boss__boss2_hit_loop:
	dec hl
	jr z, player_weapon_hitbox_check_boss__boss2_hit_continue2
	dec a
	jr nz, player_weapon_hitbox_check_boss__boss2_hit_loop
player_weapon_hitbox_check_boss__boss2_hit_continue2:
	ld (boss__hp), hl
