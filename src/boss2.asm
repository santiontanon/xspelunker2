	jr nc, update_boss2_behavior_1_state_3_next_step
	jp update_boss2_draw_boss_frame
update_boss2_behavior_1_state_3_next_step:
	; check if the boss reached the wall
	ld a, (boss__x)
	cp 1
	jp z, update_boss2_behavior_1_state_3_done
