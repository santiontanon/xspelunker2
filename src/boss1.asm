update_boss1_behavior_2_state_0:
update_boss1_behavior_3_state_0:
	ld a, 1
	call update_boss1_draw_boss_frame
	ld hl, boss__state_timer
	inc (hl)
	ld a, (hl)
	cp 32
	ret c
	ld a, 1
	ld (boss__state), a
	xor a
	ld (boss__state_timer), a
	ret

update_boss1_behavior_1_state_1:
	; walk left:
	ld a, 2
	call update_boss1_draw_boss_frame
	ld hl, boss__state_timer
	ld a, (hl)
	inc a
	and #3f  ; #7f
	ld (hl), a
	ld hl, boss__x
	jr nz, update_boss1_behavior_1_state_1_continue
	dec (hl)
	ld c, 3
	call random_modulo
	inc a
	ld (boss__state), a
	ld a, (boss__x)
	cp 10
	jr nc, update_boss1_behavior_1_state_1_continue
	ld a, 4
	ld (boss__state), a
	xor a
	ld (boss__state_timer), a
	ret
update_boss1_behavior_1_state_1_continue:
	ld a, (boss__state_timer)
	cp 32  ; 64
	jr z, update_boss1_behavior_1_state_1_move
	cp 48  ; 96
	ret nz
