; Behavior 1: walk and jump back
; - state 0: idle
; - state 1: walk left
;     after each full step, randomly choose between keep walking, staff/punch attack, left-hand attack
;     after reaching the target position, jump back
; - state 2: staff/punch attack
; - state 3: left-hand attack (lighning)
; - state 4: crouch
; - state 5: jump back
; - state 6: end behavior
update_boss1_behavior_1:
	ld a, (boss__state)
	or a
	jp z, update_boss1_behavior_1_state_0
	dec a
	jp z, update_boss1_behavior_1_state_1
	dec a
	jp z, update_boss1_behavior_1_state_2
	dec a
	jp z, update_boss1_behavior_1_state_3
	dec a
	jp z, update_boss1_behavior_1_state_4
	dec a
	jp z, update_boss1_behavior_1_state_5
	jp update_boss1_behavior_1_state_6

