update_boss1_behavior:
	ld a, (boss__active)
	or a
	ret z
	ld a, (boss__y)
	cp 13
	jr nz, update_boss1_behavior_continue
	; boss is in the floor, check if it is dead
	ld hl, (boss__hp)
	ld a, h
	or l
	jr nz, update_boss1_behavior_continue
	; boss is dead!
	ld a, 4
	ld (boss__behavior), a
update_boss1_behavior_continue:

	ld a, (boss__behavior)
	or a
	jp z, update_boss1_behavior_0  ; boss has not yet appeared, waiting for player to approach, and wake up
	dec a
	jp z, update_boss1_behavior_1  ; walk and jump back
	dec a
	jp z, update_boss1_behavior_2  ; jump attack
	dec a
	jp z, update_boss1_behavior_3  ; bullet barrage
	jp update_boss1_behavior_4  ; death


;-----------------------------------------------
; boss has not yet appeared, waiting for player to approach, and wake up
update_boss1_behavior_0:
	ld a, (player_x + 1)  ; tile x
	cp 15
	ret c

	; player crossed the screen midpoint, trigger boss appearance:
	ld a, (current_world__difficulty)
	ld hl, boss1_difficulty_setting__easy
	or a
	jr z, update_boss1_behavior_0_continue
	ld hl, boss1_difficulty_setting__normal
	dec a
	jr z, update_boss1_behavior_0_continue
	dec a
	ld hl, boss1_difficulty_setting__hard
	jr z, update_boss1_behavior_0_continue
	ld hl, boss1_difficulty_setting__hardest
update_boss1_behavior_0_continue:
	ld de, boss__1_settings
	ld bc, 8
	ldir

	ld a, 24
	ld (boss__x), a
	ld a, 13
	ld (boss__y), a
	ld a, 1
	ld (boss__1_has_staff), a
	ld a, (boss__1_settings + BOSS_1_STAFF_HP_OFFSET)  ; staff hit points
	ld (boss__1_staff_hp), a
	ld hl, (boss__1_settings + BOSS_1_HP_OFFSET)
	ld (boss__hp), hl
	ld hl, player_weapon_hitbox_check_boss__boss1_hit
	ld (boss__hit_fn), hl
	xor a
	ld (boss__hit_timer), a

	; set the clear box:
	ld hl, current_room__tile_map + 13*32 + 24
	ld (boss__clear_bbox_1), hl
	ld hl, #0906
	ld (boss__clear_bbox_1 + 2), hl
	ld bc, #0106
	ld de, current_room__tile_map + 21*32 + 24
update_boss1_behavior_0_raise_loop:
	ld hl, BOSS1_NAMETABLE_STONE
	push bc
		push de
			call draw_boss_frame_part
			xor a
			call boss1_draw_dust
			ld hl, draw_room_with_hud
			ld c, TILES_PAGE
			call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at
			ld hl, SFX_explosion_low_pitch
			call play_SFX_with_high_priority
			ld b, 10
			call wait_b_halts

			ld a, 1
			call boss1_draw_dust
			ld hl, draw_room_with_hud
			ld c, TILES_PAGE
			call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at
			ld b, 10
			call wait_b_halts
			push de
			push hl
			push bc
				call draw_boss_frame_clear_previous_frame_1
			pop bc
			pop hl
			pop de			
		pop hl
		ld bc, -32
		add hl, bc
		ex de, hl
	pop bc
	inc b
	ld a, b
	cp 9 + 1
	jp nz, update_boss1_behavior_0_raise_loop

	ld bc, #0906
	ld de, current_room__tile_map + 13*32 + 24
	ld hl, BOSS1_NAMETABLE_STONE
	call draw_boss_frame_part
	ld hl, draw_room_with_hud
	ld c, TILES_PAGE
	call call_hl_in_page_c_8000

	; Bring boss name (using sprites)
	ld hl, boss1_name_initial_sprite_attributes
	ld de, boss1_name_y_table
	call update_boss_behavior_bring_name_down
	call update_boss1_behavior_flash_stone_to_blue
	call update_boss1_draw_boss_frame_1
	ld b, 100
	call wait_b_halts_skippable
	; Remove boss name (using sprites)
	ld hl, boss1_name_initial_sprite_attributes
	ld de, boss1_name_y_table + 23
	call update_boss_behavior_bring_name_up

update_boss1_behavior_0_choose_behavior:
	ld c, 3
	call random_modulo
	inc a
	; ld a, 1  ; DEBUG: hardcode behavior
	ld (boss__behavior), a  ; 1, 2, or 3
	xor a
	ld (boss__state), a
	ld (boss__state_timer), a
	inc a
	ld (boss__active), a
	ret


;-----------------------------------------------
update_boss1_behavior_flash_stone_to_blue:
	; Turn boss to blue:
	ld b, 6
update_boss1_behavior_0_waking_loop:
	push bc
		call update_boss1_draw_boss_frame_1
		ld hl, draw_room_with_hud
		ld c, TILES_PAGE
		call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at
		ld b, 12
		call wait_b_halts

		ld de, current_room__tile_map + 13*32 + 24
		ld hl, boss1_frame_0_stone
		call draw_boss_frame_1

		ld hl, draw_room_with_hud
		ld c, TILES_PAGE
		call call_hl_in_page_c_8000
		ld b, 12
		call wait_b_halts
	pop bc
	djnz update_boss1_behavior_0_waking_loop
	ret


;-----------------------------------------------
; Behavior 1: walk and jump back
; - state 0: idle
; - state 1: walk left
;     after each full step, randomly choose between keep walking, staff/punch attack, left-hand attack
;     after reaching the target position, jump back
; - state 2: staff/punch attack
; - state 3: left-hand attack (whirlwind)
; - state 4: crouch
; - state 5: jump back
; - state 6: end behavior
update_boss1_behavior_1:
	ld a, (boss__state)
	cp 2
	call nz, boss1_check_if_staff_destroyed  ; check if staff destroyed any time the staff is not being used

	ld a, (boss__state)
	or a
	jp z, update_boss1_behavior_1_state_0
	dec a
	jp z, update_boss1_behavior_1_state_1
	dec a
	jp z, update_boss1_behavior_1_state_2
	dec a
	jp z, update_boss1_behavior_1_state_3
	dec a
	jp z, update_boss1_behavior_1_state_4
	dec a
	jp z, update_boss1_behavior_1_state_5
	jp update_boss1_behavior_1_state_6

update_boss1_behavior_1_state_0:
update_boss1_behavior_2_state_0:
update_boss1_behavior_3_state_0:
	ld a, 1
	call update_boss1_draw_boss_frame
	ld hl, boss__state_timer
	inc (hl)
	ld a, (hl)
	ld hl, boss__1_settings + BOSS_1_PAUSE_TIME_OFFSET
	cp (hl)
	ret c
	ld a, 1
	ld (boss__state), a
	xor a
	ld (boss__state_timer), a
	ret

update_boss1_behavior_1_state_1:
	; walk left:
	ld a, 2
	call update_boss1_draw_boss_frame
	ld a, (boss__1_settings + BOSS_1_WALK_TIME_OFFSET)
	ld c, a
	add a, a
	ld b, a  ; b = BOSS_1_WALK_TIME_OFFSET * 2 
	add a, c
	ld e, a  ; e = BOSS_1_WALK_TIME_OFFSET * 3
	add a, c
	dec a
	ld c, a  ; c = BOSS_1_WALK_TIME_OFFSET * 4
	ld hl, boss__state_timer
	ld a, (hl)
	inc a
	cp c
	jr c, update_boss1_behavior_1_state_1_continue1
	sub c
update_boss1_behavior_1_state_1_continue1:
	ld (hl), a
	ld hl, boss__x
	jr nz, update_boss1_behavior_1_state_1_continue2
	dec (hl)
	ld c, 3
	call random_modulo
	inc a
	ld (boss__state), a
	ld a, (boss__x)
	cp 10
	jr nc, update_boss1_behavior_1_state_1_continue2
	ld a, 4
	ld (boss__state), a
	xor a
	ld (boss__state_timer), a
	ret
update_boss1_behavior_1_state_1_continue2:
	ld a, (boss__state_timer)
	cp b  ; b = BOSS_1_WALK_TIME_OFFSET * 2 
	jr z, update_boss1_behavior_1_state_1_move
	cp e  ; e = BOSS_1_WALK_TIME_OFFSET * 3
	ret nz
update_boss1_behavior_1_state_1_move:
	ld hl, boss__x
	dec (hl)
	ret

update_boss1_behavior_1_state_2:
	; staff attack (lightning) or punch attack
	ld a, (boss__1_has_staff)
	or a
	jr nz, update_boss1_behavior_1_state_2_staff
	; staff is destroyed, do punch attack instead:
	ld a, 7
	jr update_boss1_behavior_1_state_2_continue

update_boss1_behavior_1_state_2_staff:
	ld a, (boss__state_timer)
	cp 8
	call z, update_boss1_spawn_lightning

	ld a, 5
update_boss1_behavior_1_state_2_continue:
	call update_boss1_draw_boss_frame
	ld hl, boss__state_timer
	inc (hl)
	ld a, (hl)
	ld hl, boss__1_settings + BOSS_1_ATTACK_TIME_OFFSET
	cp (hl)
	ret nz
	xor a
	ld (boss__state_timer), a
	inc a
	ld (boss__state), a
	ret

update_boss1_behavior_1_state_3:
	; left hand attack (whirlwind)
	ld a, 6
	call update_boss1_draw_boss_frame
	ld hl, boss__state_timer
	inc (hl)
	ld a, (hl)
	cp 8
	jr nz, update_boss1_behavior_1_state_3_skip_bullet
	ld a, (boss__x)
	ld c, a
	ld a, (boss__y)
	add a, 3
	ld b, a
	ld ix, #0000	
	call boss_fire_directional_bullet_towards_player
	ld (ix + ROOM_OBJECT_STRUCT_TYPE), ENEMY_BULLET_WHIRLWIND
	ld (ix + ROOM_OBJECT_STRUCT_BULLET_STATE), 0
update_boss1_behavior_1_state_3_skip_bullet:
	ld a, (boss__state_timer)
	ld hl, boss__1_settings + BOSS_1_ATTACK_TIME_OFFSET
	cp (hl)
	ret nz
	xor a
	ld (boss__state_timer), a
	inc a
	ld (boss__state), a
	ret

update_boss1_behavior_1_state_4:
update_boss1_behavior_2_state_1:
update_boss1_behavior_2_state_3:
update_boss1_behavior_2_state_5:
update_boss1_behavior_2_state_7:
	ld a, 3
	call update_boss1_draw_boss_frame
	ld hl, boss__state_timer
	inc (hl)
	ld a, (hl)
	ld hl, boss__1_settings + BOSS_1_PAUSE_TIME_OFFSET
	cp (hl)
	ret nz
	xor a
	ld (boss__state_timer), a
	ld hl, boss__state
	inc (hl)
	ret

update_boss1_behavior_1_state_5:
	ld a, 4
	call update_boss1_draw_boss_frame
	ld hl, boss__state_timer
	inc (hl)
	ld a, (hl)
	cp 24
	jr z, update_boss1_behavior_1_state_5_jumping
	jr nc, update_boss1_behavior_1_state_5_falling
update_boss1_behavior_1_state_5_jumping:
	; jumping:
	ld a, (boss__state_timer)
	ld hl, boss__y
	dec (hl)
	ld a, (boss__state_timer)
	cp 24
	ret nz
	ld a, 24
	ld (boss__x), a
	ret
update_boss1_behavior_1_state_5_falling:
	cp 24 + 12
	jr nc, update_boss1_behavior_1_state_5_land
	; falling:
	ld a, (boss__state_timer)
	ld hl, boss__y
	inc (hl)
	inc (hl)
	ret
update_boss1_behavior_1_state_5_land:
	xor a
	ld (boss__state_timer), a
	ld a, 6
	ld (boss__state), a
	ld a, 13
	ld (boss__y), a	
	; spawn dust:
	ld b, 20
	ld a, (boss__x)
	inc a
	ld c, a
	call spawn_4tile_appart_dust
	ld hl, SFX_explosion
	jp play_SFX_with_high_priority

update_boss1_behavior_1_state_6:
	ld a, 3
	call update_boss1_draw_boss_frame
	ld hl, boss__state_timer
	inc (hl)
	ld a, (hl)
	ld hl, boss__1_settings + BOSS_1_PAUSE_TIME_OFFSET
	cp (hl)
	ret c
	jp update_boss1_behavior_0_choose_behavior


;-----------------------------------------------
