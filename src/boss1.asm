update_boss1_behavior_4:
	; turn boss to stone:
	ld b, 6
update_boss1_behavior_4_loop_1:
	push bc
		call update_boss1_draw_boss_frame_1
		ld hl, draw_room_with_hud
		ld c, TILES_PAGE
		call call_hl_in_page_c_8000  ; just so that we do not lose the page we are at
