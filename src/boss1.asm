	ld a, (boss__1_has_staff)
	or a
	ret z  ; boss already does not have a staff, nothing to do
	ld a, (boss__1_staff_hp)
	or a
	ret nz
	ld (boss__1_has_staff), a

	ld bc, (boss__x)
	inc b
	inc b
	push bc
		ld e, SPRITE_OBJECT_TYPE_EXPLOSION
		call spawn_explosion
	pop bc
	inc b
	inc b
	inc b
	ld e, SPRITE_OBJECT_TYPE_EXPLOSION
	jp spawn_explosion

