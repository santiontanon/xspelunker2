; The difference between the "boss4" draw routines and those of other bosses
; is that the tiles smaller than a certain threshold need to be updated
; depending on where the tiles of a given xibalba lord have been uploaded
; to the VDP (as there are 2 lords at the same time, and we do not know
; in where the tiles of each go)
; input:
; - de: ptr to draw to
; - hl: ptr to frame struct
draw_boss4_frame_1:
	push hl
	push de
		ld hl, draw_boss_frame_clear_previous_frame_1
		ld c, BOSS_PAGE
		call call_hl_in_page_c_8000
	pop de
	pop hl
draw_boss4_frame_1_without_clearing:
	push de
		call draw_boss4_frame_internal

		; set clear bbox:
		ld c, (hl)
		inc hl
		ld b, (hl)  ; bc is the offset wrt original draw pointer
		inc hl
		ld de, boss__clear_bbox_1 + 2
		push bc
			ldi
			ldi
		pop bc
	pop hl
	add hl, bc
	ld (boss__clear_bbox_1), hl
	ret


