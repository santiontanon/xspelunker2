update_boss4_behavior_1:
	ld a, (boss__state)
	or a
	jr z, update_boss4_behavior_1_state_0  ; (0) load tileset
	cp 10
	jr c, update_boss4_behavior_1_state_1  ; (1 - 9) hands coming out
	jp z, update_boss4_behavior_1_state_2  ; (10) boss rises from the floor
	; ...
	ret

update_boss4_behavior_1_state_0:
	; patch 'rise' tileset:
	ld hl, boss4_tiles_rise_zx0
	ld de, buffer_4096
	ld c, BOSS_GFX_PAGE
	call dzx0_from_page_c

	ld de, CHRTBL2 + 3*16*8
	ld bc, 14*8
	call upload_tile_patch_to_all_banks

	; initialize all the boss variables:
	ld a, (current_world__difficulty)
	ld hl, boss4_difficulty_setting__easy
	or a
	jr z, update_boss4_behavior_1_state_0_continue
	ld hl, boss4_difficulty_setting__normal
	dec a
	jr z, update_boss4_behavior_1_state_0_continue
	dec a
	ld hl, boss4_difficulty_setting__hard
	jr z, update_boss4_behavior_1_state_0_continue
	ld hl, boss4_difficulty_setting__hardest
update_boss4_behavior_1_state_0_continue:
	ld de, boss__4_settings
	ld bc, boss4_difficulty_setting__normal - boss4_difficulty_setting__easy
	ldir

	ld a, 19
	ld (boss__x), a
	ld a, 34
	ld (boss__x), a
	ld a, 14
	ld (boss__y), a
	ld (boss__y2), a
	ld hl, (boss__4_settings + BOSS_4_HP_OFFSET)
	ld (boss__hp), hl
	ld hl, player_weapon_hitbox_check_boss__boss4_hit
	ld (boss__hit_fn), hl
	ld a, BOSS_4_PAGE
	ld (boss__hit_fn_page), a
	xor a
	ld (boss__hit_timer), a

	; set the clear box:
	ld hl, current_room__tile_map
	ld (boss__clear_bbox_1), hl
	ld (boss__clear_bbox_2), hl
	ld hl, #0101
	ld (boss__clear_bbox_1 + 2), hl
	ld (boss__clear_bbox_2 + 2), hl

	ld a, 1
	ld (boss__state), a
	xor a
	ld (boss__state_timer), a
	ret

update_boss4_behavior_1_state_1:
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
	or a
	jr z, update_boss4_behavior_1_state_1_draw
	cp 16
	jr z, update_boss4_behavior_1_state_1_next
	ret
update_boss4_behavior_1_state_1_next:
	ld hl, boss__state
	inc (hl)
	xor a
	ld (boss__state_timer), a
	ret
update_boss4_behavior_1_state_1_draw:
	ld a, (boss__state)
	dec a
	add a, a
	ld hl, update_boss4_behavior_1_state_1_table
	ADD_HL_A
	ld a, (hl)
	inc hl
	ld h, (hl)
	ld l, a
	or h
	jr z, update_boss4_behavior_1_state_1_draw_empty
	ld de, current_room__tile_map + 20*64 + 19
	push hl
		call draw_boss4_frame_lord1
	pop hl
	ld de, current_room__tile_map + 20*64 + 35
	call draw_boss4_frame_lord2
update_boss4_behavior_1_state_1_draw_continue:
	ld hl, SFX_explosion_low_pitch
	call play_SFX_with_high_priority

	ld hl, redraw_flags
	set ROOM_REDRAW_FLAG_BIT, (hl)
	ret
update_boss4_behavior_1_state_1_draw_empty:
	ld hl, draw_boss_frame_clear_previous_frame_1
	ld c, BOSS_PAGE
	call call_hl_in_page_c_8000
	ld hl, draw_boss_frame_clear_previous_frame_2
	ld c, BOSS_PAGE
	call call_hl_in_page_c_8000
	jr update_boss4_behavior_1_state_1_draw_continue

update_boss4_behavior_1_state_2:
	ld a, (boss__state_timer)
	or a
	jr nz, update_boss4_behavior_1_state_2_continue
	call update_boss4_load_xibalba_lord_tile_patches
update_boss4_behavior_1_state_2_continue:
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)

	; draw the lord:
	and #0f
	jr nz, update_boss4_behavior_1_state_2_continue2

	; draw lord1 coming up: y coordinate should be 22 - state_timer/16
	ld a, (hl)
	rrca
	rrca
	rrca
	rrca
	and #0f  ; state_timer/16
	sub 22
	neg
	ld l, a
	ld h, 0
	add hl, hl
	add hl, hl
	add hl, hl
	add hl, hl
	add hl, hl
	add hl, hl
	ld bc, current_room__tile_map + 19
	add hl, bc
	ex de, hl
	push de
		ld hl, boss4_frame_lord1_idle_right
		call draw_boss4_frame_lord1
	pop hl
	ld bc, 15
	add hl, bc
	ex de, hl
	ld hl, boss4_frame_lord1_idle_left
	call draw_boss4_frame_lord2
	ld hl, redraw_flags
	set ROOM_REDRAW_FLAG_BIT, (hl)	

update_boss4_behavior_1_state_2_continue2:
	ld a, (boss__state_timer)
