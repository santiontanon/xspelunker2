update_boss4_behavior_2_move_to_destination:
	ld a, (boss__4_settings + BOSS_4_MOVE_SPEED)
	ld c, a
	ld a, (ix + 1)
	and c
	ret nz
	; stomp?
	ld a, (player_x + 1)
	dec a
	cp (ix + 2)
	jr nz, update_boss4_behavior_2_move_to_destination_no_stomp
	ld a, (player_y + 1)
	sub 3
	cp (ix + 3)
	jr c, update_boss4_behavior_2_move_to_destination_no_stomp
	; chance of stomping!
	ld a, (boss__4_settings + BOSS_4_STOMP_MASK)
	ld c, a
	call random_a
	and c
	jr nz, update_boss4_behavior_2_move_to_destination_no_stomp
	; stomp!
	ld (ix + 0), 11  ; stomp state
	ld (ix + 1), 0
	or 1  ; return nz
	ret
update_boss4_behavior_2_move_to_destination_no_stomp:
	; move to destination:
	ld a, 1
	ld (boss__4_redraw), a
	ld a, (ix + 2)  ; x
	cp (iy + 1)  ; target x
	jr z, update_boss4_behavior_2_state_1_destination_check
	jr c, update_boss4_behavior_2_state_1_move_right
	; move left:
	dec (ix + 2)
	jr update_boss4_behavior_2_state_1_continue_x
