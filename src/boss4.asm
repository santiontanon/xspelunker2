;-----------------------------------------------
; See 'draw_boss4_frame_lord1' for why do we have a boss4-specific routine.
; input:
; - de: ptr to draw to
; - hl: ptr to frame struct
; - iyl: offset at which the tiles for the specific lord we are drawing start
; output:
; - hl: ptr to the boss__clear_bbox info
draw_boss4_frame_internal:
	ld a, (hl)  ; number of frame parts
	inc hl
	or a
	ret z
	ld b, a
draw_boss4_frame_loop:
	push bc
		push de
			ld c, (hl)  ; x offset
			inc hl
			; sign extend c to bc:
			ld a, c
		    rlca
		    sbc a
		    ld  b, a	
			ex de, hl
				add hl, bc  ; add x offset
			ex de, hl
			ld a, (current_room__width)
			ld c, a
			ld a, (hl)  ; y offset
			inc hl
			or a
			jr z, draw_boss4_frame_loop_continue
			ex de, hl
draw_boss4_frame_loop_y_offset_loop:
				add hl, bc
				dec a
				jr nz, draw_boss4_frame_loop_y_offset_loop
			ex de, hl
draw_boss4_frame_loop_continue:
			ld c, (hl)  ; width
			inc hl
			ld b, (hl)  ; height
			inc hl
			push hl
				ld a, (hl)
				inc hl
				ld h, (hl)
				ld l, a
				call draw_boss4_frame_part
			pop hl
		pop de
		inc hl
		inc hl
	pop bc
	djnz draw_boss4_frame_loop
	ret



;-----------------------------------------------
; input:
; - hl: frame ptr
; - de: destination ptr
; - c, b: width, height
; - iyl: offset at which the tiles for the specific lord we are drawing start
draw_boss4_frame_part:
draw_boss4_frame_part_loop_y:
	push bc
		push de
			; if "de" < current_room__tile_map, skip row  ->  draw_boss_frame_part_loop_y_skip
			ex de, hl
			push bc
			push hl
				ld bc, current_room__tile_map
				or a  ; clear carry flag
				sbc hl, bc
				jr c, draw_boss4_frame_part_loop_y_skip
				add hl, bc
				ld bc, boss__room_bg_buffer
				or a  ; clear carry flag
				sbc hl, bc
				jr nc, draw_boss4_frame_part_loop_y_done
			pop hl
			pop bc
			ex de, hl

			ld b, c
draw_boss4_frame_part_loop_x:
			ld a, (de)
			cp 249  ; boss should be drawn behind any tile with index 249 or higher
			jr nc, draw_boss4_frame_part_loop_x_skip
			ld a, (hl)
			or a
			jr z, draw_boss4_frame_part_loop_x_skip
			cp 24 + 68  ; first tile of the common tileset for the xibalba lords
			jr nc, draw_boss4_frame_part_loop_x_continue
			add a, iyl
draw_boss4_frame_part_loop_x_continue:
			ld (de), a
draw_boss4_frame_part_loop_x_skip:
			inc hl
			inc de
			djnz draw_boss4_frame_part_loop_x
draw_boss4_frame_part_loop_y_skip2:
		pop de
		ex de, hl
		ld a, (current_room__width)
		; ld b, 0
		ld c, a
		add hl, bc
		ex de, hl
	pop bc
	djnz draw_boss4_frame_part_loop_y
	ret
draw_boss4_frame_part_loop_y_skip:
			; advance 'hl':
			pop hl
			pop bc
			ex de, hl
			ld b, 0
			add hl, bc
			jr draw_boss4_frame_part_loop_y_skip2
draw_boss4_frame_part_loop_y_done:
			pop hl
			pop bc
		pop de
	pop bc
	ret


