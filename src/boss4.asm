;-----------------------------------------------
; boss is dead:
; - state 0: spawn explosions periodically (non-drop-spawning)
; - state 1: spawn ghosts (explosions still spawn)
; - state 2: bosses bodies disappear, and ghosts remain there
; - state 3: ghosts fly up
; - state 4: reward spawns
update_boss4_behavior_3:
	ld a, (boss__state)
	or a
	jr z, update_boss4_behavior_3_state_0
	dec a
	jr z, update_boss4_behavior_3_state_1
	dec a
	jr z, update_boss4_behavior_3_state_2
	dec a
	jp z, update_boss4_behavior_3_state_3
	dec a
	jp z, update_boss4_behavior_3_state_4
	; if we are here, it's that death sequence is over
	ret

update_boss4_behavior_3_state_0:
	ld hl, boss__state_timer
	ld a, (hl)
	cp 80
	jr z, update_boss4_behavior_3_state_0_done
	inc (hl)
	and #03
	ret nz

	ld de, (boss__x)
	ld c, 5
	call random_modulo
	add a, e
	dec a
	ld e, a  ; explosion x
	ld c, 7
	call random_modulo
	neg
	add a, d
	ld b, a
	ld c, e
	call spawn_explosion	

	ld de, (boss__x2)
	ld c, 5
	call random_modulo
	add a, e
	dec a
	ld e, a  ; explosion x
	ld c, 7
	call random_modulo
	neg
	add a, d
	ld b, a
	ld c, e
	jp spawn_explosion
update_boss4_behavior_3_state_0_done:
	ld hl, boss__state
	inc (hl)
	xor a
	ld (boss__state_timer), a
	ret


update_boss4_behavior_3_state_1:
	ld hl, boss__state_timer
	ld a, (hl)
	or a
	jr nz, 	update_boss4_behavior_3_state_0
	; spawn ghosts:
	ld bc, (boss__x)
	inc c
	dec b
	dec b
	dec b
	dec b
	call spawn_xibalba_lord_ghost
	ld bc, (boss__x2)
	inc c
	dec b
	dec b
	dec b
	dec b
	call spawn_xibalba_lord_ghost
	jr update_boss4_behavior_3_state_0


update_boss4_behavior_3_state_2:
	; wait:
	ld hl, boss__state_timer
	ld a, (hl)
	inc (hl)
	or a
	jr nz, update_boss4_behavior_3_state_2_continue
	; remove the boss:
	ld hl, draw_boss_frame_clear_previous_frame_1
	ld c, BOSS_PAGE
	call call_hl_in_page_c_8000
	ld hl, draw_boss_frame_clear_previous_frame_2
	ld c, BOSS_PAGE
	call call_hl_in_page_c_8000
	ld hl, redraw_flags
	set ROOM_REDRAW_FLAG_BIT, (hl)
update_boss4_behavior_3_state_2_continue:
	ld a, (boss__state_timer)
	cp 80
	ret nz
	ld hl, boss__state
	inc (hl)
	xor a
	ld (boss__state_timer), a
	ret

update_boss4_behavior_3_state_3:
	; ghosts go down:
	ld ix, current_room__sprite_objects + ROOM_OBJECT_STRUCT_SIZE  ; first ghost (it's the second sprite object, as the first is the boss extras)
	ld a, (ix + ROOM_OBJECT_STRUCT_TILE_Y)
	cp 24
	ld c, 23  ; target x
	call nz, update_boss4_behavior_0_lower_ghost
	ld ix, current_room__sprite_objects + ROOM_OBJECT_STRUCT_SIZE*2  ; second ghost (it's the third sprite object, as the first is the boss extras)
	ld a, (ix + ROOM_OBJECT_STRUCT_TILE_Y)
	cp 24
	ld c, 39  ; target x
	call nz, update_boss4_behavior_0_lower_ghost
	ld a, (current_room__sprite_objects + ROOM_OBJECT_STRUCT_SIZE + ROOM_OBJECT_STRUCT_TILE_Y)
	cp 24
	ret nz
	ld a, (current_room__sprite_objects + ROOM_OBJECT_STRUCT_SIZE*2 + ROOM_OBJECT_STRUCT_TILE_Y)
	cp 24
	ret nz
	; both ghosts down, remove them:
	ld a, #ff
	ld (current_room__sprite_objects + ROOM_OBJECT_STRUCT_SIZE), a
	ld (current_room__sprite_objects + ROOM_OBJECT_STRUCT_SIZE*2), a
	ld hl, boss__state
	inc (hl)
	xor a
	ld (boss__state_timer), a

update_boss4_behavior_3_state_4:
	; mark the boss as defeated and spawn rewards:
	xor a
	ld (boss__active), a

	; mark for stats:
	ld a, (boss__4_first_lord)
	add a, 3
	ld b, a
	ld c, BOSS_PAGE
	ld hl, add_killed_boss_to_stats
	call call_hl_in_page_c_8000

	ld a, (boss__4_second_lord)
	add a, 3
	ld b, a
	ld c, BOSS_PAGE
	ld hl, add_killed_boss_to_stats
	call call_hl_in_page_c_8000

	ld hl, boss__state
	inc (hl)

	ld hl, redraw_flags
	set ROOM_REDRAW_FLAG_BIT, (hl)	

	; check if the lord pairs were a proper pair:
	ld a, (boss__4_first_lord)
	dec a
	and #fe
	ld c, a
	ld a, (boss__4_second_lord)
	dec a
	and #fe
	cp c
	jr nz, update_boss4_behavior_3_state_4_not_pair
	; they are a pair, spawn a different reward:
	or a  ; hun-came / vucub-came
	jr z, update_boss4_behavior_3_state_4_spawn_golden_key
	jr update_boss4_behavior_3_state_4_spawn_skull_charm
update_boss4_behavior_3_state_4_not_pair:
	ld b, 3  ; boss number (boss 4)
	ld de, 31 + 21*256  ; - e, d: x, y coordinates to spawn the stone
	ld hl, boss_spawn_power_stone_b
	ld c, BOSS_PAGE
	jp call_hl_in_page_c_8000

update_boss4_behavior_3_state_4_spawn_golden_key:
	ld b, TAG_GOLDEN_KEY
	ld hl, buffer_4096 + 62 * 64  ; golden key
	jr update_boss4_behavior_3_state_4_spawn_golden_key_entry_point
update_boss4_behavior_3_state_4_spawn_skull_charm:
	ld b, TAG_SKULL_CHARM
	ld hl, buffer_4096 + 63 * 64  ; skull charm
update_boss4_behavior_3_state_4_spawn_golden_key_entry_point:
	push hl
	push bc
		ld hl, ptr_to_new_tile_object
		ld c, TILES_PAGE
		call call_hl_in_page_c_8000
		push hl
		pop iy
	pop bc
	pop hl
	ld (iy + ROOM_TILE_OBJECT_STRUCT_ID), 0
	ld (iy + ROOM_TILE_OBJECT_STRUCT_TYPE), b  ; type
	ld (iy + ROOM_TILE_OBJECT_STRUCT_X), 31  ; x
	ld (iy + ROOM_TILE_OBJECT_STRUCT_Y), 21  ; y
	ld (iy + ROOM_TILE_OBJECT_STRUCT_STATE), 0  ; state (hitpoints)

	; set which object gfx to up load vdp:
	ld (item_object_to_upload_to_vdp), hl
	call state_play_upload_object_tiles_to_vdp_if_necessary

	ld hl, SFX_secret
	call play_SFX_with_high_priority

	; refresh the current tile objects:
	ld hl, room_undraw_tile_objects
	ld c, TILES_PAGE
	call call_hl_in_page_c_8000
	ld hl, room_render_tile_objects
	ld c, TILES_PAGE
	jp call_hl_in_page_c_8000	


