	jr nz, update_boss4_behavior_2_internal_no_mouth
	ld a, 1
	ld (boss__4_redraw), a
	ld a, (iy + 3)  ; mouth_state
	xor #01
	ld (iy + 3), a
	jr nz, update_boss4_behavior_2_internal_no_mouth
