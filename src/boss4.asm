; input:
; - ix: ptr to state, state_timer, x, y
; - iy: ptr to lord frame, target x, target y, mouth state
; output:
; - z: redraw lord
; - nz: do not redraw
; states:
; - 0: choose what to do next
; - 1: go to player left (then 12)
; - 2: go to player right (then 13)
; - 3: go left-most (1-tile over the high ground): (1, 13) (then 14)
; - 4: go right-most (1-tile over the high ground): (59, 13) (then 16)
; - 5: 1-tile over the ground hover left-to-right (state 5 then 18)
; - 6: 1-tile over the ground hover right-to-left (state 6 then 19)
; - 7: go to a center position (center-left if lord1, and center-right if lord2)
; - 8: wait for a couple of seconds
; - 9: lord-specific attack
; - 10: joint-attack (only if there is a compatible pair)
; ---
; - 11: stomp-down (then go to 8)
; - 12: move right
; - 13: move left
; - 14: wait for 100 frames -> go to 15
; - 15: move right to (10, 13)
; - 16: wait for 100 frames -> go to 17
; - 17: move right to (50, 13)
; - 18: (from 5)
; - 19: (from 6)
; - 20: stomp 1: wait
; - 21: stomp 2: drop and then go to 8
; - 22: joint-attack: get to position
; - 23: joint-attack: wait for both to arrive
; - 24: joint-attack: barrage
