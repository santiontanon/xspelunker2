update_boss4_behavior:
	; check if we need to draw an overlay of the "damage face" when the boss is hit:
	ld hl, boss__hit_timer
	ld a, (hl)
	or a
	jr z, update_boss4_behavior_continue
	dec (hl)
update_boss4_behavior_continue:
	ld a, (boss__active)
	or a
	ret z

	; check if it is dead:
	ld hl, (boss__hp)
	ld a, h
	or l
	jr nz, update_boss4_behavior_continue2
	; boss is dead!
	ld a, 2
	ld (boss__behavior), a
update_boss4_behavior_continue2:
	ld a, (boss__behavior)
	or a
	jp z, update_boss4_behavior_0  ; boss has not yet appeared, waiting for player to wake two ghosts
	dec a
	jp z, update_boss4_behavior_1  ; boss rises from the floor
	dec a
	jp z, update_boss4_behavior_2  ; boss is active
; 	dec a
	jp update_boss4_behavior_3  ; death


;-----------------------------------------------
update_boss4_behavior_0:
	ld a, (boss__4_second_lord)
	or a
	ret z

	; two lords awakened, boss appearing sequence starts!
	; ghosts go down:
	ld ix, current_room__sprite_objects
	ld a, (ix + ROOM_OBJECT_STRUCT_TILE_Y)
	cp 24
	call nz, update_boss4_behavior_0_lower_ghost
	ld ix, current_room__sprite_objects + ROOM_OBJECT_STRUCT_SIZE
	ld a, (ix + ROOM_OBJECT_STRUCT_TILE_Y)
	cp 24
	call nz, update_boss4_behavior_0_lower_ghost
	ld a, (current_room__sprite_objects + ROOM_OBJECT_STRUCT_TILE_Y)
	cp 24
	ret nz
	ld a, (current_room__sprite_objects + ROOM_OBJECT_STRUCT_SIZE + ROOM_OBJECT_STRUCT_TILE_Y)
	cp 24
	ret nz

	; both ghosts down, remove them:
	ld a, #ff
	ld (current_room__sprite_objects), a
	ld (current_room__sprite_objects + ROOM_OBJECT_STRUCT_SIZE), a

	; Bring boss name (using sprites)
	ld ix, boss4_name_initial_sprite_attributes
	ld de, boss4_name_y_table
	ld hl, update_boss_behavior_bring_name_down_ix
	ld c, BOSS_PAGE
	call call_hl_in_page_c_8000
	ld b, 100
	call wait_b_halts_skippable
	; Remove boss name (using sprites)
	ld ix, boss4_name_initial_sprite_attributes
	ld de, boss4_name_y_table + 23
	ld hl, update_boss_behavior_bring_name_up_ix
	ld c, BOSS_PAGE
	call call_hl_in_page_c_8000

	; boss starts rising from the ground!
	ld a, 1
	ld (boss__behavior), a
	ret


update_boss4_behavior_0_lower_ghost:
	ld a, (ix + ROOM_OBJECT_STRUCT_PIXEL_Y)
	ld b, (ix + ROOM_OBJECT_STRUCT_TILE_Y)
	inc a
	cp 8
	jr nz, update_boss4_behavior_0_continue
	xor a
	inc b
update_boss4_behavior_0_continue:
	ld (ix + ROOM_OBJECT_STRUCT_PIXEL_Y), a
	ld (ix + ROOM_OBJECT_STRUCT_TILE_Y), b
	ret


